	SELECT TRIM(MB01) 产品品号,B.MB002 产品名称,B.MB003 产品规格,B.MB109  产品关闭,TRIM(材料品号) AS [材料品号],材料品名, 材料规格,FORMAT(物料用量, '0.########') AS 物料用量,D.MB109  材料关闭,FORMAT(D.MB433,'0.######') AS 拼板数,MD.MD019 插件位置,MW002 工艺
	FROM #BCPXJ JOIN SDRD..INVMB B ON MB01=B.MB001 
	JOIN INVMB C ON MD01=C.MB001 	
	JOIN INVMB D ON 材料品号=D.MB001
	JOIN BOMMD MD ON  MD01=MD001  AND  MD02=MD002 AND 材料品号=MD.MD003
	LEFT JOIN CMSMW ON MD009=MW001
	LEFT JOIN (
		SELECT TA006,TE004,LEFT(TC003,6) [ISSUE_MONTH],SUM(MATERIAL_ISSUE.TE005)-SUM(MATERIAL_RETURN.TE005) AS QTY FROM MOCTA
		INNER JOIN MOCTE MATERIAL_ISSUE ON TE011 = TA001 AND TE012 = TA002 AND LEFT(TE001,2)='54'
		INNER JOIN MOCTC MATERIAL_ISSUE ON TC001 = TE001 AND TC002 = TE002
		INNER JOIN MOCTE MATERIAL_RETURN ON TE011 = TA001 AND TE012 = TA002 AND LEFT(TE001,2)='56'
		INNER JOIN MOCTE MATERIAL_RETURN ON TC001 = TE001 AND TC002 = TE002
	) ON TA006 = MB01 AND TE004 = 材料品号
	) WX2 ON TRIM(材料品号)=WX2.MB001