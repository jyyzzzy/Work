	WHILE (SELECT COUNT(*) FROM #tbMC) > 0
	BEGIN
		SELECT TOP 1  @CLPH=RTRIM(MB01) FROM #tbMC 

		INSERT INTO #BCPXJ SELECT MB01,MD01,MD02,
		MD03 材料品号 ,MB002 材料品名,MB003 材料规格, CASE WHEN  ((MD01 LIKE'4%' AND MD13='Y') OR MD01 NOT LIKE'4%' )THEN MD06/MD07 ELSE 0 END From SDRD.[dbo].Fn_GetBOMIDs_YL(@CLPH) , #tbMC,SDRD..INVMB B where MB01=@CLPH AND MD03=MB001 and MD07>0	
		-- and ( MB002='集成电路'  or  MB002='可控硅' )
		--and  left(MD03,1) not in ('1','A','2') 
