/*
用途：
1. 查询 AHRD 生产入库明细。
2. 按 SDRD 标准 BOM 展开至末阶材料。
3. 显示末阶材料品号、品名、规格、单位用量、最近进价及材料成本。
4. 主查询不使用 GROUP BY；一条生产入库明细会按末阶材料展开为多行。
5. 日期字段为 MOCTF.TF003（入库日期）。MOCTG.TG003 是入库序号，不能用于日期范围筛选。
*/

WITH CTE_Product_Price AS
(
    SELECT
        P.company,
        P.productno,
        P.[month],
        P.price,
        P.[date]
    FROM
    (
        SELECT
            PP.company,
            PP.productno,
            PP.[month],
            PP.price,
            PP.[date],
            ROW_NUMBER() OVER
            (
                PARTITION BY PP.company, PP.productno, PP.[month]
                ORDER BY PP.[date] DESC
            ) AS rn
        FROM LSSJ..Product_Price AS PP
    ) AS P
    WHERE P.rn = 1
),
CTE_BOM_EXPAND AS
(
    SELECT
        A.MD001 AS BOM001,

        COALESCE
        (
            F.MD003,
            E.MD003,
            D.MD003,
            C.MD003,
            B.MD003,
            A.MD003
        ) AS MATERIAL_NO,

        CASE
            WHEN F.MD003 IS NOT NULL THEN
                  CAST(A.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(A.MD007 AS DECIMAL(38,12)), 0)
                * CAST(B.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(B.MD007 AS DECIMAL(38,12)), 0)
                * CAST(C.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(C.MD007 AS DECIMAL(38,12)), 0)
                * CAST(D.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(D.MD007 AS DECIMAL(38,12)), 0)
                * CAST(E.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(E.MD007 AS DECIMAL(38,12)), 0)
                * CAST(F.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(F.MD007 AS DECIMAL(38,12)), 0)

            WHEN E.MD003 IS NOT NULL THEN
                  CAST(A.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(A.MD007 AS DECIMAL(38,12)), 0)
                * CAST(B.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(B.MD007 AS DECIMAL(38,12)), 0)
                * CAST(C.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(C.MD007 AS DECIMAL(38,12)), 0)
                * CAST(D.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(D.MD007 AS DECIMAL(38,12)), 0)
                * CAST(E.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(E.MD007 AS DECIMAL(38,12)), 0)

            WHEN D.MD003 IS NOT NULL THEN
                  CAST(A.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(A.MD007 AS DECIMAL(38,12)), 0)
                * CAST(B.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(B.MD007 AS DECIMAL(38,12)), 0)
                * CAST(C.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(C.MD007 AS DECIMAL(38,12)), 0)
                * CAST(D.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(D.MD007 AS DECIMAL(38,12)), 0)

            WHEN C.MD003 IS NOT NULL THEN
                  CAST(A.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(A.MD007 AS DECIMAL(38,12)), 0)
                * CAST(B.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(B.MD007 AS DECIMAL(38,12)), 0)
                * CAST(C.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(C.MD007 AS DECIMAL(38,12)), 0)

            WHEN B.MD003 IS NOT NULL THEN
                  CAST(A.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(A.MD007 AS DECIMAL(38,12)), 0)
                * CAST(B.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(B.MD007 AS DECIMAL(38,12)), 0)

            ELSE
                  CAST(A.MD006 AS DECIMAL(38,12)) / NULLIF(CAST(A.MD007 AS DECIMAL(38,12)), 0)
        END AS MATERIAL_UNIT_USAGE

    FROM SDRD..BOMMD AS A WITH(NOLOCK)
    LEFT JOIN SDRD..BOMMD AS B WITH(NOLOCK)
        ON A.MD003 = B.MD001
    LEFT JOIN SDRD..BOMMD AS C WITH(NOLOCK)
        ON B.MD003 = C.MD001
    LEFT JOIN SDRD..BOMMD AS D WITH(NOLOCK)
        ON C.MD003 = D.MD001
    LEFT JOIN SDRD..BOMMD AS E WITH(NOLOCK)
        ON D.MD003 = E.MD001
    LEFT JOIN SDRD..BOMMD AS F WITH(NOLOCK)
        ON E.MD003 = F.MD001
),
CTE_BOM_MATERIAL AS
(
    SELECT
        E.BOM001,
        E.MATERIAL_NO,
        M.MB002 AS MATERIAL_NAME,
        M.MB003 AS MATERIAL_SPEC,
        M.MB004 AS MATERIAL_UNIT,
        E.MATERIAL_UNIT_USAGE,

        CAST
        (
            COALESCE(AH.MB049, M.MB049, 0)
            AS DECIMAL(38,12)
        ) AS MATERIAL_PRICE,

        CAST
        (
            E.MATERIAL_UNIT_USAGE
            * COALESCE(AH.MB049, M.MB049, 0)
            AS DECIMAL(38,12)
        ) AS MATERIAL_UNIT_COST

    FROM CTE_BOM_EXPAND AS E
    INNER JOIN SDRD..INVMB AS M WITH(NOLOCK)
        ON E.MATERIAL_NO = M.MB001
       AND M.MB109 = 'Y'
    LEFT JOIN AHRD..INVMB AS AH WITH(NOLOCK)
        ON E.MATERIAL_NO = AH.MB001
),
CTE_BOMMD AS
(
    SELECT
        B.BOM001,
        B.MATERIAL_NO,
        B.MATERIAL_NAME,
        B.MATERIAL_SPEC,
        B.MATERIAL_UNIT,
        B.MATERIAL_UNIT_USAGE,
        B.MATERIAL_PRICE,
        B.MATERIAL_UNIT_COST,

        SUM(B.MATERIAL_UNIT_COST) OVER
        (
            PARTITION BY B.BOM001
        ) AS PRODUCT_BOM_COST

    FROM CTE_BOM_MATERIAL AS B
),
CTE_CMSMG AS
(
    SELECT
        A.MG001,
        A.MG002,
        A.MG003,
        LEFT(A.MG002, 6) AS MG002_MONTH
    FROM SDRD..CMSMG AS A WITH(NOLOCK)
    INNER JOIN
    (
        SELECT
            MF.MF001,
            MIN(MG.MG002) AS MG002,
            LEFT(MG.MG002, 6) AS MG002_MONTH
        FROM SDRD..CMSMF AS MF WITH(NOLOCK)
        INNER JOIN SDRD..CMSMG AS MG WITH(NOLOCK)
            ON MF.MF001 = MG.MG001
        GROUP BY
            MF.MF001,
            LEFT(MG.MG002, 6)
    ) AS B
        ON A.MG001 = B.MF001
       AND A.MG002 = B.MG002
)

SELECT
    'AHRD' AS COMPANY,

    MOCTG.TG001 AS MOCTGTG001,
    MOCTG.TG002 AS MOCTGTG002,
    MOCTG.TG003 AS MOCTGTG003,
    MOCTF.TF003 AS MOCTFTF003,

    MOCTG.TG001 + '-' + MOCTG.TG002 + '-' + MOCTG.TG003 AS 入库单别号,

    MOCTG.TG004 AS MOCTGTG004,
    MOCTG.TG005 AS MOCTGTG005,
    MOCTG.TG006 AS MOCTGTG006,
    MOCTG.TG007 AS MOCTGTG007,

    ISNULL(COPTC.TC008, 'RMB') AS COPTCTC008,
    ISNULL(CMSMG.MG003, 1) AS COPTCTC009,
    MOCTG.TG013 AS MOCTGTG013,
    ISNULL(Product_Price.price, 0) AS COPTDTD011,

    MOCTG.TG013
        * ISNULL(Product_Price.price, 0)
        * ISNULL(CMSMG.MG003, 1) AS 产值,

    COST_VALUE.不含税产值,

    INVLA.LA012 AS INVMBMB057,

    /* 产品按标准 BOM 展开的单位材料成本合计，每个材料明细行重复显示。 */
    ISNULL(BOMMD.PRODUCT_BOM_COST, 0) AS MOCTGUDF51,

    MOCTF.TF011 AS MOCTFTF011,
    CMSMD.MD002 AS CMSMDMD002,
    LEFT(CMSMD.MD011, 4) AS CMSMDMD011,

    MOCTG.TG010 AS MOCTGTG010,
    MOCTG.TG014 AS MOCTGTG014,
    MOCTG.TG015 AS MOCTGTG015,

    MOCTA.TA026 AS MOCTATA026,
    MOCTA.TA027 AS MOCTATA027,
    MOCTA.TA028 AS MOCTATA028,

    CASE
        WHEN COPTC.TC008 = 'USD'
          OR COPMA.MA001 = '10000059'
        THEN 'Y'
        ELSE 'N'
    END AS 外销,

    COPTC.TC004 AS COPTCTC004,
    COPMA.MA002 AS COPMAMA002,

    PROD_INVMB.MB008 AS INVMBMB008,
    INVMA.MA003 AS INVMAMA003,
    INVMA1.MA003 AS INVMA1MA003,

    PROD_INVMB.MB096 AS INVMBMB096,

    PROD_INVMB.MB096
        * 100.0 / 3600
        * MOCTG.TG013 AS 定额工时,

    CASE
        WHEN ISNULL(MOCTG.TG013, 0) = 0 THEN 0
        ELSE CAST(INVLA.LA017 / MOCTG.TG013 AS DECIMAL(15,6))
    END AS 单位材料,

    CASE
        WHEN ISNULL(MOCTG.TG013, 0) = 0 THEN 0
        ELSE CAST(INVLA.LA018 / MOCTG.TG013 AS DECIMAL(15,6))
    END AS 单位人工,

    CASE
        WHEN ISNULL(MOCTG.TG013, 0) = 0 THEN 0
        ELSE CAST(INVLA.LA019 / MOCTG.TG013 AS DECIMAL(15,6))
    END AS 单位制费,

    INVLA.LA017 AS INVLALA017,
    INVLA.LA018 AS INVLALA018,
    INVLA.LA019 AS INVLALA019,

    CASE
        WHEN ISNULL(Product_Price.price, 0) = 0
          OR ISNULL(MOCTG.TG013, 0) = 0
        THEN 0
        ELSE
            INVLA.LA017
            / NULLIF(COST_VALUE.不含税产值, 0)
            * 100
    END AS 材料占比,

    CASE
        WHEN ISNULL(Product_Price.price, 0) = 0
          OR ISNULL(MOCTG.TG013, 0) = 0
        THEN 0
        ELSE
            (INVLA.LA019 + INVLA.LA018)
            / NULLIF(COST_VALUE.不含税产值, 0)
            * 100
    END AS 加工成本率,

    CASE
        WHEN ISNULL(Product_Price.price, 0) = 0
          OR ISNULL(MOCTG.TG013, 0) = 0
        THEN 0
        ELSE
            (
                1
                - INVLA.LA017
                  / NULLIF(COST_VALUE.不含税产值, 0)
                - (INVLA.LA019 + INVLA.LA018)
                  / NULLIF(COST_VALUE.不含税产值, 0)
            ) * 100
    END AS 毛利率,

    /* 以下字段为展开后的末阶材料成本明细。 */
    BOMMD.MATERIAL_NO AS MATERIAL_NO,
    BOMMD.MATERIAL_NAME AS MATERIAL_NAME,
    BOMMD.MATERIAL_SPEC AS MATERIAL_SPEC,
    BOMMD.MATERIAL_UNIT AS MATERIAL_UNIT,
    BOMMD.MATERIAL_UNIT_USAGE AS MATERIAL_UNIT_USAGE,
    BOMMD.MATERIAL_PRICE AS MATERIAL_PRICE,
    BOMMD.MATERIAL_UNIT_COST AS MATERIAL_UNIT_COST,

    CAST
    (
        ISNULL(BOMMD.MATERIAL_UNIT_COST, 0)
        * ISNULL(MOCTG.TG013, 0)
        AS DECIMAL(38,12)
    ) AS MATERIAL_TOTAL_COST

FROM AHRD..MOCTG AS MOCTG WITH(NOLOCK)

LEFT JOIN AHRD..MOCTA AS MOCTA WITH(NOLOCK)
    ON MOCTG.TG014 = MOCTA.TA001
   AND MOCTG.TG015 = MOCTA.TA002

LEFT JOIN AHRD..MOCTF AS MOCTF WITH(NOLOCK)
    ON MOCTG.TG001 = MOCTF.TF001
   AND MOCTG.TG002 = MOCTF.TF002

LEFT JOIN AHRD..INVLA AS INVLA WITH(NOLOCK)
    ON INVLA.LA006 = MOCTG.TG001
   AND INVLA.LA007 = MOCTG.TG002
   AND INVLA.LA008 = MOCTG.TG003

LEFT JOIN AHRD..INVMB AS PROD_INVMB WITH(NOLOCK)
    ON MOCTG.TG004 = PROD_INVMB.MB001

LEFT JOIN AHRD..INVMA AS INVMA WITH(NOLOCK)
    ON PROD_INVMB.MB008 = INVMA.MA002

LEFT JOIN AHRD..INVMA AS INVMA1 WITH(NOLOCK)
    ON PROD_INVMB.MB007 = INVMA1.MA002

LEFT JOIN AHRD..COPTC AS COPTC WITH(NOLOCK)
    ON MOCTA.TA026 = COPTC.TC001
   AND MOCTA.TA027 = COPTC.TC002

LEFT JOIN AHRD..COPMA AS COPMA WITH(NOLOCK)
    ON COPTC.TC004 = COPMA.MA001

LEFT JOIN AHRD..CMSMD AS CMSMD WITH(NOLOCK)
    ON MOCTF.TF011 = CMSMD.MD001

LEFT JOIN CTE_BOMMD AS BOMMD
    ON BOMMD.BOM001 = MOCTG.TG004

LEFT JOIN CTE_Product_Price AS Product_Price
    ON TRIM(MOCTG.TG001)
       + '-'
       + TRIM(MOCTG.TG002)
       + '-'
       + TRIM(MOCTG.TG003) = Product_Price.productno
   AND Product_Price.[month] = LEFT(MOCTF.TF003, 6)
   AND Product_Price.company = 'AHRD'

INNER JOIN CTE_CMSMG AS CMSMG
    ON CMSMG.MG002_MONTH = LEFT(MOCTF.TF003, 6)
   AND ISNULL(COPTC.TC008, 'RMB') = CMSMG.MG001

CROSS APPLY
(
    SELECT
        CAST
        (
            CASE
                WHEN COPTC.TC008 = 'USD'
                  OR COPMA.MA001 = '10000059'
                THEN
                    MOCTG.TG013
                    * ISNULL(Product_Price.price, 0)
                    * ISNULL(CMSMG.MG003, 1)
                ELSE
                    MOCTG.TG013
                    * ISNULL(Product_Price.price, 0)
                    * ISNULL(CMSMG.MG003, 1)
                    / 1.13
            END
            AS DECIMAL(38,12)
        ) AS 不含税产值
) AS COST_VALUE

WHERE MOCTA.TA001 = '5101'
  AND MOCTF.TF006 = 'Y'
  AND CMSMD.MD002 NOT LIKE '%虚拟%'
  AND MOCTF.TF003 BETWEEN '20260701' AND '20260731'

ORDER BY
    MOCTF.TF003,
    MOCTG.TG001,
    MOCTG.TG002,
    MOCTG.TG003,
    BOMMD.MATERIAL_NO;
