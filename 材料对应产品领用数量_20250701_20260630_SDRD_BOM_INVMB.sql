    R.事业部,
    R.账套,
    R.客户简称,
    R.销售部门
FROM #RESULT R
LEFT JOIN #INVMB MATL
    ON MATL.账套 = R.账套
   AND MATL.ITEMNO = R.材料品号
LEFT JOIN #INVMB PROD
    ON PROD.账套 = R.账套
   AND PROD.ITEMNO = R.产品品号
LEFT JOIN #BOM B
    ON B.账套 = R.账套
   AND B.产品品号 = R.产品品号
   AND B.材料品号 = R.材料品号
ORDER BY
    R.材料品号,
    R.产品品号,
    R.事业部,
    R.账套,
    R.客户简称,
    R.销售部门;
