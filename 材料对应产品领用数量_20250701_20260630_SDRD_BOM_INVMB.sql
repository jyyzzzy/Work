    INNER JOIN SDRD..MOCTE TE WITH(NOLOCK)
        ON TE.TE001 = TC.TC001
       AND TE.TE002 = TC.TC002
    INNER JOIN #ITEM_RAW I
        ON LTRIM(RTRIM(TE.TE004)) COLLATE DATABASE_DEFAULT = I.材料品号
    WHERE TC.TC003 >= @BeginDate
      AND TC.TC003 <= @EndDate
      AND TE.TE019 = 'Y'
