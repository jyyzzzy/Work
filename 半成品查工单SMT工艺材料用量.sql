SELECT TA006 产品品号
	,PROD.MB002 产品品名
	,PROD.MB003 产品规格
	,SUM(TA017) 已生产量
	,TB003 材料品号
	,MATL.MB002 材料品名
	,MATL.MB003 材料规格
	,TB006 材料工艺
	,MW002 工艺名称
	,TB004/TA015 单位用量
	,SUM(TB005) 已领用量
FROM LSSJ..ITEMTMP I 
INNER JOIN MOCTA ON TA006 = I.ITEMNO
INNER JOIN MOCTB ON TA001 = TB001 AND TA002 = TB002
INNER JOIN CMSMW ON MW001 = TB006
INNER JOIN INVMB PROD ON PROD.MB001 = TA006
INNER JOIN INVMB MATL ON MATL.MB001 = TB003
WHERE TA013 = 'Y'
AND TA011 IN ('Y','y')
AND EXISTS(
	SELECT 1 
	FROM MOCTG 
		INNER JOIN MOCTF ON TF001 = TG001 AND TF002 = TG002
	WHERE TG014 = TA001 
		AND TG015 = TA002
		AND TF003 BETWEEN '20260101' AND '20261231'
)
--AND LEFT(MW002,3) = 'SMT'
AND MW002 LIKE '%SMT%'
GROUP BY TA006,PROD.MB002,PROD.MB003,TB003,MATL.MB002,MATL.MB003,TB006,MW002,TB004/TA015
ORDER BY TA006,TB003,TB006