SELECT ITEMNO,
SUM(TD008) 采购数量,
SUM(TD015) 验收数量,
'SDRD' COMPANY
FROM LSSJ..ITEMTMP 
INNER JOIN SDRD..PURTD ON TD004 = ITEMNO
INNER JOIN SDRD..PURTC ON TC001 = TD001 AND TC002 = TD002
WHERE TC003 BETWEEN '20250101' AND '20261231'
AND TC014 = 'Y'
AND TD018 = 'Y'
GROUP BY ITEMNO

UNION

