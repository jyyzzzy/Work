/*
    4. 创建者名称。
       原查询连续使用 UNION 和外层 DISTINCT，会产生多次排序。
       此处改成 UNION ALL 后只执行一次 DISTINCT，保持原查询结果口径。
*/
SELECT DISTINCT
    S.MV001,
    S.MV002
INTO #CMSMV
FROM
(
    SELECT V.MV001, V.MV002
    FROM SDRD..CMSMV AS V
    INNER JOIN (SELECT DISTINCT CREATOR FROM #ITEM WHERE CREATOR IS NOT NULL) AS I
        ON I.CREATOR = V.MV001

    UNION ALL

    SELECT V.MV001, V.MV002
    FROM ZJRD..CMSMV AS V
    INNER JOIN (SELECT DISTINCT CREATOR FROM #ITEM WHERE CREATOR IS NOT NULL) AS I
        ON I.CREATOR = V.MV001

    UNION ALL

    SELECT V.MV001, V.MV002
    FROM AHRD..CMSMV AS V
    INNER JOIN (SELECT DISTINCT CREATOR FROM #ITEM WHERE CREATOR IS NOT NULL) AS I
        ON I.CREATOR = V.MV001

    UNION ALL

    SELECT V.MV001, V.MV002
    FROM YNRD..CMSMV AS V
    INNER JOIN (SELECT DISTINCT CREATOR FROM #ITEM WHERE CREATOR IS NOT NULL) AS I
        ON I.CREATOR = V.MV001
) AS S;

CREATE NONCLUSTERED INDEX IX_CMSMV ON #CMSMV(MV001);

/*
    5. 历史总入库、总出库。
       原查询 SELECT * 合并四地 INVLA 全部历史明细后才 GROUP BY，是最主要慢点之一。
       此处改成：只查目标品号、每个账套先汇总、最后再汇总。
*/
SELECT
    Q.LA001,
    SUM(Q.ISSUED) AS ISSUED,
    SUM(Q.RECEIVED) AS RECEIVED
INTO #TOT_QTY
FROM
(
    SELECT
        L.LA001,
        SUM(CASE WHEN L.LA005 = -1 THEN L.LA011 ELSE 0 END) AS ISSUED,
        SUM(CASE WHEN L.LA005 =  1 THEN L.LA011 ELSE 0 END) AS RECEIVED
    FROM SDRD..INVLA AS L
    INNER JOIN #ITEM AS I ON I.MB001 = L.LA001
    WHERE L.LA005 IN (-1, 1)
    GROUP BY L.LA001

    UNION ALL

    SELECT
        L.LA001,
        SUM(CASE WHEN L.LA005 = -1 THEN L.LA011 ELSE 0 END),
        SUM(CASE WHEN L.LA005 =  1 THEN L.LA011 ELSE 0 END)
    FROM ZJRD..INVLA AS L
    INNER JOIN #ITEM AS I ON I.MB001 = L.LA001
    WHERE L.LA005 IN (-1, 1)
    GROUP BY L.LA001

    UNION ALL

    SELECT
        L.LA001,
        SUM(CASE WHEN L.LA005 = -1 THEN L.LA011 ELSE 0 END),
        SUM(CASE WHEN L.LA005 =  1 THEN L.LA011 ELSE 0 END)
    FROM AHRD..INVLA AS L
    INNER JOIN #ITEM AS I ON I.MB001 = L.LA001
    WHERE L.LA005 IN (-1, 1)
    GROUP BY L.LA001

    UNION ALL

    SELECT
        L.LA001,
        SUM(CASE WHEN L.LA005 = -1 THEN L.LA011 ELSE 0 END),
        SUM(CASE WHEN L.LA005 =  1 THEN L.LA011 ELSE 0 END)
    FROM YNRD..INVLA AS L
    INNER JOIN #ITEM AS I ON I.MB001 = L.LA001
    WHERE L.LA005 IN (-1, 1)
    GROUP BY L.LA001
) AS Q
GROUP BY Q.LA001
OPTION (RECOMPILE);

CREATE UNIQUE CLUSTERED INDEX CX_TOT_QTY ON #TOT_QTY(LA001);

/*
    6. BOM 成品数量单独计算并落临时表。
       仍会逐品号调用 Fn_GetBOMUpIDs，但只执行一次，避免被最终连接放大。
       若此步骤仍慢，需要把 Fn_GetBOMUpIDs 改写为基于 BOMMD 的集合式递归查询。
*/
SELECT
    I.MB001,
    COUNT(B.MD01) AS 成品数量
INTO #BOM_COUNT
FROM #ITEM AS I
OUTER APPLY
(
    SELECT F.MD01
    FROM SDRD.dbo.Fn_GetBOMUpIDs(I.MB001) AS F
    WHERE F.MD01 LIKE 'A%'
       OR F.MD01 LIKE '1%'
) AS B
GROUP BY I.MB001;

CREATE UNIQUE CLUSTERED INDEX CX_BOM_COUNT ON #BOM_COUNT(MB001);

/* 7. 最终结果。 */
SELECT
    RTRIM(I.MB001) AS 品号,
    RTRIM(I.MB002) AS 品名,
    RTRIM(I.MB003) AS 规格,
    RTRIM(I.MB004) AS 单位,
    ISNULL(S.MC007, 0) AS 库存,
    ISNULL(B.成品数量, 0) AS 成品数量,
    ISNULL(I.UDF05, '') AS 采购选型,
    ISNULL(M.TC003, '') AS 最后交易日,
    ISNULL(M.TE005, 0) AS 最后交易数量,
    LEFT(I.CREATE_DATE, 8) AS 物料创建时间,
    RTRIM(I.CREATOR) AS 物料创建者编号,
    RTRIM(ISNULL(V.MV002, '')) AS 物料创建者名称,
    I.MB109 AS 核准状况,
    ISNULL(M.TE001, '') AS 单别,
    ISNULL(M.TE002, '') AS 单号,
    ISNULL(Q.RECEIVED, 0) AS 总入库数量,
    ISNULL(Q.ISSUED, 0) AS 总出库数量
FROM #ITEM AS I
LEFT JOIN #MOC AS M ON M.TE004 = I.MB001
LEFT JOIN #INVMC AS S ON S.MC001 = I.MB001
LEFT JOIN #CMSMV AS V ON V.MV001 = I.CREATOR
LEFT JOIN #TOT_QTY AS Q ON Q.LA001 = I.MB001
LEFT JOIN #BOM_COUNT AS B ON B.MB001 = I.MB001
ORDER BY I.MB001;

DROP TABLE #BOM_COUNT;
DROP TABLE #TOT_QTY;
DROP TABLE #CMSMV;
DROP TABLE #INVMC;
DROP TABLE #MOC;
DROP TABLE #ITEM;

