/* 先建立符合 ROW_NUMBER 顺序的索引，降低再次排序和 TempDB 压力。 */
CREATE CLUSTERED INDEX CX_MOVE_RAW
    ON #MOVE_RAW(品号, 交易日 DESC, 单别 DESC, 单号 DESC);

SELECT
    单别 AS TE001,
    单号 AS TE002,
    品号 AS TE004,
    交易日 AS TC003,
    数量 AS TE005
INTO #MOC
FROM
(
    SELECT
        单别,
        单号,
        交易日,
        品号,
        数量,
        ROW_NUMBER() OVER
        (
            PARTITION BY 品号
            ORDER BY 交易日 DESC, 单别 DESC, 单号 DESC
        ) AS RN
    FROM #MOVE_RAW
) AS D
WHERE D.RN = 1;

CREATE UNIQUE CLUSTERED INDEX CX_MOC ON #MOC(TE004);
DROP TABLE #MOVE_RAW;

/*
    3. 可用库存。
       四地先分别按品号汇总，再 UNION ALL，减少进入最终汇总的数据量。
*/
SELECT
    S.MC001,
    SUM(S.MC007) AS MC007
INTO #INVMC
FROM
(
    SELECT M.MC001, SUM(M.MC007) AS MC007
    FROM SDRD..INVMC AS M
    INNER JOIN SDRD..CMSMC AS C ON C.MC001 = M.MC002
    INNER JOIN #ITEM AS I ON I.MB001 = M.MC001
    WHERE M.MC007 > 0
      AND RIGHT(C.UDF01, 3) <> N'不良品'
      AND C.MC005 = 'Y'
    GROUP BY M.MC001

    UNION ALL

    SELECT M.MC001, SUM(M.MC007)
    FROM ZJRD..INVMC AS M
    INNER JOIN ZJRD..CMSMC AS C ON C.MC001 = M.MC002
    INNER JOIN #ITEM AS I ON I.MB001 = M.MC001
    WHERE M.MC007 > 0
      AND RIGHT(C.UDF01, 3) <> N'不良品'
      AND C.MC005 = 'Y'
    GROUP BY M.MC001

    UNION ALL

    SELECT M.MC001, SUM(M.MC007)
    FROM AHRD..INVMC AS M
    INNER JOIN AHRD..CMSMC AS C ON C.MC001 = M.MC002
    INNER JOIN #ITEM AS I ON I.MB001 = M.MC001
    WHERE M.MC007 > 0
      AND RIGHT(C.UDF01, 3) <> N'不良品'
      AND C.MC005 = 'Y'
    GROUP BY M.MC001

    UNION ALL

    SELECT M.MC001, SUM(M.MC007)
    FROM YNRD..INVMC AS M
    INNER JOIN YNRD..CMSMC AS C ON C.MC001 = M.MC002
    INNER JOIN #ITEM AS I ON I.MB001 = M.MC001
    WHERE M.MC007 > 0
      AND RIGHT(C.UDF01, 3) <> N'不良品'
      AND C.MC005 = 'Y'
    GROUP BY M.MC001
) AS S
GROUP BY S.MC001
OPTION (RECOMPILE);

