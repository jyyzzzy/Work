SELECT
    MB001 AS 品号,
    MB002 供应商编号,
    MB003 币种,
    MB011 单价,
    MB014 生效日,
    MB015 失效日,
    MB008 核价日
FROM (
    SELECT
        PURMB.MB001,
        PURMB.MB002,
        PURMB.MB003,
        PURMB.MB011,
        PURMB.MB014,
        PURMB.MB015,
        PURMB.MB008,
        ROW_NUMBER() OVER (
            PARTITION BY PURMB.MB001
            ORDER BY
                PURMB.MB014 DESC,
                CASE WHEN PURMB.MB003 = 'RMB' THEN 0 ELSE 1 END,
                PURMB.MB008 DESC
        ) AS RN
    FROM LSSJ..Sh11 I
    INNER JOIN PURMB
        ON PURMB.MB001 = I.内部料号
) A
WHERE RN = 1
ORDER BY MB001;