SELECT TRIM(MB001) 品号
	,TRIM(MB002) 品名
	,TRIM(MB003) 规格
	,TRIM(MB004) 单位
	,TRIM(MB017) 主要仓库
	,TRIM(MC002) 仓库名称
	,TRIM(MB109) 核准状况
FROM INVMB 
LEFT JOIN CMSMC ON MB017 = MC001
WHERE 1=1 
AND MB017 IN ('005','605')
--AND MB017 NOT IN ('001', '052', '053')
ORDER BY MB001 ASC

