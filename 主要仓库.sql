SELECT TRIM(MB001) 品号
	,TRIM(MB002) 品名
	,TRIM(MB003) 规格
	,TRIM(MB004) 单位
	,TRIM(MB017) 主要仓库
	,TRIM(MC002) 仓库名称
	,TRIM(MB109) 核准状况
FROM INVMB 
LEFT JOIN CMSMC ON MB017 = MC001
WHERE MB017 NOT IN ('001', '052', '053')
ORDER BY MB001 ASC

UPDATE MOCTB 
SET TB009 = MB017
--SELECT MB017,TB009,MOCTB.*
FROM MOCTB
INNER JOIN INVMB ON MB001 = TB003
WHERE NOT EXISTS(
	SELECT 1 FROM CMSMC WHERE TB009 = MC001
)
AND EXISTS (
	SELECT 1 FROM CMSMC WHERE MB017 = MC001
)