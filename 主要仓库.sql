--工单仓库与产品仓库不同。
SELECT TA020,MB017,MOCTA.* 
--UPDATE MOCTA SET TA020 = MB017
--UPDATE INVMB SET MB017 = '002'
FROM MOCTA 
INNER JOIN INVMB ON MB001 = TA006
WHERE TA020 <> MB017
AND LEFT(TA006,1) = '1' --AND MB017 = '002'
AND TA011 <> 'Y' AND TA011 <> 'y'-- AND MB017 = '102'
ORDER BY MOCTA.CREATE_DATE DESC




--源订单属二三部
