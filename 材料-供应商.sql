SELECT DISTINCT
    供应商编号,
    供应商简称,
    品号,
    品名,
    规格,
    COMPANY
FROM
(
    /* =========================
       SDRD
       ========================= */
    SELECT
        RTRIM(PURMA.MA001) AS 供应商编号,
        RTRIM(PURMA.MA002) AS 供应商简称,
        RTRIM(INVMB.MB001) AS 品号,
        RTRIM(INVMB.MB002) AS 品名,
        RTRIM(INVMB.MB003) AS 规格,
        'SDRD' AS COMPANY
    FROM SDRD..PURTG
    INNER JOIN SDRD..PURMA
        ON PURMA.MA001 = PURTG.TG005
    INNER JOIN SDRD..PURTH
        ON PURTH.TH001 = PURTG.TG001
       AND PURTH.TH002 = PURTG.TG002
    INNER JOIN SDRD..INVMB
        ON INVMB.MB001 = PURTH.TH004
    WHERE PURTG.TG003 BETWEEN '20250801' AND '20260831'

    UNION ALL

    SELECT
        RTRIM(PURMA.MA001),
        RTRIM(PURMA.MA002),
        RTRIM(INVMB.MB001),
        RTRIM(INVMB.MB002),
        RTRIM(INVMB.MB003),
        'SDRD'
    FROM SDRD..PURTI
    INNER JOIN SDRD..PURMA
        ON PURMA.MA001 = PURTI.TI004
    INNER JOIN SDRD..PURTJ
        ON PURTJ.TJ001 = PURTI.TI001
       AND PURTJ.TJ002 = PURTI.TI002
    INNER JOIN SDRD..INVMB
        ON INVMB.MB001 = PURTJ.TJ004
    WHERE PURTI.TI003 BETWEEN '20250801' AND '20260831'


    /* =========================
       ZJRD
       ========================= */
    UNION ALL

    SELECT
        RTRIM(PURMA.MA001),
        RTRIM(PURMA.MA002),
        RTRIM(INVMB.MB001),
        RTRIM(INVMB.MB002),
        RTRIM(INVMB.MB003),
        'ZJRD'
    FROM ZJRD..PURTG
    INNER JOIN ZJRD..PURMA
        ON PURMA.MA001 = PURTG.TG005
    INNER JOIN ZJRD..PURTH
        ON PURTH.TH001 = PURTG.TG001
       AND PURTH.TH002 = PURTG.TG002
    INNER JOIN ZJRD..INVMB
        ON INVMB.MB001 = PURTH.TH004
    WHERE PURTG.TG003 BETWEEN '20250801' AND '20260831'

    UNION ALL

    SELECT
        RTRIM(PURMA.MA001),
        RTRIM(PURMA.MA002),
        RTRIM(INVMB.MB001),
        RTRIM(INVMB.MB002),
        RTRIM(INVMB.MB003),
        'ZJRD'
    FROM ZJRD..PURTI
    INNER JOIN ZJRD..PURMA
        ON PURMA.MA001 = PURTI.TI004
    INNER JOIN ZJRD..PURTJ
        ON PURTJ.TJ001 = PURTI.TI001
       AND PURTJ.TJ002 = PURTI.TI002
    INNER JOIN ZJRD..INVMB
        ON INVMB.MB001 = PURTJ.TJ004
    WHERE PURTI.TI003 BETWEEN '20250801' AND '20260831'


    /* =========================
       AHRD
       ========================= */
    UNION ALL

    SELECT
        RTRIM(PURMA.MA001),
        RTRIM(PURMA.MA002),
        RTRIM(INVMB.MB001),
        RTRIM(INVMB.MB002),
        RTRIM(INVMB.MB003),
        'AHRD'
    FROM AHRD..PURTG
    INNER JOIN AHRD..PURMA
        ON PURMA.MA001 = PURTG.TG005
    INNER JOIN AHRD..PURTH
        ON PURTH.TH001 = PURTG.TG001
       AND PURTH.TH002 = PURTG.TG002
    INNER JOIN AHRD..INVMB
        ON INVMB.MB001 = PURTH.TH004
    WHERE PURTG.TG003 BETWEEN '20250801' AND '20260831'

    UNION ALL

    SELECT
        RTRIM(PURMA.MA001),
        RTRIM(PURMA.MA002),
        RTRIM(INVMB.MB001),
        RTRIM(INVMB.MB002),
        RTRIM(INVMB.MB003),
        'AHRD'
    FROM AHRD..PURTI
    INNER JOIN AHRD..PURMA
        ON PURMA.MA001 = PURTI.TI004
    INNER JOIN AHRD..PURTJ
        ON PURTJ.TJ001 = PURTI.TI001
       AND PURTJ.TJ002 = PURTI.TI002
    INNER JOIN AHRD..INVMB
        ON INVMB.MB001 = PURTJ.TJ004
    WHERE PURTI.TI003 BETWEEN '20250801' AND '20260831'
) AS T;