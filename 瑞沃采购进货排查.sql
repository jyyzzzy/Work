--瑞沃采购进货排查


SELECT TC009 订单单号,INVTA.UDF01 进货单号,TD008 采购数量,TB009 已交数量
FROM PURTD
INNER JOIN PURTC ON TC001 = TD001 AND TC002 = TD002
INNER JOIN scm_lnk.myerp_scm_rw.dbo.pu_pps_beliverylist 
	ON TC009 = sbillno COLLATE Chinese_PRC_BIN
INNER JOIN INVTA ON TA001 = '1112' AND INVTA.UDF01 = msgno COLLATE Chinese_PRC_BIN
INNER JOIN INVTB ON TA001 = TB001 AND TA002 = TB002
WHERE TC001 = '3301'
AND TC002 = '20260209005'

SELECT * 
FROM INVTA 
INNER JOIN INVTB ON TB001 = TA001 AND TB002 = TA002
WHERE TA001 = '1112'
AND INVTA.UDF01 = 'T2602100004'

SELECT * 
FROM scm_lnk.myerp_scm_rw.dbo.pu_pps_beliverylist
WHERE sbillno = 'P2602090015'