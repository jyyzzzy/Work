select --'广东瑞德' 账套, 
LA001 领料编号,MB002 品名,MB003 规格,MB004 单位,left(LA004,6) 领退料日期,SUM(-1*LA011*LA005) 领料数量,left(CMSMD.MD011,4)所属经营单位
--, -SUM(LA013*LA005*1.13) 金额
from  INVLA JOIN INVMB ON MB001=LA001
LEFT JOIN  CMSMD On SUBSTRING(INVLA.UDF06, 1, CHARINDEX('|', INVLA.UDF06) - 1) = RTRIM(CMSMD.MD001)

WHERE LA004>='20260101' AND LA004<='20260631'-- AND LA001 = '309000039900'
--and LA001='303000313400'
AND LEFT(LA006,2) IN ('54','56')
AND LEFT(LA001,1) IN ('3','5','6','7')
--AND MB002 LIKE '%集成电路%'
--AND left(CMSMD.MD011,4) = '事业一部'
GROUP BY LA001,left(LA004,6),MB002,MB003,left(CMSMD.MD011,4),MB004

ORDER BY LA001,left(LA004,6),MB002,MB003,left(CMSMD.MD011,4),MB004


select --'广东瑞德' 账套, 
TRIM(LA001) 领料编号,MB002 品名,MB003 规格,SUM(-1*LA011*LA005) 总领料数量
--, -SUM(LA013*LA005*1.13) 金额
from  INVLA JOIN INVMB ON MB001=LA001

WHERE LA004>='20260401' AND LA004<='20260631'-- AND LA001 = '309000039900'
--and LA001='303000313400'
AND LEFT(LA006,2) IN ('54','56')
AND LEFT(LA001,1) IN ('3','5','6','7')
--AND MB002 LIKE '%集成电路%'
--AND left(CMSMD.MD011,4) = '事业一部'
GROUP BY LA001,MB002,MB003

ORDER BY LA001