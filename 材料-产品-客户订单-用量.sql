;WITH U AS
(
    SELECT
        I.ITEMNO AS COMP,
        B.PARENT AS P,
        CAST(B.CNT AS DECIMAL(38,12)) AS CNT,
        CAST(1 AS INT) AS LVL,
        CAST('|' + I.ITEMNO + '|' + B.PARENT + '|' AS VARCHAR(4000)) AS PATH
    FROM #ITEM I
    INNER JOIN #BOM B
        ON B.CHILD = I.ITEMNO

    UNION ALL

    SELECT
        U.COMP,
        B.PARENT AS P,
        CAST(U.CNT * B.CNT AS DECIMAL(38,12)) AS CNT,
        U.LVL + 1 AS LVL,
        CAST(U.PATH + B.PARENT + '|' AS VARCHAR(4000)) AS PATH
    FROM U
    INNER JOIN #BOM B
        ON B.CHILD = U.P
    WHERE U.LVL < 50
      AND CHARINDEX('|' + B.PARENT + '|', U.PATH) = 0
)
SELECT
    COMP,
    P,
    CNT
INTO #ANCESTOR
FROM U
OPTION (MAXRECURSION 100);

