-- 11. 事业部按 产品 + 客户 拼接
------------------------------------------------------------
SELECT
    D1.PROD,
    D1.客户编号,
    STUFF(
        (
            SELECT ';' + D2.事业部
            FROM
            (
                SELECT DISTINCT
                    PROD,
                    客户编号,
                    事业部
                FROM #ORDER_DEPT
                WHERE ISNULL(事业部, '') <> ''
            ) D2
            WHERE D2.PROD = D1.PROD
              AND D2.客户编号 = D1.客户编号
            ORDER BY D2.事业部
            FOR XML PATH(''), TYPE
        ).value('.', 'NVARCHAR(MAX)'),
        1,
        1,
        ''
    ) AS 事业部
INTO #CUSTOMER_DEPT
FROM
(
    SELECT DISTINCT
        PROD,
        客户编号
    FROM #ORDER_DEPT
    WHERE ISNULL(事业部, '') <> ''
) D1;

CREATE UNIQUE CLUSTERED INDEX IX_CUSTOMER_DEPT ON #CUSTOMER_DEPT(PROD, 客户编号);

