-- 9. 事业部按产品拼接
--    兼容低版本/低兼容级别 SQL Server，不使用 STRING_AGG WITHIN GROUP
------------------------------------------------------------
SELECT
    D1.PROD,
    STUFF(
        (
            SELECT ';' + D2.事业部
            FROM
            (
                SELECT DISTINCT
                    PROD,
                    事业部
                FROM #ORDER_DEPT
                WHERE ISNULL(事业部, '') <> ''
            ) D2
            WHERE D2.PROD = D1.PROD
            ORDER BY D2.事业部
            FOR XML PATH(''), TYPE
        ).value('.', 'NVARCHAR(MAX)'),
        1,
        1,
        ''
    ) AS 事业部
INTO #PRODUCT_DEPT
FROM
(
    SELECT DISTINCT
        PROD
    FROM #ORDER_DEPT
    WHERE ISNULL(事业部, '') <> ''
) D1;

