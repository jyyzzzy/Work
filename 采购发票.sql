--UPDATE COPTH
--SET TH042 = TB019
FROM 
PURTH
INNER JOIN PURTG ON TG001 + '-' + TG002 = TH001 + '-' + TH002
INNER JOIN (
	SELECT TB005,TB006,TB007,SUM(TB019) TB019 
	FROM ACPTB 
	WHERE TB012 = 'Y'
	GROUP BY TB005,TB006,TB007
) AS ACPTB ON TB005 + '-' + TB006 + '-' + TB007 = TH001 + '-' + TH002 + '-' + TH003
WHERE TB019 <> TH054
--AND PURTH.CREATE_DATE >='20260101170008270'
ORDER BY TG003 DESC
UPDATE PURTG SET TG033 = '' WHERE TG033 IS NULL