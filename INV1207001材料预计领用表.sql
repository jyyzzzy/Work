SELECT INVMB.MB109 as INVMBMB109
    , INVMB.MB001 as INVMBMB001
    , INVMB.MB002 as INVMBMB002
    , INVMB.MB003 as INVMBMB003
    , INVMB.MB004 as INVMBMB004
    , INVMA.MA003 as INVMAMA003
    , ISNULL((
        SELECT SUM(INVMC.MC007) AS KC002
        FROM INVMC 
        INNER JOIN  CMSMC ON INVMC.MC002 = CMSMC.MC001 
        WHERE CMSMC.MC005 = 'Y' and INVMC.MC001= INVMB.MB001
    ),0) as INVMBMB064
    ,ISNULL(A.TB004,0) as INVMBUDF51
    ,ISNULL(B.TD008,0) as INVMBUDF52
    ,ISNULL(A.TB004,0) + ISNULL(B.TD008,0) as INVMBUDF53
    ,INVMB.MB090 as INVMBMB090 
FROM INVMB as INVMB  
Left JOIN INVMA as INVMA On INVMB.MB006=INVMA.MA002 
LEFT JOIN
(
    SELECT TB003, SUM(TB004-TB005) AS TB004
    FROM MOCTB INNER JOIN     MOCTA ON TA001 = TB001 AND TA002 = TB002
    WHERE TB004 > TB005 AND TA011 <> 'Y' AND TA011 <> 'y' AND TA013 = 'Y'
    GROUP BY TB003
) AS A ON INVMB.MB001 = A.TB003 
LEFT JOIN
(
    SELECT TD004, TD008-TD009 AS TD008
    FROM COPTD
    WHERE TD016 = 'N' AND TD021 = 'Y'
) AS B ON B.TD004 = INVMB.MB001  
