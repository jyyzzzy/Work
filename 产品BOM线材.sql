;WITH BomTree AS
(
    SELECT
        T.ITEMNO AS TopItemNo,
        B.MD001     AS ParentItemNo,
        B.MD003     AS ComponentItemNo,
        LTRIM(RTRIM(ISNULL(B.MD009, ''))) AS ProcessNo
    FROM LSSJ..ITEMTMP T
    INNER JOIN BOMMD B
        ON B.MD001 = T.ITEMNO

    UNION ALL

    SELECT
        BT.TopItemNo,
        B.MD001,
        B.MD003,
        LTRIM(RTRIM(ISNULL(B.MD009, ''))) AS ProcessNo
    FROM BomTree BT
    INNER JOIN BOMMD B
        ON B.MD001 = BT.ComponentItemNo
)
,
[Proc] AS
(
    SELECT DISTINCT
        TopItemNo,
        TRIM(MW002) ProcessName
    FROM BomTree
    INNER JOIN CMSMW ON MW001 = ProcessNo
    WHERE MW002 LIKE 'SMT%'
)
SELECT
    A.TopItemNo AS 产品品号,
    STUFF
    (
        (
            SELECT N'、' + P2.ProcessName
            FROM [Proc] P2
            WHERE P2.TopItemNo = A.TopItemNo
            ORDER BY P2.ProcessName
            FOR XML PATH(''), TYPE
        ).value('.', 'NVARCHAR(MAX)')
    ,1,1,'') AS 工艺名称
FROM
(
    SELECT DISTINCT TopItemNo
    FROM [Proc]
) A
ORDER BY A.TopItemNo
OPTION (MAXRECURSION 0);