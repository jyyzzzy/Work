SELECT DISTINCT TRIM(MD001) AS [品号]
FROM BOMMD
WHERE LEFT(MD001,1) IN ('1','A')
AND EXISTS(
	SELECT 1 FROM INVMB WHERE MB001 = MD003
	AND MB006 = '213'
)
AND MD006 > 0
ORDER BY TRIM(MD001)


WITH ProductPoint AS (
    SELECT
        MD.MD001,
        MD.MD009,
sum(convert(float,Rtrim(case isnull(MB3.MB180,'') when '' then '-99999' else MB3.MB180 end),0)*MD006/MD007 )as Point 
    FROM SDRD.dbo.BOMMD AS MD
    JOIN SDRD.dbo.INVMB AS MB3
        ON MD.MD003 = MB3.MB001
    WHERE MD006 > 0
      AND MD007 >= 1
      AND MB3.MB006 <> '220' ---辅料去除点数
      AND LEFT(MD.MD003, 1) NOT IN ('A', '1', '2', '5', 'P')
    GROUP BY MD.MD001, MD.MD009
),
tmp AS(
SELECT DISTINCT MF001,MB002,MB003,BOMMF.MF004,MW002,left(CMSMC.UDF01,4) 事业部,IIF(MB110 = '',MB001,IIF(LEFT(MB110,1) = 'K',SUBSTRING(MB110,2,13),SUBSTRING(MB110,1,12))) AS PLMNO--,TA001,TA002
FROM BOMMF 
INNER JOIN CMSMW ON MW001 = BOMMF.MF004
INNER JOIN MOCTG ON TG004 = MF001
INNER JOIN CMSMC ON MC001 = TG010
INNER JOIN INVMB ON MB001 = MF001
INNER JOIN MOCTF ON TG001 = TF001 AND TG002 = TF002
WHERE BOMMF.MF004 IN ('P030','P040') --AND left(CMSMC.UDF01,4) LIKE '%三部%'
AND TF003 BETWEEN '20240101' AND '20261231'
)
SELECT DISTINCT TRIM(T.MF001) ERP品号,T.MB002 品名,T.MB003 规格,--MOCTGTG007,
T.MF004 工艺编号,T.MW002 工艺名称,
CASE
            WHEN PP.Point IS NULL THEN -1
            WHEN PP.Point >= 0 THEN PP.Point
            ELSE 0
        END 自动化点数,T.事业部,TRIM(T.PLMNO) AS PLM品号--,* 
FROM tmp AS T
--LEFT JOIN SDRD_Result AS R ON T.MF001 = R.MOCTGTG004 AND T.事业部 = R.MOCTACOMPANY AND T.MF004 = MOCTGTG010
LEFT JOIN ProductPoint AS PP ON PP.MD001 = T.MF001 AND PP.MD009 = T.MF004

