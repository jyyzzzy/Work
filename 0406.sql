;WITH U AS(
	SELECT T.ITEMNO AS COMP, M.MD001 AS P, M.MD006 AS CNT
	FROM LSSJ..ITEMTMP T
	LEFT OUTER JOIN SDRD..BOMMD M ON M.MD003 = T.ITEMNO
	UNION ALL
	SELECT U.COMP, M.MD001,M.MD006 AS CNT
	FROM U
	INNER JOIN SDRD..BOMMD M ON M.MD003 = U.P
) ,
FATHER AS (SELECT DISTINCT U.P AS 主件, U.COMP AS 元件, U.CNT AS 用量
	FROM U
	WHERE U.P IS NOT NULL
		AND NOT EXISTS (SELECT 1 FROM SDRD..BOMMD Z WHERE Z.MD003 = U.P)
		AND SUBSTRING(U.P, 1, 1) IN ('1', 'A')
)
--SELECT FATHER.元件 FROM FATHER GROUP BY FATHER.元件

SELECT FATHER.主件 AS PROD,FATHER.元件 AS MATL, FATHER.用量 AS CNT INTO #RELATION
FROM FATHER ORDER BY FATHER.主件;

SELECT LA001,MAX(LA004) LA004 INTO #LAST_DATE FROM #RELATION R
INNER JOIN (
	SELECT LA001,LA004 FROM SDRD..INVLA
	UNION ALL
	SELECT LA001,LA004 FROM ZJRD..INVLA
	UNION ALL
	SELECT LA001,LA004 FROM AHRD..INVLA
	UNION ALL
	SELECT LA001,LA004 FROM YNRD..INVLA
) INVLA ON LA001 = R.PROD
GROUP BY LA001;



SELECT R.MATL 材料品号,MATL.MB002 材料品名, MATL.MB003 材料规格,R.PROD 产品品号,PROD.MB002 产品品名,PROD.MB003 产品规格,LEFT(PROD.CREATE_DATE,8) 产品创建日期,
L.LA004 产品最近交易日期 ,LEFT(CMSMC.UDF01,4) 默认入库事业部

FROM #RELATION R
INNER JOIN SDRD..INVMB PROD ON PROD.MB001 = R.PROD
INNER JOIN SDRD..INVMB MATL ON MATL.MB001 = R.MATL
LEFT OUTER JOIN #LAST_DATE L ON L.LA001 = R.PROD
LEFT OUTER JOIN SDRD..CMSMC ON CMSMC.MC001 = PROD.MB017
ORDER BY R.MATL,R.PROD

SELECT 
    R.MATL AS 材料品号,
    MATL.MB002 AS 材料品名,
    MATL.MB003 AS 材料规格,
    LEFT(MATL.CREATE_DATE,8) AS 材料创建日期,
    R.PROD AS 产品品号,
    PROD.MB002 AS 产品品名,
    PROD.MB003 AS 产品规格,
    LEFT(PROD.CREATE_DATE, 8) AS 产品创建日期,
    L.LA004 AS 产品最近交易日期,
    CONCAT_WS(';',
        NULLIF(LEFT(CMSMC_SDRD.UDF01, 4), ''),
        NULLIF(LEFT(CMSMC_ZJRD.UDF01, 4), ''),
        NULLIF(LEFT(CMSMC_AHRD.UDF01, 4), ''),
        NULLIF(LEFT(CMSMC_YNRD.UDF01, 4), '')
    ) AS 默认入库事业部
FROM #RELATION R
INNER JOIN SDRD..INVMB PROD
    ON PROD.MB001 = R.PROD
INNER JOIN SDRD..INVMB MATL
    ON MATL.MB001 = R.MATL
LEFT JOIN #LAST_DATE L
    ON L.LA001 = R.PROD

LEFT JOIN ZJRD..INVMB PROD_ZJRD
    ON PROD_ZJRD.MB001 = R.PROD
LEFT JOIN AHRD..INVMB PROD_AHRD
    ON PROD_AHRD.MB001 = R.PROD
LEFT JOIN YNRD..INVMB PROD_YNRD
    ON PROD_YNRD.MB001 = R.PROD

LEFT JOIN SDRD..CMSMC CMSMC_SDRD
    ON CMSMC_SDRD.MC001 = PROD.MB017
LEFT JOIN ZJRD..CMSMC CMSMC_ZJRD
    ON CMSMC_ZJRD.MC001 = PROD_ZJRD.MB017
LEFT JOIN AHRD..CMSMC CMSMC_AHRD
    ON CMSMC_AHRD.MC001 = PROD_AHRD.MB017
LEFT JOIN YNRD..CMSMC CMSMC_YNRD
    ON CMSMC_YNRD.MC001 = PROD_YNRD.MB017

ORDER BY R.MATL, R.PROD;