SELECT I.ITEMNO 料号,
	M.MB002 品名,
	M.MB003 规格型号,
	ISNULL(
			(
				SELECT COUNT(*)
				FROM SDRD.dbo.Fn_GetBOMUpIDs(I.ITEMNO) BOM 
				WHERE LEFT(BOM.MD01,1) IN ('A','1')
			),
			0
		) AS 产品引用数量,
		ISNULL(INV2024.QTY,0) [2024年使用量],
		ISNULL(INV2025.QTY,0) [2025年使用量],
		ISNULL(INV2026.QTY,0) [2026年使用量],
		ISNULL(INV2024.QTY,0)+ISNULL(INV2025.QTY,0)+ISNULL(INV2026.QTY,0) 合计
FROM LSSJ..ITEMTMP AS I
INNER JOIN SDRD..INVMB AS M ON M.MB001 = I.ITEMNO
LEFT OUTER JOIN (
	SELECT INVLA.LA001,SUM(-1*LA005*LA011) AS QTY
	FROM(
		SELECT * FROM SDRD..INVLA WHERE LA004 BETWEEN '20240101' AND '20241231' AND LEFT(LA006,1) = '5'
		UNION ALL
		SELECT * FROM ZJRD..INVLA WHERE LA004 BETWEEN '20240101' AND '20241231' AND LEFT(LA006,1) = '5'
		UNION ALL
		SELECT * FROM AHRD..INVLA WHERE LA004 BETWEEN '20240101' AND '20241231' AND LEFT(LA006,1) = '5'
		UNION ALL
		SELECT * FROM YNRD..INVLA WHERE LA004 BETWEEN '20240101' AND '20241231' AND LEFT(LA006,1) = '5'
	) AS INVLA 
	GROUP BY LA001
) AS INV2024 ON INV2024.LA001 = I.ITEMNO
LEFT OUTER JOIN (
	SELECT INVLA.LA001,SUM(-1*LA005*LA011) AS QTY
	FROM(
		SELECT * FROM SDRD..INVLA WHERE LA004 BETWEEN '20250101' AND '20251231' AND LEFT(LA006,1) = '5'
		UNION ALL
		SELECT * FROM ZJRD..INVLA WHERE LA004 BETWEEN '20250101' AND '20251231' AND LEFT(LA006,1) = '5'
		UNION ALL
		SELECT * FROM AHRD..INVLA WHERE LA004 BETWEEN '20250101' AND '20251231' AND LEFT(LA006,1) = '5'
		UNION ALL
		SELECT * FROM YNRD..INVLA WHERE LA004 BETWEEN '20250101' AND '20251231' AND LEFT(LA006,1) = '5'
	) AS INVLA 
	GROUP BY LA001
) AS INV2025 ON INV2025.LA001 = I.ITEMNO
LEFT OUTER JOIN (
	SELECT INVLA.LA001,SUM(-1*LA005*LA011) AS QTY
	FROM(
		SELECT * FROM SDRD..INVLA WHERE LA004 BETWEEN '20260101' AND '20261231' AND LEFT(LA006,1) = '5'
		UNION ALL
		SELECT * FROM ZJRD..INVLA WHERE LA004 BETWEEN '20260101' AND '20261231' AND LEFT(LA006,1) = '5'
		UNION ALL
		SELECT * FROM AHRD..INVLA WHERE LA004 BETWEEN '20260101' AND '20261231' AND LEFT(LA006,1) = '5'
		UNION ALL
		SELECT * FROM YNRD..INVLA WHERE LA004 BETWEEN '20260101' AND '20261231' AND LEFT(LA006,1) = '5'
	) AS INVLA 
	GROUP BY LA001
) AS INV2026 ON INV2026.LA001 = I.ITEMNO
ORDER BY I.ITEMNO