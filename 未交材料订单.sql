SELECT 'SDRD' COMPANY,
TC001 订单单别,
TC002 订单单号,
TC003 订单日期,
TC004 客户编号,
MA002 客户简称,
TD003 订单序号,
TD004 品号,
MB002 品名,
MB003 规格,
TD007 仓库编号,
TD008 订单数量,
TD009 已交数量,
TD008-TD009 未交数量
FROM SDRD..COPTD
INNER JOIN SDRD..COPTC ON TC001 = TD001 AND TC002 = TD002
INNER JOIN SDRD..COPMA ON MA001 = TC004
INNER JOIN SDRD..INVMB ON MB001 = TD004
WHERE SUBSTRING(TD001,4,1) = '4' 
AND TD016 = 'N' 
AND TD021 = 'Y'
AND TC027 = 'Y'

UNION ALL
