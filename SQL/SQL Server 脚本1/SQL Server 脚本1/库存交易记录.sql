DECLARE @RQ VARCHAR(8)
SET @RQ='202508'

SELECT LA001 AS 品号,MB002 AS 品名,MB003 AS 规格,MB004 AS 单位,LA004 AS 日期,CASE LA005 WHEN '1' THEN '入库' else '出库' END AS [出/入库],LA006 AS 单别,
MQ002 AS 单据名称,LA007 AS 单号,LA008 AS 序号,LA009 AS 仓库编号,MC002 AS 仓库名称,CASE MC004 WHEN '1' THEN '存货仓' ELSE '非存货仓' END AS 仓库性质,
LA011 AS 交易数量,LA012 AS 单位成本,LA013 AS [金额],LA017 AS [金额-材料],LA018 AS [金额-人工],LA019 AS [金额-制费],LA020 AS [金额-制费],
CASE LA014 WHEN '1' THEN '入库' WHEN '2' THEN '销货' WHEN '3' THEN '领用' WHEN '4' THEN '调拨' WHEN '5' THEN '调整' END AS 交易别,
CASE LA015 WHEN 'Y' THEN '成本计算来源' WHEN 'N' THEN '赋值计算结果' WHEN 'y' THEN '成本调整' WHEN 'r' THEN '返工领' WHEN 'R' THEN '返工入' END AS 影响成本,
LA010 AS 备注,LA024 AS 对象

FROM INVLA INNER JOIN INVMB ON MB001 = LA001
INNER JOIN CMSMQ ON MQ001 = LA006
INNER JOIN CMSMC ON MC001 = LA009
WHERE  LA004 LIKE ''+@RQ+'%' --and left(LA006,1) not in('5')  --LA004 >= '20190801'-- AND LA004 <= '20190731' --AND MB002='贴片电容' --AND LA005 = '1'





