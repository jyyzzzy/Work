/*******************修改2304单头金额汇总************************/
--根据单身更新销货单头
UPDATE SDRD..COPTG
SET
	TG013 = JE1,
	TG025 = JE2,
	TG045 = JE3,
	TG046 = JE4,
	TG033=JE5
	FROM
		SDRD..COPTG
			INNER JOIN (
						   SELECT
							   TG001,
							   TG002,
							   TG013,
							   SUM(TH035) AS JE1,
							   TG025,
							   SUM(TH036) AS JE2,
							   TG045,
							   SUM(TH037) AS JE3,
							   TG046,
							   SUM(TH038) AS JE4,
							   SUM(TH008) AS JE5
							   FROM
								   SDRD..COPTG
									   INNER JOIN SDRD..COPTH
										   ON TG001 = TH001 AND TG002 = TH002
							   GROUP BY
								   TG001,
								   TG002,
								   TG013,
								   TG025,
								   TG036,
								   TG045,
								   TG046,
								   TG033
							   HAVING
								   TG013 <> SUM(TH035)
								   OR TG025 <> SUM(TH036)
								   OR TG045 <> SUM(TH037)
								   OR TG046 <> SUM(TH038)
								   OR TG033 <> SUM(TH008)
					   ) AS ZJXH
				ON COPTG.TG001 = ZJXH.TG001 AND COPTG.TG002 = ZJXH.TG002


