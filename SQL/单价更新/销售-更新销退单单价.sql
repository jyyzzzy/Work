--更新销退单单头
UPDATE COPTI
SET
	TI010=COP.TI010,--原币销退金额
	TI011=COP.TI011, --原币销退税额
	TI037=COP.TI037,--本币销退金额
	TI038=COP.TI038--本币销退税额
	FROM
		(
			SELECT
				TJ001,
				TJ002,
				TI010=SUM(TJ012),
				TI011=SUM(TJ032),
				TI037= SUM(TJ033),
				TI038=SUM(TJ034)
				FROM
					COPTJ
						--INNER JOIN LSSJ..zjcgrk
						--	ON cgdh LIKE TJ001 + '-' + TJ002 + '%'

				GROUP BY
					TJ001,
					TJ002
		) AS COP
			JOIN COPTI
				ON TJ001 = COPTI.TI001 AND COPTI.TI002 = TJ002
	WHERE
		COPTI.TI003 BETWEEN '20260301' AND  '20260331' 
		AND (
			COPTI.TI010 <> COP.TI010--原币销退金额
			OR COPTI.TI011 <> COP.TI011 --原币销退税额
			OR COPTI.TI037 <> COP.TI037--本币销退金额
			OR COPTI.TI038 <> COP.TI038--本币销退税额
		);


