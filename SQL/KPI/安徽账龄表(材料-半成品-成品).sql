--安徽半成品帐龄检视表
SELECT  MB007,MA003,CLZL001, CLZL002, CLZL003,-- CLZL004, CLZL005, CLZL006, CLZL007, CLZL008, CLZL009, CLZL010,
CLZL011, CLZL012, CLZL013, CLZL014,
CLZL015,
CLZL016, CLZL017, CLZL018,
CC.MC001+ CC.MC002 AS CLZL020,CLZL021,
CASE WHEN ISNULL(B.PH,'')='' AND CC.UDF01 NOT LIKE '%安徽一厂%' THEN CLZL015 ELSE 0 END '安徽三厂',
CASE WHEN ISNULL(B.PH,'')<>''  or CC.UDF01   LIKE '%安徽一厂%' THEN CLZL015 ELSE 0 END '安徽一厂金额',B.PH
FROM web_lnk.RDSJK.dbo.AHCLZLB 
JOIN  AHRD..INVMB on MB001=CLZL001 
LEFT join AHRD..INVMA on MB007=MA002
LEFT JOIN  LSSJ..AHYGPH B ON CLZL001=B.PH
JOIN AHRD..CMSMC CC ON CC.MC001=CLZL020
WHERE left(CLZL001,1)='2' AND (CLZL017 = '2026/11/3')
order by MB007,CLZL001,CLZL021 desc,CLZL004,CLZL014,CLZL017,CLZL018 DESC;

 
---安徽成品账龄检视表
select MB007,MA003,CPZL001, CPZL002, CPZL003, CPZL004,
CPZL005, CPZL007, CPZL008,  CPZL010, CPZL011, CPZL012, CPZL013, CPZL014, CPZL015, CPZL016, CPZL017, CPZL018,
CC.MC001+ CC.MC002  as CPZL020,
CPZL021,ISNULL(ZLDZ04,'') AS ZLDZ04,ISNULL(ZLDZ05,'') AS ZLDZ05,ISNULL(ZLDZ06,'') AS ZLDZ06,ISNULL(CPZL026,'') AS CPZL026,
ISNULL(COP.UDF04,'') AS UDF04,ISNULL(COP.UDF01,'') AS UDF01,ISNULL(COP.UDF02,'') AS UDF02,ISNULL(COP.UDF03,'') AS UDF03,
CASE WHEN ISNULL(B.PH,'')='' AND  CC.UDF01 NOT LIKE '%安徽一厂%'THEN CPZL015 ELSE 0 END '安徽三厂',
CASE WHEN ISNULL(B.PH,'')<>'' OR  CC.UDF01 LIKE '%安徽一厂%'THEN CPZL015 ELSE 0 END '安徽一厂金额'
FROM web_lnk.RDSJK.dbo.AHCPZLB 
JOIN  AHRD..INVMB on MB001=CPZL001 
LEFT join AHRD..INVMA on MB007=MA002 
LEFT JOIN ( select distinct ZLDZ02,ZLDZ04 ,ZLDZ05,ZLDZ06,ZLDZ03 from  web_lnk.RDSJK.dbo.ZLDZYY  
JOIN ( select ZLDZ02 ZLDZ2,MAX(ZLDZ03) ZLDZ3 from  web_lnk.RDSJK.dbo.ZLDZYY where ZLDZ01='AHRD' GROUP BY ZLDZ02) as dz on ZLDZ02=ZLDZ2 and ZLDZ3 =ZLDZ03 where ZLDZ01='AHRD' ) dz ON   CPZL001=ZLDZ02  and left(convert(varchar, CPZL016,112),6)<=left(convert(varchar ,DATEADD(month,-3 ,ZLDZ03),112),6) left join AHRD..COPTD COP on TD001=LEFT(CPZL026,4) AND  TD002= RIGHT(CPZL026,11) AND TD003='0001' AND TD004=MB001
LEFT JOIN  LSSJ..AHYGPH B ON CPZL001=B.PH
LEFT JOIN AHRD..CMSMC CC ON CC.MC001=CPZL020
WHERE (CPZL017 = '2026/11/3');




