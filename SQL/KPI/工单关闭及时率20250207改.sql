WITH DateNumbers AS (
    SELECT 
        ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS rn 
    FROM (
        SELECT TOP 50 1 AS dummy FROM master..spt_values 
    ) t 
)
,RKDate as (
SELECT 
    convert(varchar,DATEADD(DAY, rn - 1,DATEADD(day,-5,'20260201') ) ,112) AS [RDate],rn
FROM DateNumbers 

)
,RKSJ as (
select TF003,TG014,TG015,SUM(TG011) TG011 from MOCTF JOIN MOCTG ON TF001=TG001 AND TG002=TF002 WHERE TF006='Y' AND TF003>=convert(varchar, DATEADD(day,3,'20260201') ,112) AND TF003<='20260231' GROUP BY TF003,TG014,TG015
)
,GDRQ as
(
select * from RKDate,(select DISTINCT TG014 TG14,TG015 TG15 from  RKSJ ) A  WHERE [RDate]<='20260231'
)
