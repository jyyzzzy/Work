ALTER VIEW [dbo].[CGDJ]
AS 
SELECT CGYDJ.YDJ001,CGYDJ.YDJ002,CGYDJ.YDJ003,CGYDJ.YDJ004,CGYDJ.YDJ005,case when YDJ006<>0 then 0 else ISNULL(CGYDJ01.YDJ005,0) end  AS YDJ006,case when YDJ006<>0 then 0 else ISNULL(isnull(CGYDJ02.YDJ005,CGYDJ05.YDJ005),0)  end  AS  YDJ007,case when YDJ006<>0 then 0 else ISNULL(CGYDJ03.YDJ005,0) end  AS  YDJ008 FROM RDSJK..CGYDJ
LEFT JOIN (SELECT YDJ001,YDJ002,YDJ005 FROM RDSJK..CGYDJ WHERE YDJ002+YDJ001 IN ( SELECT YDJ002+MAX(YDJ001) AS YDJ001 FROM RDSJK..CGYDJ 
