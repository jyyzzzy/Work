/**********************************导 顺德采购及时率*********************************************/
SELECT DISTINCT TC001+'-'+TC002+'-'+TD003,TC004,MA003,TC003,TD012,TD004,TD005,TD006,TD008,ISNULL(SL,0),
TD016,CASE TD016 WHEN 'y' THEN ISNULL(TE004,'') ELSE '' END,CASE WHEN ISNULL(SL,0) > 0.8*TD008 THEN 'Y' ELSE 'N' END
FROM SDRD..PURTC INNER JOIN SDRD..PURTD ON TC001 = TD001 AND TC002 = TD002
INNER JOIN SDRD..PURMA ON MA001 = TC004
LEFT JOIN (
SELECT TH011,TH012,TH013,SUM(TH015) AS SL
FROM SDRD..PURTC INNER JOIN SDRD..PURTD ON TC001 = TD001 AND TC002 = TD002
LEFT JOIN SDRD..PURTH ON TD001 = TH011 AND TD002 = TH012 AND TD003 = TH013
WHERE TD018 = 'Y' AND TH014 <= TD012
GROUP BY TH011,TH012,TH013) AS JHHZB
ON TD001 = TH011 AND TD002 = TH012 AND TD003 = TH013
LEFT JOIN 
(SELECT TE001,TE002,TF003,MAX(TE004) AS TE004 FROM SDRD..PURTE LEFT JOIN SDRD..PURTF ON TE001 = TF001 AND TE002 = TF002 
WHERE (TE012 = 'Y' OR TF014 = 'Y') AND TE017 = 'Y' GROUP BY TE001,TE002,TF003) AS CGDGX
ON TD001 = TE001 AND TD002 = TE002
WHERE TD018 = 'Y' AND TD012 >='20260201' AND TD012 <='20260231'




