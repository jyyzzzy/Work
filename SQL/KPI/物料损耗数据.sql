SELECT LS001 AS SH001,LS002 AS SH002,LS003 AS SH003,LS004 AS SH004,LS005 AS SH005,LS006 AS SH006,LS007 AS SH007,
LS008 AS SH008,LS009 AS SH009,LS010 AS SH010,LS011 AS SH011,LS012 AS SH012,LS013 AS SH013,LS014 AS SH014,LS015 AS SH015,SUM(LS016) AS SH016,
SUM(LS017) AS SH017,SUM(LS018) AS SH018,case SUM(LS018) when 0 then 0 else SUM(LS019)end AS SH019,case SUM(LS018) when 0 then 0 else SUM(LS020) end AS SH020,
case SUM(LS018) when 0 then 0 else SUM(LS021)end AS SH021,case SUM(LS018) when 0 then 0 else SUM(LS022)end AS SH022,LS023 AS SH023,
case SUM(LS018) when 0 then 0 else SUM(LS025)end AS SH025,case SUM(LS018) when 0 then 0 else SUM(LS026)end AS SH026,case SUM(LS018) when 0 then 0 else SUM(LS027)end AS SH027,
case SUM(LS018) when 0 then 0 else SUM(LS028)end AS SH028,case SUM(LS018) when 0 then 0 else SUM(LS029) end AS SH029,case SUM(LS018) when 0 then 0 else SUM(LS030)end AS SH030
,TB006,MW002
FROM 
(


SELECT MOCTA.TA021 AS LS001,CMSMD.MD002 AS LS002,MOCTA.TA001 AS LS003,MOCTA.TA002 AS LS004,MOCTA.TA003 AS LS005,
MOCTA.TA014 AS LS006,MOCTA.TA006 AS LS007,MOCTA.TA034 AS LS008,MOCTA.TA035 AS LS009,MOCTA.TA015 AS LS010,MOCTA.TA017 AS LS011,
MOCTB.TB003 AS LS012,INVMB.MB002 AS LS013,INVMB.MB003 AS LS014,CASE WHEN SUBSTRING(INVMB.MB001,1,1)< '3' THEN INVMB.MB057*1.17 ELSE INVMB.UDF54 END AS LS015,
CASE MOCTA.TA015 WHEN 0 THEN 0 ELSE MOCTB.TB004*MOCTA.TA017/MOCTA.TA015 END AS LS016,CASE MOCTA.TA015 WHEN 0 THEN MOCTB.TB004 ELSE MOCTB.TB004/MOCTA.TA015 END AS LS017,
0 AS LS018,0 AS LS019,0 AS LS020,0 AS LS021,0 AS LS022,  --实领数量，开发原因，生产原因，材料原因，其它原因
--CASE WHEN MOCTA.TA017 < MOCTA.TA015 THEN MOCTB.TB005 - (MOCTB.TB004/MOCTA.TA015)*MOCTA.TA017 ELSE MOCTB.TB005 - MOCTB.TB004 END AS LS023,
INVMB.MB004 AS LS023,
0 AS LS025,0 AS LS026,0 AS LS027,0 AS LS028,0 AS LS029,0 AS LS030 ----工程原因，市场原因，自动化原因，品质原因，仓库原因，供应商原因、报废
,TB006,MW002
FROM SDRD..MOCTA INNER JOIN SDRD..MOCTB ON  MOCTA.TA001 = MOCTB.TB001 AND MOCTA.TA002 = MOCTB.TB002
INNER JOIN SDRD..CMSMD ON MOCTA.TA021 = CMSMD.MD001
INNER JOIN SDRD..INVMB ON MOCTB.TB003 = INVMB.MB001
LEFT JOIN SDRD..CMSMW ON TB006=MW001
WHERE MOCTA.TA011 = 'Y' OR MOCTA.TA011 = 'y'
UNION ALL
--领料数量
SELECT MOCTA.TA021,CMSMD.MD002,MOCTA.TA001,MOCTA.TA002,MOCTA.TA003,MOCTA.TA014,MOCTA.TA006,MOCTA.TA034,MOCTA.TA035,MOCTA.TA015,MOCTA.TA017,
MOCTE.TE004,INVMB.MB002,INVMB.MB003,CASE WHEN SUBSTRING(INVMB.MB001,1,1)< '3' THEN INVMB.MB057*1.17 ELSE INVMB.UDF54 END,
0,0,
MOCTE.TE005,
0,0,0,0, --开发原因，生产原因，材料原因，其它原因
INVMB.MB004
,0,0,0,0,0,0---工程原因，市场原因，自动化原因，品质原因，仓库原因，供应商原因、报废
,TE009,MW002
FROM SDRD..MOCTE INNER JOIN SDRD..MOCTC ON MOCTE.TE001 = MOCTC.TC001 AND MOCTE.TE002 = MOCTC.TC002
INNER JOIN SDRD..MOCTA ON MOCTE.TE011 = MOCTA.TA001 AND MOCTE.TE012 = MOCTA.TA002
INNER JOIN SDRD..CMSMD ON MOCTA.TA021 = CMSMD.MD001
INNER JOIN SDRD..INVMB ON MOCTE.TE004 = INVMB.MB001
LEFT JOIN SDRD..CMSMW ON TE009=MW001
WHERE (MOCTA.TA011 = 'Y' OR MOCTA.TA011 = 'y') AND MOCTE.TE019 = 'Y' 
AND MOCTE.TE001 like '54%'

) AS WLSHLS GROUP BY LS001,LS002,LS003,LS004,LS005,LS006,LS007,LS008,LS009,LS010,LS011,LS012,LS013,LS014,LS015,LS023,TB006,MW002


