

SELECT WHSSH.SH001 as 工作中心编号,WHSSH.SH002 as 工作中心名称,WHSSH.SH003 as 工单单别,WHSSH.SH004 as 工单单号,
WHSSH.SH005 as 单据日期,WHSSH.SH006 as 完工日期,WHSSH.SH007 as 产品品号,WHSSH.SH008 as 产品名称,WHSSH.SH009 as 产品规格,
WHSSH.SH010 as 预计产量,WHSSH.SH011 as 入库数量,WHSSH.SH012 as 材料品号,WHSSH.SH013 as 材料品名,WHSSH.SH014 as 材料规格,
WHSSH.SH015 as 单位标准成本,WHSSH.SH016 as 需领用量,WHSSH.SH017 as 单位用量,WHSSH.SH018 as 实领数量,
case WHSSH.SH018 when 0 then 0 else WHSSH.SH018-WHSSH.SH016 end as 超领数量,WHSSH.SH019 as 开发原因,
WHSSH.SH020 as 生产原因,WHSSH.SH021 as 材料原因,WHSSH.SH022 as 其它原因,WHSSH.SH025 as 工程原因,
WHSSH.SH026 as 市场原因,WHSSH.SH027 as 自动化原因,WHSSH.SH028 as 品质原因,WHSSH.SH029 as 仓库原因,
WHSSH.SH030 as [供应商原因、报废],
case WHSSH.SH018 when 0 then 0 else  WHSSH.SH018-WHSSH.SH019-WHSSH.SH020-WHSSH.SH021-WHSSH.SH022-WHSSH.SH025-WHSSH.SH026-WHSSH.SH027-WHSSH.SH028-WHSSH.SH016-WHSSH.SH029-WHSSH.SH030 end as 未退数量,
WHSSH.SH023 as 单位,isnull(TB006,'') 工艺,isnull(MW002,'') 工艺名称  FROM WHSSH as WHSSH   WHERE ( ( (LEFT(WHSSH.SH006,6) = '202605' ) ) ) 
	--and WHSSH.SH002  like '%SMT%'
ORDER BY WHSSH.SH001 asc,WHSSH.SH002 asc,WHSSH.SH003 asc,WHSSH.SH004 asc



SELECT  SYB,SUM(PRODUCTCOST) FROM (
SELECT C.TA003+'-'+C.TA004 AS TA003C,(C.TA026+C.TA027+C.TA028+C.TA029) AS PRODUCTCOST, M.TA020 AS TA36789, LEFT(MD011,4) SYB,MD002
FROM CSTTA AS  C 
LEFT JOIN MOCTA AS M ON M.TA001=C.TA003 AND M.TA002=C.TA004 LEFT JOIN INVMB AS INVMB ON MB001=C.TA001 LEFT JOIN CMSMF AS CMSMF ON MF001= 'RMB' 
LEFT JOIN CMSMD ON M.TA021=MD001

WHERE (C.TA002='202601' AND (C.TA023<>0 OR C.TA024<>0 OR C.TA031<>0 OR C.TA026<>0 OR C.TA027<>0 OR C.TA028<>0 OR C.TA029<>0)) 

) AS B GROUP BY SYB




