SELECT TB016 审核码,TB003 序号, TA003 AS 凭证日期,TB001+'-'+TB002 AS 凭证号,TB005 AS 会计科目,ACTMA.MA026 AS 科目名称,TB010 AS 摘要,TB006 AS 部门编号,
ISNULL(ME002,'') AS 部门名称,TB008 AS 核算项目一编号,TB017 AS 核算项目名称一,TB009 AS 核算项目二编号,TB018 AS 核算项目名称二,CASE TB004 WHEN '1' THEN TB007 ELSE 0 END AS 借方金额,
CASE TB004 WHEN '-1' THEN TB007 ELSE 0 END AS 贷方金额,TB031 AS 客户代码,ISNULL(COPMA.MA003,'') AS 客户名称,
TB032 AS 供应商代码,ISNULL(PURMA.MA003,'') AS 供应商名称,TB033 AS 人员,ISNULL(MV002,'') AS 人员名称,
TB024 AS 结算日期,TB022 AS 结算方式,TB023 AS 结算号

FROM ACTTB INNER JOIN ACTTA ON TA001 = TB001 AND TA002 = TB002 INNER JOIN ACTMA ON ACTMA.MA001 = TB005
LEFT JOIN CMSME ON ME001 = TB006
LEFT JOIN COPMA ON COPMA.MA001 = TB031
LEFT JOIN PURMA ON PURMA.MA001 = TB032
LEFT JOIN CMSMV ON MV001 = TB033
WHERE TA003 >='20250101' AND TA003 <= '20251231'
AND TB016 = 'Y'  --AND TB033 = '10089390'
ORDER BY TA003, TB001,TB002,TB003
