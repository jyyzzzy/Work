SELECT 
	PURTC.TC009 SCM单号
	,PURTD.TD001 采购单别
	,PURTD.TD002 采购单号
	,PURTD.TD003 采购序号
	,PURTD.TD004 材料品号
	,PURTD.TD005 材料品名
	,PURTD.TD006 材料规格
	,PURTB.TB001 请购单别
	,PURTB.TB002 请购单号
	,PURTB.TB003 请购序号
	,MOCTA.TA001 工单单别
	,MOCTA.TA002 工单单号
	,COPTD.TD001 订单单别
	,COPTD.TD002 订单单号
	,COPTD.TD003 订单序号
	,COPTD.TD004 产品品号
	,COPTD.TD005 产品品名
	,COPTD.TD006 产品规格
	,COPMA.MA001 客户编号
	,COPMA.MA002 客户简称
	,COPMA.MA003 客户全称
	,COPTC.UDF06 CRM单号
FROM LSSJ..ITEMTMP I
INNER JOIN PURTC ON PURTC.TC009 = I.NOTE
INNER JOIN PURTD ON PURTD.TD001 = PURTC.TC001 AND PURTD.TD002 = PURTC.TC002 AND PURTD.TD004 = I.ITEMNO
INNER JOIN PURTB ON PURTB.TB001 = PURTD.TD026 AND PURTB.TB002 = PURTD.TD027 AND PURTB.TB003 = PURTD.TD028
INNER JOIN MOCTA ON MOCTA.TA001 = TB029 AND MOCTA.TA002 = TB030
INNER JOIN COPTD ON COPTD.TD001 = MOCTA.TA026 AND COPTD.TD002 = MOCTA.TA027 AND COPTD.TD003 = MOCTA.TA028
INNER JOIN COPTC ON COPTC.TC001 = COPTD.TD001 AND COPTC.TC002 = COPTD.TD002
INNER JOIN COPMA ON COPMA.MA001 = COPTC.TC004
ORDER BY PURTC.TC009,PURTD.TD004,PURTD.TD002,PURTD.TD003