SELECT
    X.材料品号 AS [现用料号],
    B.MB002 AS [材料品名],
    B.MB003 AS [材料规格],
    B.MB004 AS [材料单位],
    X.现用型号,
    X.客户编号,
    X.客户简称,
    X.产品品号,
    P.MB002 AS [产品品名],
    P.MB003 AS [产品规格],
    X.事业部,
    SUM(X.领退料数量) AS [2026年1-10月领退料净数量]
FROM
(
    -- 顺德瑞德
    SELECT
        M.材料品号,
        M.现用型号,
        O.TC004 AS 客户编号,
        COALESCE(NULLIF(RTRIM(C.MA002), ''), C.MA003) AS 客户简称,
        D.TD004 AS 产品品号,
        ISNULL(NULLIF(LTRIM(RTRIM(LEFT(W.MD011, CHARINDEX('-', W.MD011 + '-') - 1))), ''), N'顺德瑞德') AS 事业部,
        CASE WHEN LEFT(E.TE001, 2) = '54' THEN E.TE005 ELSE -E.TE005 END AS 领退料数量
    FROM SDRD.dbo.MOCTE E WITH(NOLOCK)
    JOIN SDRD.dbo.MOCTC H WITH(NOLOCK)
      ON H.TC001 = E.TE001 AND H.TC002 = E.TE002
    JOIN #MAT M ON M.材料品号 = E.TE004
    JOIN SDRD.dbo.MOCTA A WITH(NOLOCK)
      ON A.TA001 = E.TE011 AND A.TA002 = E.TE012
    LEFT JOIN SDRD.dbo.MOCTA S WITH(NOLOCK)
      ON S.TA001 = A.TA024 AND S.TA002 = A.TA025
    LEFT JOIN SDRD.dbo.COPTC O WITH(NOLOCK)
      ON O.TC001 = COALESCE(NULLIF(RTRIM(A.TA026), ''), NULLIF(RTRIM(S.TA026), ''))
     AND O.TC002 = COALESCE(NULLIF(RTRIM(A.TA027), ''), NULLIF(RTRIM(S.TA027), ''))
    LEFT JOIN SDRD.dbo.COPTD D WITH(NOLOCK)
      ON D.TD001 = O.TC001
     AND D.TD002 = O.TC002
     AND D.TD003 = COALESCE(NULLIF(RTRIM(A.TA028), ''), NULLIF(RTRIM(S.TA028), ''))
    LEFT JOIN SDRD.dbo.COPMA C WITH(NOLOCK)
      ON C.MA001 = O.TC004
    LEFT JOIN SDRD.dbo.CMSMD W WITH(NOLOCK)
      ON W.MD001 = A.TA021
    WHERE H.TC003 >= '20260101'
      AND H.TC003 < '20261101'
      AND E.TE019 = 'Y'
      AND (E.TE001 LIKE '54%' OR E.TE001 LIKE '56%')

    UNION ALL

    -- 浙江瑞德
    SELECT
        M.材料品号,
        M.现用型号,
        O.TC004 AS 客户编号,
        COALESCE(NULLIF(RTRIM(C.MA002), ''), C.MA003) AS 客户简称,
        D.TD004 AS 产品品号,
        N'浙江瑞德' AS 事业部,
        CASE WHEN LEFT(E.TE001, 2) = '54' THEN E.TE005 ELSE -E.TE005 END AS 领退料数量
    FROM ZJRD.dbo.MOCTE E WITH(NOLOCK)
    JOIN ZJRD.dbo.MOCTC H WITH(NOLOCK)
      ON H.TC001 = E.TE001 AND H.TC002 = E.TE002
    JOIN #MAT M ON M.材料品号 = E.TE004
    JOIN ZJRD.dbo.MOCTA A WITH(NOLOCK)
      ON A.TA001 = E.TE011 AND A.TA002 = E.TE012
    LEFT JOIN ZJRD.dbo.MOCTA S WITH(NOLOCK)
      ON S.TA001 = A.TA024 AND S.TA002 = A.TA025
    LEFT JOIN ZJRD.dbo.COPTC O WITH(NOLOCK)
      ON O.TC001 = COALESCE(NULLIF(RTRIM(A.TA026), ''), NULLIF(RTRIM(S.TA026), ''))
     AND O.TC002 = COALESCE(NULLIF(RTRIM(A.TA027), ''), NULLIF(RTRIM(S.TA027), ''))
    LEFT JOIN ZJRD.dbo.COPTD D WITH(NOLOCK)
      ON D.TD001 = O.TC001
     AND D.TD002 = O.TC002
     AND D.TD003 = COALESCE(NULLIF(RTRIM(A.TA028), ''), NULLIF(RTRIM(S.TA028), ''))
    LEFT JOIN ZJRD.dbo.COPMA C WITH(NOLOCK)
      ON C.MA001 = O.TC004
    WHERE H.TC003 >= '20260101'
      AND H.TC003 < '20261101'
      AND E.TE019 = 'Y'
      AND (E.TE001 LIKE '54%' OR E.TE001 LIKE '56%')

    UNION ALL

    -- 安徽瑞德
    SELECT
        M.材料品号,
        M.现用型号,
        O.TC004 AS 客户编号,
        COALESCE(NULLIF(RTRIM(C.MA002), ''), C.MA003) AS 客户简称,
        D.TD004 AS 产品品号,
        ISNULL(NULLIF(LTRIM(RTRIM(LEFT(W.MD011, CHARINDEX('-', W.MD011 + '-') - 1))), ''), N'安徽瑞德') AS 事业部,
        CASE WHEN LEFT(E.TE001, 2) = '54' THEN E.TE005 ELSE -E.TE005 END AS 领退料数量
    FROM AHRD.dbo.MOCTE E WITH(NOLOCK)
    JOIN AHRD.dbo.MOCTC H WITH(NOLOCK)
      ON H.TC001 = E.TE001 AND H.TC002 = E.TE002
    JOIN #MAT M ON M.材料品号 = E.TE004
    JOIN AHRD.dbo.MOCTA A WITH(NOLOCK)
      ON A.TA001 = E.TE011 AND A.TA002 = E.TE012
    LEFT JOIN AHRD.dbo.MOCTA S WITH(NOLOCK)
      ON S.TA001 = A.TA024 AND S.TA002 = A.TA025
    LEFT JOIN AHRD.dbo.COPTC O WITH(NOLOCK)
      ON O.TC001 = COALESCE(NULLIF(RTRIM(A.TA026), ''), NULLIF(RTRIM(S.TA026), ''))
     AND O.TC002 = COALESCE(NULLIF(RTRIM(A.TA027), ''), NULLIF(RTRIM(S.TA027), ''))
    LEFT JOIN AHRD.dbo.COPTD D WITH(NOLOCK)
      ON D.TD001 = O.TC001
     AND D.TD002 = O.TC002
     AND D.TD003 = COALESCE(NULLIF(RTRIM(A.TA028), ''), NULLIF(RTRIM(S.TA028), ''))
    LEFT JOIN AHRD.dbo.COPMA C WITH(NOLOCK)
      ON C.MA001 = O.TC004
    LEFT JOIN AHRD.dbo.CMSMD W WITH(NOLOCK)
      ON W.MD001 = A.TA021
    WHERE H.TC003 >= '20260101'
      AND H.TC003 < '20261101'
      AND E.TE019 = 'Y'
      AND (E.TE001 LIKE '54%' OR E.TE001 LIKE '56%')

    UNION ALL

    -- 越南瑞德
    SELECT
        M.材料品号,
        M.现用型号,
        O.TC004 AS 客户编号,
        COALESCE(NULLIF(RTRIM(C.MA002), ''), C.MA003) AS 客户简称,
        D.TD004 AS 产品品号,
        N'越南瑞德' AS 事业部,
        CASE WHEN LEFT(E.TE001, 2) = '54' THEN E.TE005 ELSE -E.TE005 END AS 领退料数量
    FROM YNRD.dbo.MOCTE E WITH(NOLOCK)
    JOIN YNRD.dbo.MOCTC H WITH(NOLOCK)
      ON H.TC001 = E.TE001 AND H.TC002 = E.TE002
    JOIN #MAT M ON M.材料品号 = E.TE004
    JOIN YNRD.dbo.MOCTA A WITH(NOLOCK)
      ON A.TA001 = E.TE011 AND A.TA002 = E.TE012
    LEFT JOIN YNRD.dbo.MOCTA S WITH(NOLOCK)
      ON S.TA001 = A.TA024 AND S.TA002 = A.TA025
    LEFT JOIN YNRD.dbo.COPTC O WITH(NOLOCK)
      ON O.TC001 = COALESCE(NULLIF(RTRIM(A.TA026), ''), NULLIF(RTRIM(S.TA026), ''))
     AND O.TC002 = COALESCE(NULLIF(RTRIM(A.TA027), ''), NULLIF(RTRIM(S.TA027), ''))
    LEFT JOIN YNRD.dbo.COPTD D WITH(NOLOCK)
      ON D.TD001 = O.TC001
     AND D.TD002 = O.TC002
     AND D.TD003 = COALESCE(NULLIF(RTRIM(A.TA028), ''), NULLIF(RTRIM(S.TA028), ''))
    LEFT JOIN YNRD.dbo.COPMA C WITH(NOLOCK)
      ON C.MA001 = O.TC004
    WHERE H.TC003 >= '20260101'
      AND H.TC003 < '20261101'
      AND E.TE019 = 'Y'
      AND (E.TE001 LIKE '54%' OR E.TE001 LIKE '56%')
) X
INNER JOIN SDRD.dbo.INVMB B WITH(NOLOCK)
  ON B.MB001 = X.材料品号
LEFT JOIN SDRD.dbo.INVMB P WITH(NOLOCK)
  ON P.MB001 = X.产品品号
GROUP BY
    X.材料品号,
    X.现用型号,
    X.客户编号,
    X.客户简称,
    X.产品品号,
    P.MB002,
    P.MB003,
    X.事业部,
    B.MB002,
    B.MB003,
    B.MB004
ORDER BY
    X.材料品号,
    X.事业部,
    X.客户编号,
    X.产品品号;
