	INVMB.MB002 品名,
	INVMB,MB003 规格,
	PURMB.MB002,
	PURMB.MB003,
	PURMB.MB004,
	PURMB.MB005,
	PURMB.MB007,
	PURMB.MB008,
	PURMB.MB009,
	PURMB.MB0010,
	PURMB.MB0011,
	PURMB.MB0012,
	PURMB.MB0013,
	PURMB.MB0014,
	PURMB.MB0015,
	PURMB.MB0016
FROM PURMB
