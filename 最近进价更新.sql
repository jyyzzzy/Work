UPDATE INVMB
SET INVMB.MB049 = PURMB.MB011,
INVMB.MB050 = PURMB.MB011
--SELECT INVMB.MB001,PURMB.MB011,INVMB.MB049,INVMB.MB050
FROM INVMB INNER JOIN 
(
	SELECT TOP (1) WITH TIES MB001, MB011--,*
	FROM PURMB
	ORDER BY ROW_NUMBER() OVER (PARTITION BY MB001 ORDER BY CREATE_DATE DESC)
) AS PURMB ON INVMB.MB001 = PURMB.MB001
WHERE INVMB.MB049 <> PURMB.MB011
OR INVMB.MB050 <> PURMB.MB011

