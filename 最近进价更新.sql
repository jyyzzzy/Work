--SELECT INVMB.MB050,CAST(INVMB.MB049 / 0.000266 AS NUMERIC(17,6)),MB001,MB002,MB048
FROM INVMB
WHERE NOT EXISTS(
	SELECT 1 FROM PURMB WHERE PURMB.MB001 = INVMB.MB001
)
AND INVMB.MB048 = 'RMB'
--AND MB050 > 100

