SELECT 
	--LEFT(TC003,6) AS 领料年月,
	TE004 AS 材料品号,
	MB002 材料品名,
	MB003 材料规格,
	MB004 材料单位,
	SUM(
		CASE LEFT(TC001,2)
			WHEN '54' THEN 1
			WHEN '56' THEN -1
			ELSE 0
		END
		*
		TE005
	) AS 领料数量
FROM MOCTE
	INNER JOIN MOCTC ON TC001 = TE001 AND TC002 = TE002
	INNER JOIN INVMB ON MB001 = TE004
	INNER JOIN LSSJ..ITEMTMP ON ITEMNO = TE004
WHERE 1=1
	--AND LEFT(TC001,2) = '54'
	AND TC003 BETWEEN '20250101' AND '20251231'
	AND TC009 = 'Y'
	--AND MB003 LIKE '%光颉%'
GROUP BY --LEFT(TC003,6),
	TE004,
	MB002,
	MB003,
	MB004
ORDER BY --LEFT(TC003,6),
TE004
