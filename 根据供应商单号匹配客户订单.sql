/******依SCM采购订单号与材料品号查询客户订单******/
/*
	采购单->请购单->工单->客户订单
*/
SELECT DISTINCT PURTD.TD001 AS 采购订单单别,
	PURTD.TD002 采购订单单号,
	PURTD.TD003 采购订单序号,
	ITEMNO 材料品号,
	MATL.MB002 材料品名,
	MATL.MB003 材料规格,
	MATL.MB004 材料单位,
	COPTD.TD001 客户订单单别,
	COPTD.TD002 客户订单单号,
	COPTD.TD003 客户订单序号,
	COPTC.TC004 客户编号 ,
	COPMA.MA002 客户简称,
	COPMA.MA015 部门编号,
	CMSME.ME002 部门名称,
	COPTD.TD004 产品品号,
	PROD.MB002 产品品名,
	PROD.MB003 产品规格,
	PROD.MB004 产品单位,
	NOTE + '-' + ITEMNO [KEY]
FROM LSSJ..ITEMTMP 
	LEFT OUTER JOIN PURTC ON  PURTC.TC009 = NOTE
	LEFT OUTER JOIN PURTD ON PURTD.TD001 = PURTC.TC001 AND PURTD.TD002 = PURTC.TC002 AND PURTD.TD004 = ITEMNO
	LEFT OUTER JOIN PURTB ON PURTB.TB001 = PURTD.TD026 AND PURTB.TB002 = PURTD.TD027 AND PURTB.TB003 = PURTD.TD028
	LEFT OUTER JOIN MOCTA ON MOCTA.TA001 = PURTB.TB029 AND MOCTA.TA002 = PURTB.TB030
	LEFT OUTER JOIN COPTD ON COPTD.TD001 = MOCTA.TA026 AND COPTD.TD002 = MOCTA.TA027 AND COPTD.TD003 = MOCTA.TA028
	LEFT OUTER JOIN COPTC ON COPTC.TC001 = COPTD.TD001 AND COPTC.TC002 = COPTD.TD002
	LEFT OUTER JOIN COPMA ON COPMA.MA001 = COPTC.TC004
	LEFT OUTER JOIN CMSME ON CMSME.ME001 = COPMA.MA015
	LEFT OUTER JOIN INVMB AS MATL ON MATL.MB001 = ITEMNO
	LEFT OUTER JOIN INVMB AS PROD ON PROD.MB001 = COPTD.TD004
ORDER BY ITEMNO,COPTD.TD004



