select TC001,TC002,'WMS:'+TC001+'-'+TC002+'-'+status+'|ERP:'+ERPTC001+'-'+ERPTC002+'-'+TC009 
from(
	select distinct WMS.TC001,WMS.TC002,WMS.status, ERP.TC001 ERPTC001, ERP.TC002 ERPTC002,ERP.TC009 
	from
	(
		select TC001,TC002,TC003,TE003,TE004,TE005,TE008,MOCTCFROMWMS.status 
		from SDRD.dbo.MOCTCFROMWMS (nolock) 
		join SDRD.dbo.MOCTEFROMWMS (nolock) on TC001=TE001 and TC002=TE002
	)WMS 
	join 
	(
		select TC001,TC002,TE003,TE004,TE005,TE008,TE019,TC009,TE011,TE012,MOCTC.CREATOR 
		from SDRD.dbo.MOCTC (nolock) 
		join SDRD.dbo.MOCTE (nolock) on TC001=TE001 and TC002=TE002
	)ERP on WMS.TC001=ERP.TC001 and WMS.TC002=ERP.TC002 and WMS.TE003=ERP.TE003 
	WHERE TC009<>'Y' --and TC009<>'V' 
	AND WMS. TE005>0 
	and WMS.TC002 like '20%' 
	-- AND WMS.status='Y'
	and WMS.TC002>'202601'
	union all
	select distinct WMS.TC001,WMS.TC002,WMS.status, ERP.TC001 ERPTC001, ERP.TC002 ERPTC002,ERP.TC009 
	from 
	(
		select TC001,TC002,TC003,TE003,TE004,TE005,TE008,MOCTCFROMWMS.status 
		from SDRD.dbo.MOCTCFROMWMS (nolock) 
		join SDRD.dbo.MOCTEFROMWMS (nolock) on TC001=TE001 and TC002=TE002
	) WMS 
	join 
	(
		select TC001,TC002,TE003,TE004,TE005,TE008,TE019,TC009,TC007,TE011,TE012 
		from SDRD.dbo.MOCTC (nolock) join SDRD.dbo.MOCTE (nolock) on TC001=TE001 and TC002=TE002
	) ERP on WMS.TC001=ERP.TC001 and WMS.TC002=ERP.TC007 and WMS.TE003=ERP.TE003 and TC009<>'Y'  and (WMS.TC002 like 'W%' or  WMS.TC002 like 'F%' ) --AND WMS.status='Y' 
	WHERE  WMS.TC003>'20260101'
	--and TC009<>'V'
) A;