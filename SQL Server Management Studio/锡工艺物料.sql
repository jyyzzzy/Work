SELECT DISTINCT 
	TRIM(MF001) 品号,
	TA034 品名,
	TA035 规格,
	BOMMF.MF004 工艺编号,
	MW002 工艺名称,
	left(CMSMC.UDF01,4) 事业部--,TA001,TA002
FROM BOMMF 
INNER JOIN CMSMW ON MW001 = BOMMF.MF004
INNER JOIN MOCTA ON TA006 = MF001 --AND TA003 >= '20230101'
INNER JOIN CMSMC ON MC001 = TA020
WHERE BOMMF.MF004 IN ('P060') AND left(CMSMC.UDF01,4) LIKE '%三部%'
ORDER BY TRIM(MF001)