SELECT TB001,TB002,
SUM(
CASE 
WHEN TB004 = 1
THEN TB007
ELSE 0
END
) AS TA007,
SUM(
CASE
WHEN TB004 = -1
THEN TB007
ELSE 0
END) AS TA008
FROM ACTTB
GROUP BY TB001,TB002
HAVING SUM(
CASE 
WHEN TB004 = 1
THEN TB007
ELSE 0
END
) <>SUM(
CASE
WHEN TB004 = -1
THEN TB007
ELSE 0
END)

UPDATE ACTTA 
SET 
TA007 = ATB.NTA007,
TA008 = ATB.NTA008
FROM ACTTA 
INNER JOIN (
SELECT 
TB001,
TB002,
SUM(
CASE 
WHEN TB004 = 1
THEN TB007
ELSE 0
END
) AS NTA007,
SUM(
CASE
WHEN TB004 = -1
THEN TB007
ELSE 0
END) AS NTA008
FROM ACTTB 
GROUP BY TB001,TB002
) AS ATB ON TA001 =TB001 AND TA002 = TB002 AND TA007 <> NTA007 AND TA008 <> NTA008

