/******采购进货未开票查询******/
--CREATE AT 2026/2/4
SELECT TH001 单别,
TH002 单号,
TH003 序号,
TH004 品号,
TH005 品名,
TH006 规格,
TH031 开票码,
TH034 进货数量,
TH054 已开票数量
FROM PURTH
INNER JOIN PURTG ON TG001 = TH001 AND TG002 = TH002
WHERE TH030 = 'Y'
AND TH031 = 'N'
AND TG013 = 'Y'
UNION ALL

SELECT TJ001 单别,
TJ002 单号,
TJ003 序号,
TJ004 品号,
TJ005 品名,
TJ006 规格,
TJ021 开票码,
TJ009 进货数量,
TJ036 已开票数量
FROM PURTJ
INNER JOIN PURTI ON TI001 = TJ001 AND TI002 = TJ002
WHERE TJ020 = 'Y'
AND TJ021 = 'N'
AND TI013 = 'Y'
ORDER BY CREATE_DATE 

USE SDRD