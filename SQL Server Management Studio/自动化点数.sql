WITH ProductPoint AS (
    SELECT
        MD.MD001,
        MD.MD009,
sum(convert(float,Rtrim(case isnull(MB3.MB180,'') when '' then '-99999' else MB3.MB180 end),0)*MD006/MD007 )as Point 
    FROM SDRD.dbo.BOMMD AS MD
    JOIN SDRD.dbo.INVMB AS MB3
        ON MD.MD003 = MB3.MB001
    WHERE MD006 > 0
      AND MD007 >= 1
      AND MB3.MB006 <> '220' ---辅料去除点数
      AND LEFT(MD.MD003, 1) NOT IN ('A', '1', '2', '5', 'P')
    GROUP BY MD.MD001, MD.MD009
),
tmp AS(
SELECT DISTINCT MF001,TA034,TA035,BOMMF.MF004,MW002,left(CMSMC.UDF01,4) 事业部,IIF(MB110 = '',MB001,IIF(LEFT(MB110,1) = 'K',SUBSTRING(MB110,2,13),SUBSTRING(MB110,1,12))) AS PLMNO--,TA001,TA002
FROM BOMMF 
INNER JOIN CMSMW ON MW001 = BOMMF.MF004
INNER JOIN MOCTA ON TA006 = MF001
INNER JOIN CMSMC ON MC001 = TA020
INNER JOIN INVMB ON MB001 = MF001
INNER JOIN MOCTG ON TG004 = MF001
INNER JOIN MOCTF ON TG001 = TF001 AND TG002 = TF002
WHERE BOMMF.MF004 IN ('P030','P040') --AND left(CMSMC.UDF01,4) LIKE '%三部%'
AND TF003 BETWEEN '20230101' AND '20260228'
)
SELECT DISTINCT TRIM(T.MF001) ERP品号,T.TA034 品名,T.TA035 规格,--MOCTGTG007,
T.MF004 工艺编号,T.MW002 工艺名称,
CASE
            WHEN PP.Point IS NULL THEN -1
            WHEN PP.Point >= 0 THEN PP.Point
            ELSE 0
        END 自动化点数,T.事业部,TRIM(T.PLMNO) AS PLM品号--,* 
FROM tmp AS T
--LEFT JOIN SDRD_Result AS R ON T.MF001 = R.MOCTGTG004 AND T.事业部 = R.MOCTACOMPANY AND T.MF004 = MOCTGTG010
LEFT JOIN ProductPoint AS PP ON PP.MD001 = T.MF001 AND PP.MD009 = T.MF004
--WHERE MF001 = '222753830AX0'
--WHERE MOCTACOMPANY = '事业三部' AND MOCTGTG010 IN ('P030','P040')
USE ZJRD

UNION ALL

SELECT
    MOCTF.TF003 AS MOCTFTF003,
    MOCTG.TG001 AS MOCTGTG001,
    MOCTG.TG002 AS MOCTGTG002,
    MOCTG.TG004 AS MOCTGTG004,
    MOCTG.TG005 AS MOCTGTG005,
    MOCTG.TG006 AS MOCTGTG006,
    MOCTG.TG007 AS MOCTGTG007,
    MOCTG.TG011 AS MOCTGTG011,
    CASE
        WHEN PP.Point IS NULL THEN -1
        WHEN PP.Point >= 0 THEN PP.Point
        ELSE 0
    END AS WHS1105001,
    CASE
        WHEN PP.Point IS NULL THEN -1
        WHEN PP.Point >= 0 THEN PP.Point
        ELSE 0
    END * MOCTG.TG011 AS WHS1105002,
    MW.MW001 AS MOCTGTG010,
    MW.MW002 AS CMSMCMC002,
    MOCTG.TG014 AS MOCTGTG014,
    MOCTG.TG015 AS MOCTGTG015,
    MOCTA.TA015 AS MOCTATA015,
    MOCTA.TA017 AS MOCTATA017,
    MOCTF.TF011 AS MOCTFTF011,
    CMD.MD002 AS CMSMDMD002,
    MOCTF.TF012 AS MOCTFTF012,
    CME.UDF01 AS MOCTACOMPANY
FROM ZJRD.dbo.MOCTG AS MOCTG WITH (NOLOCK)
LEFT JOIN ZJRD.dbo.MOCTF AS MOCTF WITH (NOLOCK)
    ON MOCTG.TG001 = MOCTF.TF001
   AND MOCTG.TG002 = MOCTF.TF002
LEFT JOIN ZJRD.dbo.MOCTA AS MOCTA WITH (NOLOCK)
    ON MOCTG.TG014 = MOCTA.TA001
   AND MOCTG.TG015 = MOCTA.TA002
LEFT JOIN ProductPoint AS PP
    ON PP.MD001 = MOCTG.TG004
LEFT JOIN ZJRD.dbo.CMSMW AS MW WITH (NOLOCK)
    ON MW.MW001 = PP.MD009
LEFT JOIN ZJRD.dbo.CMSMD AS CMD WITH (NOLOCK)
    ON MOCTF.TF011 = CMD.MD001
LEFT JOIN ZJRD.dbo.CMSME AS CME WITH (NOLOCK)
    ON CMD.MD015 = CME.ME001
WHERE RTRIM(MOCTG.TG004) LIKE '2%X_'

UNION ALL

SELECT
    MOCTF.TF003 AS MOCTFTF003,
    MOCTG.TG001 AS MOCTGTG001,
    MOCTG.TG002 AS MOCTGTG002,
    MOCTG.TG004 AS MOCTGTG004,
    MOCTG.TG005 AS MOCTGTG005,
    MOCTG.TG006 AS MOCTGTG006,
    MOCTG.TG007 AS MOCTGTG007,
    MOCTG.TG011 AS MOCTGTG011,
    CASE
        WHEN PP.Point IS NULL THEN -1
        WHEN PP.Point >= 0 THEN PP.Point
        ELSE 0
    END AS WHS1105001,
    CASE
        WHEN PP.Point IS NULL THEN -1
        WHEN PP.Point >= 0 THEN PP.Point
        ELSE 0
    END * MOCTG.TG011 AS WHS1105002,
    MW.MW001 AS MOCTGTG010,
    MW.MW002 AS CMSMCMC002,
    MOCTG.TG014 AS MOCTGTG014,
    MOCTG.TG015 AS MOCTGTG015,
    MOCTA.TA015 AS MOCTATA015,
    MOCTA.TA017 AS MOCTATA017,
    MOCTF.TF011 AS MOCTFTF011,
    CMD.MD002 AS CMSMDMD002,
    MOCTF.TF012 AS MOCTFTF012,
    CME.UDF01 AS MOCTACOMPANY
FROM AHRD.dbo.MOCTG AS MOCTG WITH (NOLOCK)
LEFT JOIN AHRD.dbo.MOCTF AS MOCTF WITH (NOLOCK)
    ON MOCTG.TG001 = MOCTF.TF001
   AND MOCTG.TG002 = MOCTF.TF002
LEFT JOIN AHRD.dbo.MOCTA AS MOCTA WITH (NOLOCK)
    ON MOCTG.TG014 = MOCTA.TA001
   AND MOCTG.TG015 = MOCTA.TA002
LEFT JOIN ProductPoint AS PP
    ON PP.MD001 = MOCTG.TG004
LEFT JOIN AHRD.dbo.CMSMW AS MW WITH (NOLOCK)
    ON MW.MW001 = PP.MD009
LEFT JOIN AHRD.dbo.CMSMD AS CMD WITH (NOLOCK)
    ON MOCTF.TF011 = CMD.MD001
LEFT JOIN AHRD.dbo.CMSME AS CME WITH (NOLOCK)
    ON CMD.MD015 = CME.ME001
WHERE RTRIM(MOCTG.TG004) LIKE '2%X_';
