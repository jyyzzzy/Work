	CASE LEFT(MOCTE.TE014,1) WHEN 'a' THEN MOCTE.TE005 ELSE CASE LEFT(MOCTC.TC007,1) WHEN 'a' THEN MOCTE.TE005 ELSE 0 END END ,
	TE009,
	MW002
