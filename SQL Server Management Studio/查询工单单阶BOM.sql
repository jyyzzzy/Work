/******查询工单单阶BOM******/
SELECT DISTINCT
QTY.DEPT 部门,
BOM.MD001 产品品号,
PROD.MB002 产品品名,
PROD.MB003 产品规格,
PROD.MB004 产品单位,
QTY.RECEIVE_CNT AS 验收总数量,
BOM.MD003 材料品号,
MATL.MB002 材料品名,
MATL.MB003 材料规格,
MATL.MB004 材料单位,
BOM.QTY_PER 单位用量,
QTY.ISSUE_QTY 领用总数量
FROM (
	SELECT MD001,MD003,SUM(MD006/IIF(MD007 = 0,1,MD007)) AS QTY_PER
	FROM BOMMD
	GROUP BY MD001,MD003
) AS BOM 
INNER JOIN 
(
	SELECT TG004,TB003,LEFT(CMSMC.UDF01,CHARINDEX('-',CMSMC.UDF01 + '-') - 1) DEPT,SUM(TG013) AS RECEIVE_CNT ,SUM(TB005) ISSUE_QTY
	FROM MOCTG INNER JOIN MOCTF ON TF001 = TG001 AND TF002 = TG002
	INNER JOIN CMSMC ON MC001 = TG010
	INNER JOIN MOCTB ON TB001 = TG014 AND TB002 = TG015
	WHERE TF003 BETWEEN '20250101' AND '20251231'
	AND LEFT(TG004,1) IN ('1','A')
	GROUP BY TG004,LEFT(CMSMC.UDF01,CHARINDEX('-',CMSMC.UDF01 + '-') - 1),TB003
) AS QTY ON BOM.MD001 = QTY.TG004 AND BOM.MD003 = QTY.TB003

INNER JOIN INVMB AS PROD ON PROD.MB001 = BOM.MD001
INNER JOIN INVMB AS MATL ON MATL.MB001 = BOM.MD003
--LEFT OUTER JOIN BOMMD ON MD001 = TG004 AND MD003 = TB003
WHERE 
LEFT(TB003,1) IN ('3','5','6','7')
AND BOM.QTY_PER>0
AND QTY.DEPT = '事业一部'
--AND TA015 <> 0
GROUP BY 
QTY.DEPT,
BOM.MD001,
PROD.MB002,
PROD.MB003,
PROD.MB004,
QTY.RECEIVE_CNT,
BOM.MD003,
MATL.MB002,
MATL.MB003,
MATL.MB004,
BOM.QTY_PER,
QTY.ISSUE_QTY
ORDER BY BOM.MD001,BOM.MD003


/******查询工单单阶BOM******/
;WITH BOM AS (
    SELECT
        MD001,
        MD003,
        SUM(MD006 / IIF(MD007 = 0, 1, MD007)) AS QTY_PER
    FROM BOMMD
    GROUP BY MD001, MD003
),
TG_BASE AS (
    SELECT
        G.TG014,
        G.TG015,
        G.TG004,
        LEFT(MC.UDF01, CHARINDEX('-', MC.UDF01 + '-') - 1) AS DEPT,
        G.TG013
    FROM MOCTG G
    INNER JOIN MOCTF F
        ON F.TF001 = G.TG001 AND F.TF002 = G.TG002
    INNER JOIN CMSMC MC
        ON MC.MC001 = G.TG010
    WHERE F.TF003 BETWEEN '20250101' AND '20251231'
      AND LEFT(G.TG004, 1) IN ('1', 'A')
),
ORD AS (   -- 工单唯一集：避免 MOCTB 被 MOCTG 行数放大
    SELECT DISTINCT
        TG014, TG015, TG004, DEPT
    FROM TG_BASE
),
RECV AS (  -- 验收数量：按 产品 + 部门 汇总（不与材料绑定）
    SELECT
        TG004,
        DEPT,
        SUM(TG013) AS RECEIVE_CNT
    FROM TG_BASE
    GROUP BY TG004, DEPT
),
ISSUE AS ( -- 领用数量：用工单唯一集去连 MOCTB，避免重复累加
    SELECT
        O.TG004,
        O.DEPT,
        B.TB003,
        SUM(B.TB005) AS ISSUE_QTY
    FROM ORD O
    INNER JOIN MOCTB B
        ON B.TB001 = O.TG014 AND B.TB002 = O.TG015
    GROUP BY O.TG004, O.DEPT, B.TB003
),
QTY AS (
    SELECT
        I.TG004,
        I.TB003,
        I.DEPT,
        R.RECEIVE_CNT,
        I.ISSUE_QTY
    FROM ISSUE I
    INNER JOIN RECV R
        ON R.TG004 = I.TG004 AND R.DEPT = I.DEPT
)

SELECT DISTINCT
    QTY.DEPT 部门,
    BOM.MD001 产品品号,
    PROD.MB002 产品品名,
    PROD.MB003 产品规格,
    PROD.MB004 产品单位,
    QTY.RECEIVE_CNT AS 验收总数量,
    BOM.MD003 材料品号,
    MATL.MB002 材料品名,
    MATL.MB003 材料规格,
    MATL.MB004 材料单位,
    BOM.QTY_PER 单位用量,
    QTY.ISSUE_QTY 领用总数量
FROM BOM
INNER JOIN QTY
    ON BOM.MD001 = QTY.TG004
   AND BOM.MD003 = QTY.TB003
INNER JOIN INVMB AS PROD
    ON PROD.MB001 = BOM.MD001
INNER JOIN INVMB AS MATL
    ON MATL.MB001 = BOM.MD003
WHERE
    LEFT(QTY.TB003, 1) IN ('3', '5', '6', '7')
    AND BOM.QTY_PER > 0
    AND QTY.DEPT = '事业一部'
GROUP BY
    QTY.DEPT,
    BOM.MD001,
    PROD.MB002,
    PROD.MB003,
    PROD.MB004,
    QTY.RECEIVE_CNT,
    BOM.MD003,
    MATL.MB002,
    MATL.MB003,
    MATL.MB004,
    BOM.QTY_PER,
    QTY.ISSUE_QTY
ORDER BY
    BOM.MD001,
    BOM.MD003;
