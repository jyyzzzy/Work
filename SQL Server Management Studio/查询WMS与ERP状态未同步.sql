    ''''+TC007+''',',
    COUNT(*) AS Cnt
FROM MOCTC
WHERE LEFT(TC007,1) = 'W'
GROUP BY
    TC007
HAVING COUNT(*) > 1
ORDER BY
TC007 DESC,
    Cnt DESC

