		'PURR03',
		'PURR10',
		'PURR11',
		'PURR12',
		'PURR19',
		'PURR20',
		'PURR36',
		'PURR39'
	)
	AND SUBSTRING(MG006,2,1) = 'Y'
	AND MG004 = 'Y'  
	AND (
		SUBSTRING(MG006,7,1)='Y' 
		OR SUBSTRING(MG006,8,1)='Y'
	)
ORDER BY departmentcode,workcode ASC


