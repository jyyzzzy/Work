	LEFT OUTER JOIN master.dbo.OA_COMPLETEDEP_Vcode AS DEPT ON DEPT.departmentID = HRM.departmentid 
WHERE
	EXISTS (
		SELECT 1 
		FROM master.dbo.OA_Hrm AS W 
		WHERE W.workcode COLLATE CHINESE_PRC_CI_AS = M.MG001 COLLATE CHINESE_PRC_CI_AS 
		--AND seclevel = '30'
	) 
	AND SUBSTRING(M.MG002,1,3) = 'ACT'
	AND SUBSTRING(M.MG002,1,5) <> 'PURAB'
	AND SUBSTRING(M.MG002,1,4) <> 'PURB' 
	AND SUBSTRING(M.MG002,1,4) <> 'PURQ' 
	AND M.MG002 NOT IN(
		'PURI01',
		'PURI04',
		'PURI05',
		'PURI10',
		'PURI12',
		'PURI13',
		'PURR01',
