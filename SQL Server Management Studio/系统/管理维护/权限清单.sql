SELECT 
MG001 AS 用户编号,
MA002 AS 用户名称,
MG002 AS 程序编号,
MB002 AS 程序名称,
MG004 AS 运行权限,
MG005 AS 信息控制,
SUBSTRING(MG006,1,1) AS 查询,
SUBSTRING(MG006,2,1) AS 更改,
SUBSTRING(MG006,3,1) AS 删除,
SUBSTRING(MG006,4,1) AS 审核,
SUBSTRING(MG006,5,1) AS 撤销审核,
SUBSTRING(MG006,6,1) AS 输出,
SUBSTRING(MG006,9,1) AS 新增,
SUBSTRING(MG006,10,1) AS 送签,
SUBSTRING(MG006,12,1) AS 作废
FROM ADMMG
INNER JOIN DSCSYS..DSCMA ON MA001 = MG001 AND MA005 = 'Y'
INNER JOIN DSCSYS..ADMMB ON MB001 = MG002
WHERE MB004 = 'MOC' AND LEFT(MG002,4) IN ('MOCI')
ORDER BY MG002,MG001