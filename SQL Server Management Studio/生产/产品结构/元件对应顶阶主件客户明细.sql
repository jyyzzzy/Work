	MA.MA001 AS 客户编号,
	MA.MA003 AS 客户全称,
	TOTAL_MIR.分部名称 AS 分部名称
FROM TOTAL_MIR
INNER JOIN FATHER ON FATHER.元件 = TOTAL_MIR.LA001
