;WITH U AS(
	SELECT T.ITEMNO AS COMP, M.MD001 AS P
	FROM LSSJ..ITEMTMP T
	LEFT OUTER JOIN SDRD..BOMMD M ON M.MD003 = T.ITEMNO
	UNION ALL
	SELECT U.COMP, M.MD001
	FROM U
	INNER JOIN SDRD..BOMMD M ON M.MD003 = U.P
) ,
FATHER AS (SELECT DISTINCT U.P AS 主件, U.COMP AS 元件
	FROM U
	WHERE U.P IS NOT NULL
		AND NOT EXISTS (SELECT 1 FROM SDRD..BOMMD Z WHERE Z.MD003 = U.P)
		AND SUBSTRING(U.P, 1, 1) IN ('1', 'A')
),
CUSTOMER AS (
	SELECT FATHER.主件 AS 产品,TOP_COPMB.MB001 AS 客户编号,MA.MA003 AS 客户全称 FROM FATHER 
	LEFT OUTER JOIN (
		SELECT *, ROW_NUMBER() OVER (PARTITION BY MB001,MB002 ORDER BY MB017 DESC) AS rn FROM SDRD..COPMB
	) AS TOP_COPMB ON rn =1 AND MB002 = FATHER.主件
	INNER JOIN SDRD..COPMA AS MA ON MA001 = TOP_COPMB.MB001

	UNION ALL

		SELECT FATHER.主件 AS 产品,TOP_COPMB.MB001 AS 客户编号,MA.MA003 AS 客户全称 FROM FATHER 
	LEFT OUTER JOIN (
		SELECT *, ROW_NUMBER() OVER (PARTITION BY MB001,MB002 ORDER BY MB017 DESC) AS rn FROM AHRD..COPMB
	) AS TOP_COPMB ON rn =1 AND MB002 = FATHER.主件
	INNER JOIN AHRD..COPMA AS MA ON MA001 = TOP_COPMB.MB001

	UNION ALL

		SELECT FATHER.主件 AS 产品,TOP_COPMB.MB001 AS 客户编号,MA.MA003 AS 客户全称 FROM FATHER 
	LEFT OUTER JOIN (
		SELECT *, ROW_NUMBER() OVER (PARTITION BY MB001,MB002 ORDER BY MB017 DESC) AS rn FROM SDRD..COPMB
	) AS TOP_COPMB ON rn =1 AND MB002 = FATHER.主件
	INNER JOIN ZJRD..COPMA AS MA ON MA001 = TOP_COPMB.MB001

	UNION ALL

		SELECT FATHER.主件 AS 产品,TOP_COPMB.MB001 AS 客户编号,MA.MA003 AS 客户全称 FROM FATHER 
	LEFT OUTER JOIN (
		SELECT *, ROW_NUMBER() OVER (PARTITION BY MB001,MB002 ORDER BY MB017 DESC) AS rn FROM YNRD..COPMB
	) AS TOP_COPMB ON rn =1 AND MB002 = FATHER.主件
	INNER JOIN YNRD..COPMA AS MA ON MA001 = TOP_COPMB.MB001
),
ILA AS (
		SELECT SDRD..INVLA.*, TA001,TA002,TA006,TA021,[分部名称]
		FROM SDRD..INVLA 
		INNER JOIN SDRD..MOCTA  AS MOCTA ON TA001 = SUBSTRING(LA024,1,4) AND TA002 = SUBSTRING(LA024,6,16)
		LEFT JOIN SDRD..CMSMD AS CMSMD ON MD001 = TA021 
		LEFT JOIN [master].[dbo].[OA_COMPLETEDEP] ON [部门编码]COLLATE Chinese_PRC_BIN = MD015
		LEFT JOIN (
			SELECT MA.MA001,MA.MA002 FROM (
				SELECT *, ROW_NUMBER() OVER (PARTITION BY MB001,MB002 ORDER BY MB017 DESC) AS rn FROM SDRD..COPMB
			) AS CMB 
			INNER JOIN COPMA AS MA ON MA.MA001 = CMB.MB001
			WHERE CMB.rn = 1 
		) AS MA ON MA.MB002 = FATHER.主件
		WHERE LA004 BETWEEN '20250101' AND '20250930' 
		AND EXISTS (
			SELECT 1 FROM FATHER WHERE 主件 = TA006
		)

		UNION ALL

		SELECT AHRD..INVLA.*, TA001,TA002,TA006,TA021,[分部名称]
		FROM AHRD..INVLA 
		INNER JOIN AHRD..MOCTA AS MOCTA ON TA001 = SUBSTRING(LA024,1,4) AND TA002 = SUBSTRING(LA024,6,16)
		LEFT JOIN AHRD..CMSMD AS CMSMD ON MD001 = TA021 
		LEFT JOIN [master].[dbo].[OA_COMPLETEDEP] ON [部门编码]COLLATE Chinese_PRC_BIN = MD015
		WHERE LA004 BETWEEN '20250101' AND '20250930'
		AND EXISTS (
			SELECT 1 FROM FATHER WHERE 主件 = TA006
		)

		UNION ALL

		SELECT ZJRD..INVLA.*, TA001,TA002,TA006,TA021,[分部名称]
		FROM ZJRD..INVLA 
		INNER JOIN ZJRD..MOCTA AS MOCTA ON TA001 = SUBSTRING(LA024,1,4) AND TA002 = SUBSTRING(LA024,6,16)
		LEFT JOIN ZJRD..CMSMD AS CMSMD ON MD001 = TA021 
		LEFT JOIN [master].[dbo].[OA_COMPLETEDEP] ON [部门编码]COLLATE Chinese_PRC_BIN = MD015
		WHERE LA004 BETWEEN '20250101' AND '20250930'
		AND EXISTS (
			SELECT 1 FROM FATHER WHERE 主件 = TA006
		)

		UNION ALL

		SELECT YNRD..INVLA.*, TA001,TA002,TA006,TA021,[分部名称]
		FROM YNRD..INVLA 
		INNER JOIN YNRD..MOCTA AS MOCTA ON TA001 = SUBSTRING(LA024,1,4) AND TA002 = SUBSTRING(LA024,6,16)
		LEFT JOIN YNRD..CMSMD AS CMSMD ON MD001 = TA021 
		LEFT JOIN [master].[dbo].[OA_COMPLETEDEP] ON [部门编码]COLLATE Chinese_PRC_BIN = MD015
		INNER JOIN FATHER ON 主件 = TA006

		WHERE LA004 BETWEEN '20250101' AND '20250930'
),
TOTAL_MIR AS (
	SELECT LA001,分部名称,SUM(LA005 * LA011) AS 领料数量 FROM ILA GROUP BY LA001,[分部名称]
)
SELECT FATHER.元件 AS 材料品号,
	SUM(TOTAL_MIR.领料数量) AS 领料数量,
	FATHER.主件 AS 品号,
