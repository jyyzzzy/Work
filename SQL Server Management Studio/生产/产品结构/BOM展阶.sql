SELECT 
ISNULL(ITEM.MB001, '') AS 一层品号,
ISNULL(I.MB002, '') AS 一层品名,
ISNULL(I.MB003, '') AS 一层规格,
ISNULL(I.MB004, '') AS 一层单位,
1 AS 一层用量,
ISNULL(A.MD003, '') AS 二层品号,
ISNULL(IA.MB002, '') AS 二层品名,
ISNULL(IA.MB003, '') AS 二层规格,
ISNULL(IA.MB004, '') AS 二层单位,
ISNULL(A.MD006, 0) AS 二层用量,
ISNULL(B.MD003, '') AS 三层品号,
ISNULL(IB.MB002, '') AS 三层品名,
ISNULL(IB.MB003, '') AS 三层规格,
ISNULL(IB.MB004, '') AS 三层单位,
ISNULL(B.MD006, 0) AS 三层用量,
ISNULL(C.MD003, '') AS 四层品号,
ISNULL(IC.MB002, '') AS 四层品名,
ISNULL(IC.MB003, '') AS 四层规格,
ISNULL(IC.MB004, '') AS 四层单位,
ISNULL(C.MD006, 0) AS 四层用量,
ISNULL(D.MD003, '') AS 五层品号,
ISNULL(ID.MB002, '') AS 五层品名,
ISNULL(ID.MB003, '') AS 五层规格,
ISNULL(ID.MB004, '') AS 五层单位,
ISNULL(D.MD006, 0) AS 五层用量,
ISNULL(E.MD003, '') AS 六层品号,
ISNULL(IE.MB002, '') AS 六层品名,
ISNULL(IE.MB003, '') AS 六层规格,
ISNULL(IE.MB004, '') AS 六层单位,
ISNULL(E.MD006, 0) AS 六层用量,
ISNULL(F.MD003, '') AS 七层品号,
ISNULL(I_F.MB002, '') AS 七层品名,
ISNULL(I_F.MB003, '') AS 七层规格,
ISNULL(I_F.MB004, '') AS 七层单位,
ISNULL(F.MD006, 0) AS 七层用量
FROM SDRD..INVMB AS ITEM
LEFT OUTER JOIN BOMMD AS A ON A.MD001 = ITEM.MB001 AND LEFT(A.MD003,1) IN ('1','A')
LEFT OUTER JOIN BOMMD AS B ON A.MD003 = B.MD001 AND LEFT(B.MD003,1) IN ('1','A')
LEFT OUTER JOIN BOMMD AS C ON B.MD003 = C.MD001 AND LEFT(C.MD003,1) IN ('1','A')
LEFT OUTER JOIN BOMMD AS D ON C.MD003 = D.MD001 AND LEFT(D.MD003,1) IN ('1','A')
LEFT OUTER JOIN BOMMD AS E ON D.MD003 = E.MD001 AND LEFT(E.MD003,1) IN ('1','A')
LEFT OUTER JOIN BOMMD AS F ON E.MD003 = F.MD001 AND LEFT(F.MD003,1) IN ('1','A')
LEFT OUTER JOIN INVMB AS I ON I.MB001 = ITEM.MB001
LEFT OUTER JOIN INVMB AS IA ON IA.MB001 = A.MD003
LEFT OUTER JOIN INVMB AS IB ON IB.MB001 = B.MD003
LEFT OUTER JOIN INVMB AS IC ON IC.MB001 = C.MD003
LEFT OUTER JOIN INVMB AS ID ON ID.MB001 = D.MD003
LEFT OUTER JOIN INVMB AS IE ON IE.MB001 = E.MD003
LEFT OUTER JOIN INVMB AS I_F ON I_F.MB001 = F.MD003
WHERE LEFT(ITEM.MB001,1) IN ('1','A')
ORDER BY 
ITEM.MB001,
A.MD003,
B.MD003,
C.MD003,
D.MD003,
E.MD003,
F.MD003