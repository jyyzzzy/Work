SELECT  
    --TA.TA001 AS 工单单别,
    --TA.TA002 AS 工单单号,
    CME.ME002 AS 部门名称,
    TA.TA006 AS 产品品号,
    MBA.MB002 AS 产品品名,
    MBA.MB003 AS 产品规格,
    TB.TB003 AS 材料品号,
    BMD.MD009 AS 材料工艺,
    TB.TB012 AS 材料品名,
    TB.TB013 AS 材料规格,
    SUM(TB.TB005) AS 总领用量,
    BMD.MD006 AS 组成用量
FROM MOCTB AS TB
INNER JOIN INVMB AS MBB ON TB.TB003 = MBB.MB001 --匹配BOM品号
INNER JOIN MOCTA AS TA ON TB.TB001 = TA.TA001 --匹配工单
    AND TB.TB002 = TA.TA002 
    AND TA.TA013 = 'Y' --已审核
    AND TA.TA003 BETWEEN '20240901' AND '20250831' --
INNER JOIN INVMB AS MBA ON MBA.MB001 = TA.TA006
INNER JOIN BOMMD AS BMD ON BMD.MD001 = TA.TA006 AND BMD.MD003 = TB.TB003
LEFT JOIN CMSMD AS CMD ON CMD.MD001 = TA.TA021
LEFT JOIN CMSME AS CME ON CME.ME001 = CMD.MD015

WHERE 
    ((
        CHARINDEX('散热片', MBB.MB002) > 0
        OR CHARINDEX('整流桥', MBB.MB002) > 0
        OR CHARINDEX('可控硅', MBB.MB002) > 0
        OR CHARINDEX('三极管', MBB.MB002) > 0
        OR CHARINDEX('保险丝', MBB.MB002) > 0
        OR CHARINDEX('场效应管', MBB.MB002) > 0
        OR CHARINDEX('肖特基二极管', MBB.MB002) > 0
        OR CHARINDEX('发光二极管', MBB.MB002) > 0
        OR CHARINDEX('安规电容', MBB.MB002) > 0
        OR CHARINDEX('电解电容', MBB.MB002) > 0
        OR CHARINDEX('线绕电阻', MBB.MB002) > 0
        OR CHARINDEX('金膜电阻', MBB.MB002) > 0
        OR CHARINDEX('热敏电阻', MBB.MB002) > 0
        OR CHARINDEX('压敏电阻', MBB.MB002) > 0
        OR CHARINDEX('工字电感', MBB.MB002) > 0
        OR CHARINDEX('色码电感', MBB.MB002) > 0
        OR CHARINDEX('跳线', MBB.MB002) > 0
        OR CHARINDEX('金属膜电容', MBB.MB002) > 0
        OR CHARINDEX('IGBT', MBB.MB002) > 0
        OR CHARINDEX('接收头', MBB.MB002) > 0
         OR CHARINDEX('散热器', MBB.MB002) > 0
    ) OR (
        CHARINDEX('编带', MBB.MB003) > 0
        OR CHARINDEX('脚长', MBB.MB003) > 0
        OR CHARINDEX('热缩套管', MBB.MB003) > 0
    )) AND TB.TB005 > 0
GROUP BY CME.ME002,TA.TA006,MBA.MB002,MBA.MB003,TB.TB003,TB.TB012,TB.TB013,BMD.MD009,BMD.MD006
ORDER BY TA.TA006 ASC,TB.TB003 ASC