/******材料对应产品、客户及替代料******/
SELECT DISTINCT
	I.ITEMNO 材料品号,
	TB012 材料品名,
	TB013 材料规格,
	TB006 材料工艺,
	SUM(TB004) 需领用量,
	SUM(TB005) 已领用量,
	SUM(TB004-TB005) 未领用量,
	TA006 产品品号,
	TA034 产品品名,
	TA035 产品规格,
	TC004 客户编号,
	MA002 客户简称,
	BMDB.MD003 AS 替代材料品号,
	IMBC.MB002 AS 替代材料品名,
	IMBC.MB003 AS 替代材料规格,
	IMBC.MB004 AS 替代材料单位
FROM LSSJ..ITEMTMP I 
INNER JOIN MOCTB ON TB003 = I.ITEMNO AND TB018 = 'Y'
INNER JOIN MOCTA ON TA001 = TB001 AND TA002 = TB002 
INNER JOIN COPTD ON TD001 = TA026 AND TD002 = TA027 AND TD003 = TA028
INNER JOIN COPTC ON TC001 = TD001 AND TC002 = TD002
INNER JOIN COPMA ON MA001 = TC004
LEFT OUTER JOIN SDRD..BOMMD AS BMDA ON BMDA.MD001 = TA006 AND BMDA.MD003 = I.ITEMNO --关联插件位置
LEFT OUTER JOIN SDRD..BOMMD AS BMDB ON BMDB.MD001 = TA006  --关联插件位置下其他品
	AND BMDB.MD003 <> BMDA.MD003 
	AND CHARINDEX(BMDB.MD019, BMDA.MD019) > 0
LEFT OUTER JOIN INVMB AS IMBC ON IMBC.MB001 = BMDB.MD003 --替代品信息
WHERE TA011 IN ('1','2','3') 
GROUP BY 
	I.ITEMNO,
	TB012,
	TB013,
	TB006,
	TA006,
	TA034,
	TA035,
	TC004,
	MA002,
	BMDB.MD003,
	IMBC.MB002,
	IMBC.MB003,
	IMBC.MB004
ORDER BY I.ITEMNO,TA006,TC004,BMDB.MD003