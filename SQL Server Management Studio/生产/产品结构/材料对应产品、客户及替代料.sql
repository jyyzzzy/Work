/******材料对应产品、客户及替代料******/
SELECT DISTINCT
	I.ITEMNO 材料品号,
	TB012 材料品名,
	TB013 材料规格,
	TB006 材料工艺,
	SUM(TB004) 需领用量,
	SUM(TB005) 已领用量,
	SUM(TB004-TB005) 未领用量,
	TA006 产品品号,
	TA034 产品品名,
	TA035 产品规格,
	TC004 客户编号,
	MA002 客户简称--,
	--BMDB.MD003 AS 替代材料品号,
	--IMBC.MB002 AS 替代材料品名,
	--IMBC.MB003 AS 替代材料规格,
	--IMBC.MB004 AS 替代材料单位
FROM LSSJ..ITEMTMP I 
LEFT OUTER JOIN MOCTB ON TB003 = I.ITEMNO AND TB018 = 'Y'
LEFT OUTER JOIN MOCTA ON TA001 = TB001 AND TA002 = TB002 
LEFT OUTER JOIN COPTD ON TD001 = TA026 AND TD002 = TA027 AND TD003 = TA028
LEFT OUTER JOIN COPTC ON TC001 = TD001 AND TC002 = TD002
LEFT OUTER JOIN COPMA ON MA001 = TC004
--LEFT OUTER JOIN SDRD..BOMMD AS BMDA ON BMDA.MD001 = TA006 AND BMDA.MD003 = I.ITEMNO --关联插件位置
--LEFT OUTER JOIN SDRD..BOMMD AS BMDB ON BMDB.MD001 = TA006  --关联插件位置下其他品
--	AND BMDB.MD003 <> BMDA.MD003 
--	AND CHARINDEX(BMDB.MD019, BMDA.MD019) > 0
--LEFT OUTER JOIN INVMB AS IMBC ON IMBC.MB001 = BMDB.MD003 --替代品信息
--WHERE TA011 IN ('1','2','3') 
GROUP BY 
	I.ITEMNO,
	TB012,
	TB013,
	TB006,
	TA006,
	TA034,
	TA035,
	TC004,
	MA002--,
	--BMDB.MD003,
	--IMBC.MB002,
	--IMBC.MB003,
	--IMBC.MB004
ORDER BY I.ITEMNO,TA006,TC004--,BMDB.MD003



SELECT I.ITEMNO,SD_CUST.MA002--,ZJ_CUST.TC004,AH_CUST.TC004,YN_CUST.TC004
FROM LSSJ..ITEMTMP I
INNER JOIN (
	SELECT DISTINCT LA001,TC004,MA002
	FROM SDRD..INVLA
	INNER JOIN SDRD..MOCTA ON TA001 + '-' + TA002 = LA024
	INNER JOIN SDRD..COPTD ON TA026 = TD001 AND TA027 = TD002 AND TA028 = TD003
	INNER JOIN SDRD..COPTC ON TC001 = TD001 AND TC002 = TD002
	INNER JOIN SDRD..COPMA ON MA001 = TC004
	WHERE LA004 BETWEEN '20260101' AND '20260331'
) SD_CUST ON SD_CUST.LA001 = I.ITEMNO
INNER JOIN (
	SELECT DISTINCT LA001,TC004
	FROM ZJRD..INVLA
	INNER JOIN ZJRD..MOCTA ON TA001 + '-' + TA002 = LA024
	INNER JOIN ZJRD..COPTD ON TA026 = TD001 AND TA027 = TD002 AND TA028 = TD003
	INNER JOIN ZJRD..COPTC ON TC001 = TD001 AND TC002 = TD002
		INNER JOIN ZJRD..COPMA ON MA001 = TC004
	WHERE LA004 BETWEEN '20260101' AND '20260331'
) ZJ_CUST ON ZJ_CUST.LA001 = I.ITEMNO
INNER JOIN (
	SELECT DISTINCT LA001,TC004
	FROM AHRD..INVLA
	INNER JOIN AHRD..MOCTA ON TA001 + '-' + TA002 = LA024
	INNER JOIN AHRD..COPTD ON TA026 = TD001 AND TA027 = TD002 AND TA028 = TD003
	INNER JOIN AHRD..COPTC ON TC001 = TD001 AND TC002 = TD002
		INNER JOIN AHRD..COPMA ON MA001 = TC004
	WHERE LA004 BETWEEN '20260101' AND '20260331'
) AH_CUST ON AH_CUST.LA001 = I.ITEMNO
INNER JOIN (
	SELECT DISTINCT LA001,TC004
	FROM YNRD..INVLA
	INNER JOIN YNRD..MOCTA ON TA001 + '-' + TA002 = LA024
	INNER JOIN YNRD..COPTD ON TA026 = TD001 AND TA027 = TD002 AND TA028 = TD003
	INNER JOIN YNRD..COPTC ON TC001 = TD001 AND TC002 = TD002
		INNER JOIN YNRD..COPMA ON MA001 = TC004
	WHERE LA004 BETWEEN '20260101' AND '20260331'
) YN_CUST ON YN_CUST.LA001 = I.ITEMNO

SELECT I.ITEMNO,MB002,MB003,SUM(-1*LA005*LA011),ORD.MA001,ORD.MA002 FROM LSSJ..ITEMTMP I
INNER JOIN INVLA ON LA001 = I.ITEMNO
INNER JOIN INVMB ON MB001 = LA001
INNER JOIN (

SELECT DISTINCT TA001,TA002,MA001,MA002 FROM SDRD..MOCTA 
INNER JOIN SDRD..COPTD ON TA026 = TD001 AND TA027 = TD002 AND TA028 = TD003
INNER JOIN SDRD..COPTC ON TC001 = TD001 AND TC002 = TD002
INNER JOIN SDRD..COPMA ON MA001 = TC004) ORD ON TA001 + '-' + TA002 = LA024
WHERE LA004 BETWEEN '20260101' AND '20260331'
GROUP BY I.ITEMNO,MB002,MB003,ORD.MA001,ORD.MA002 
ORDER BY ITEMNO