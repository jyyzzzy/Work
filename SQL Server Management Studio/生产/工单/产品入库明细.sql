SELECT TG001 入库单别,TG002　入库单号,TG003　入库序号,TF003　入库日期,TG004 AS 产品品号,TG005 AS 产品品名,TG006 AS 产品规格,
TG007 AS 产品单位,TG010 AS 仓库编号,TG011 入库数量,TG012 报废数量,TG013 验收数量,TA021 工作中心编号,MD002 工作中心名称,
ME001 部门编号,ME002 部门名称,MA002 客户简称
FROM MOCTG
INNER JOIN MOCTF ON TF001 = TG001 AND TF002 = TG002 
LEFT OUTER JOIN MOCTA ON TA001 = TG014 AND TA002 = TG015
LEFT OUTER JOIN COPTC ON TC001 = TA026 AND TC002 = TA027
LEFT OUTER JOIN COPMA ON MA001 = TC004
LEFT OUTER JOIN CMSMD ON MD001 = TA021
LEFT OUTER JOIN CMSME ON ME001 = MD015
INNER JOIN CMSMC ON MC001 = TG010
WHERE 
TF003 BETWEEN '20250101' AND '20251231'
AND TG009 = '1'
AND TF006 = 'Y'
AND CMSMC.UDF01 LIKE '%二部%'
AND MD002 NOT LIKE '%SMT%'
ORDER BY TF003,TG001,TG002,TG003

SELECT TG004 AS 产品品号,TG005 AS 产品品名,TG006 AS 产品规格,
TG007 AS 产品单位,TG010 AS 仓库编号,MC002 AS 仓库名称,SUM(TG011) 入库数量,SUM(TG012) 报废数量,SUM(TG013) 验收数量,TC004 客户编号,MA002 客户简称
FROM MOCTG
INNER JOIN MOCTF ON TF001 = TG001 AND TF002 = TG002 
LEFT OUTER JOIN MOCTA ON TA001 = TG014 AND TA002 = TG015
LEFT OUTER JOIN COPTC ON TC001 = TA026 AND TC002 = TA027
LEFT OUTER JOIN COPMA ON MA001 = TC004
LEFT OUTER JOIN CMSMD ON MD001 = TA021
LEFT OUTER JOIN CMSME ON ME001 = MD015
INNER JOIN CMSMC ON MC001 = TG010
WHERE 
TF003 BETWEEN '20250101' AND '20251231'
AND TG009 = '1'
AND TF006 = 'Y'
AND CMSMC.UDF01 LIKE '%一部%'
AND MD002 NOT LIKE '%SMT%'
GROUP BY TG004,TG005,TG006,TG007,TG010,MC002,TC004,MA002
ORDER BY TG004,TG010