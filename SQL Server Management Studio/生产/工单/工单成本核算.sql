SELECT LA001,SUM(LA012)/COUNT(LA012) AS AA
INTO #A
FROM MOCTE
LEFT OUTER JOIN INVLA ON LA006 = TE001 AND LA007 = TE002 AND LA008 = TE003
WHERE TE011 = '5102'
AND TE012 = '25102901119'
--AND TE001 LIKE '54%'
GROUP BY LA001
ORDER BY LA001

SELECT SUM(AA) FROM #A

SELECT LA001,LA004,LA005,LA006,LA007,LA008,LA012,ROW_NUMBER() OVER(PARTITION BY LA001 ORDER BY LA004,LA007)AS RN
INTO #B
FROM MOCTE
LEFT OUTER JOIN INVLA ON LA006 = TE001 AND LA007 = TE002 AND LA008 = TE003
WHERE TE011 = '5102'
AND TE012 = '25102901119'
--AND TE001 LIKE '54%'
ORDER BY LA001

SELECT SUM(LA012)
FROM #B
WHERE RN = 1;