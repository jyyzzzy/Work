SELECT TE011,TE012 FROM MOCTE 
WHERE 
TE001 = '5401'
AND TE002 = '20251000001'
GROUP BY TE011,TE012
ORDER BY TE011,TE012


SELECT TE003 AS 领料单序号,
TB001 AS 工单单别,
TB002 AS 工单单号,
TB003 AS 材料品号,
TB004 AS 需领数量,
TB005 AS 已领数量,
TB005 - TB004 AS 超领数量
FROM MOCTE 
INNER JOIN MOCTB ON TB001 = TE011 AND TB002 = TE012 AND TB003 = TE004
WHERE TE001 = '5401'
AND TE002 = '20251000001'
AND TB005 > TB004
ORDER BY TB001,TB002,TB003