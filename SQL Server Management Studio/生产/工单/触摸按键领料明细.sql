SELECT 
SUBSTRING(ME002,1,4) AS 部门名称,
MOCTC.TC003 AS 领退料日期,
MOCTC.TC007 AS WMS单号,
CMSMD.MD002 AS 工作中心名称,
MOCTE.TE004 AS 品号,
MOCTE.TE017 AS 品名,
MOCTE.TE018 AS 规格,
SUM(MOCTE.TE005) AS 领退料数量,
MOCTE.TE011 AS 工单单别,
MOCTE.TE012 AS 工单单号,
MOCTE.TE008 AS 仓库编号,
CMSMC.MC002 AS 仓库名称,
MOCTC.TC014 AS 单据日期,
MOCTE.TE013 AS 领料说明
FROM MOCTE
INNER JOIN MOCTC ON TC001 = TE001 AND TC002 = TE002
LEFT OUTER JOIN CMSMC ON MC001 = MOCTE.TE008
LEFT OUTER JOIN CMSMD ON MD001 = MOCTC.TC005
LEFT OUTER JOIN CMSME ON ME001 = MD015
WHERE
MOCTE.TE017 = '触摸按键'
AND TC003 BETWEEN '20250901' AND '20250930'
GROUP BY 
SUBSTRING(ME002,1,4),
MOCTC.TC003,
MOCTC.TC007,
CMSMD.MD002,
MOCTE.TE004,
MOCTE.TE017,
MOCTE.TE018,
MOCTE.TE011,
MOCTE.TE012,
MOCTE.TE008,
CMSMC.MC002,
MOCTC.TC014,
MOCTE.TE013
ORDER BY 
MOCTC.TC003
