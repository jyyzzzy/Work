SELECT 
SUBSTRING(ME002,1,4) AS 部门名称,
INVLA.LA004 AS 领退料日期,
MOCTC.TC007 AS WMS单号,
CMSMD.MD002 AS 工作中心名称,
INVLA.LA001 AS 品号,
INVMB.MB002 AS 品名,
INVMB.MB003 AS 规格,
SUM(-1 * LA005 * LA011) AS 领退料数量,
INVLA.LA024 AS 对象,
INVLA.LA009 AS 仓库编号,
CMSMC.MC002 AS 仓库名称,
MOCTC.TC014 AS 单据日期,
MOCTE.TE013 AS 领料说明
FROM 
INVLA
INNER JOIN INVMB ON MB001 = LA001
INNER JOIN MOCTC ON TC001 = LA006 AND TC002 = LA007
INNER JOIN MOCTE ON TE001 = LA006 AND TE002 = LA007 AND TE003 = LA008
LEFT OUTER JOIN CMSMC ON MC001 = INVLA.LA009
LEFT OUTER JOIN CMSMD ON MD001 = MOCTC.TC005
LEFT OUTER JOIN CMSME ON ME001 = MD015
WHERE
INVMB.MB002 = '触摸按键'
AND INVLA.LA004 BETWEEN '20251201' AND '20251231'
GROUP BY 
SUBSTRING(ME002,1,4),
INVLA.LA004,
MOCTC.TC007,
CMSMD.MD002,
INVLA.LA001,
INVMB.MB002,
INVMB.MB003,
INVLA.LA024,
INVLA.LA009,
CMSMC.MC002,
MOCTC.TC014,
MOCTE.TE013
ORDER BY LA004,LA024

