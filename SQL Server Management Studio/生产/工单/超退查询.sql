SELECT 
TE001 单别,
TE002 单号,
TE003 AS 序号,
TE004 AS 材料品号,
TE009 AS 工艺,
TE011 AS 工单单别,
TE012 AS 工单单号,
TB004*TA017/TA015 AS 需领用量,
TB005 AS 已领用量,
TB005-TB004*TA017/TA015 AS 超领数量,
TE005 AS 退料数量,
TE005-(TB005-TB004*TA017/TA015) AS 超退数量,
CASE 
WHEN TE005>(TB005-TB004*TA017/TA015)
THEN 'Y'
ELSE 'N'
END AS 是否超退
FROM MOCTE 
INNER JOIN MOCTC ON TC001 = TE001 AND TC002 = TE002 
INNER JOIN MOCTB 
	ON TB001 = TE011 
	AND TB002 = TE012 
	AND TB003 = TE004 
	AND TB006 = TE009
INNER JOIN MOCTA ON TA001 = TE011 
	AND TA002 = TE012 
WHERE 
	TE005>(TB005-TB004*TA017/TA015)
	AND TA015 <> 0
	--AND TC003 BETWEEN '20251201' AND '20251231'
	--AND TC009 <> 'Y'
	--AND TC008 = '56'
	AND TE001 = '5672' 
	AND TE002 = '20260100019'
ORDER BY TE003,TE002,TE001

