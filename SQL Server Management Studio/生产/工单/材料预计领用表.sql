SELECT INVMB.MB109 as 核准状况,
	INVMB.MB001 as 品号,
	INVMB.MB002 as 品名,
	INVMB.MB003 as 规格,
	INVMB.MB004 as 单位,
	INVMA.MA003 as 类别,
	ISNULL((
		SELECT SUM(INVMC.MC007) AS KC002 
		FROM INVMC 
			INNER JOIN CMSMC ON INVMC.MC002 = CMSMC.MC001 
		WHERE CMSMC.MC005 = 'Y' 
			and INVMC.MC001= INVMB.MB001
	),0) as 库存数量,
	ISNULL(A.TB004,0) as 预计领用,
	ISNULL(B.TD008,0) as 预计销货,
	ISNULL(A.TB004,0) + ISNULL(B.TD008,0) as 未来需求量,
	INVMB.MB090 as 包装单位 
FROM INVMB as INVMB  
	Left JOIN INVMA as INVMA On INVMB.MB006=INVMA.MA002 
	LEFT JOIN (
		SELECT TB003,SUM(TB004-TB005) AS TB004 
		FROM MOCTB 
			INNER JOIN MOCTA ON TA001 = TB001 AND TA002 = TB002 
		WHERE TB004 > TB005 AND TA011 <> 'Y' AND TA011 <> 'y' AND TA013 = 'Y' 
		GROUP BY TB003
	) AS A ON INVMB.MB001 = A.TB003 
	LEFT JOIN (
		SELECT TD004,TD008-TD009 AS TD008 
		FROM COPTD 
		WHERE TD016 = 'N' AND TD021 = 'Y'
	) AS B ON B.TD004 = INVMB.MB001  
WHERE LEFT(MB001,1) IN ('3','5','6','7') --AND ((INVMB.MB025 = 'P'))
ORDER BY MB001