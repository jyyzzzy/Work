SELECT MA001 AS 客户编号,
MA002 AS 客户简称,
MA003 AS 客户全称,
TB003 AS 材料品号,
MB002 AS 材料品名,
MB003 AS 材料规格,
SUM(TB005) 总领用量
FROM 
COPMA
INNER JOIN COPTC ON TC004 = MA001 
INNER JOIN COPTD ON TC001 = TD001 AND TD002 = TC002
INNER JOIN MOCTA ON TA026 = TD001 AND TA027 = TD002 AND TA028 = TD003
INNER JOIN MOCTB ON TB001 = TA001 AND TB002 = TA002
INNER JOIN INVMB ON MB001 = TB003
WHERE 
COPMA.MA001 = '10500692'
AND TC003 BETWEEN '20250101' AND '20251015'
AND LEFT(MB001,1) IN ('3','5')
GROUP BY 
MA001,MA002,MA003,TB003,MB002,MB003
ORDER BY TB003


