SELECT TE003,TE004,TA014
FROM
MOCTE
INNER JOIN MOCTB ON TB001 = TE011 AND TB002 = TE012 AND TB003 = TE004
INNER JOIN MOCTA ON TA001 = TB001 AND TA002 = TB002
WHERE 
TE001 = '5602'
AND TE002 = '20260500002'
AND (TA011 = 'Y' OR TA011 = 'y')
AND TA014 < '20260501'

UPDATE MOCTC SET TC016 = 'N'
WHERE TC001 = '5602'
AND TC002 = '20260500002'