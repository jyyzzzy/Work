SELECT 
	TA040 AS MOCTATA040,
	CMSMD.MD002 AS CMSMDMD002,
	MOCTA.TA001 AS MOCTATA001,
	MOCTA.TA002 AS MOCTATA002,
	MOCTA.TA006 AS MOCTATA006,
	MOCTA.TA034 AS MOCTATA034 ,
	MOCTA.TA035 AS MOCTATA035,
	MOCTA.TA015 AS MOCTATA015,
	MOCTB.TB003 AS MOCTBTB003,
	MOCTB.TB012 AS MOCTBTB012,
	MOCTB.TB013 AS MOCTBTB013,
	MOCTB.TB007 AS MOCTBTB007,
	INVMB.MB090 AS MB090,
	MOCTB.TB004 AS MOCTBTB004,
	MOCTB.TB005 AS MOCTBTB005,
	(MOCTB.TB004-MOCTB.TB005) AS MOCTB001, 
	( 
		SELECT 
			SUM(ISNULL(INVMC.MC007,0)) 
		FROM  INVMB AS INVMB  
			LEFT OUTER JOIN INVMC AS INVMC ON INVMB.MB001=INVMC.MC001 
			LEFT OUTER JOIN CMSMC AS CMSMC ON INVMC.MC002 = CMSMC.MC001 
		WHERE 
			CMSMC.MC005='Y' 
			AND INVMC.MC007>0  
			AND  MB001=TB003 
	) AS WHS006, 
	(
		SELECT SUM(TH007) 
		FROM   PURTH 
		WHERE  
			TH030 = 'N' 
			AND TH004=TB003
	) TH007,
	(
		SELECT SUM(TB007) 
		FROM INVTB AS INVTB 
		WHERE 
			TB004=TB003 
			AND TB018 = 'N' 
			AND TB001='1112'
	) TB007,
	MOCTA.UDF02 AS MOCTAUDF02,
	MOCTA.TA026 AS MOCTATA026,
	MOCTA.TA027 AS MOCTATA027,
	MOCTA.TA028 AS MOCTATA028
	FROM MOCTB AS MOCTB  
		LEFT OUTER JOIN INVMB AS INVMB ON TB003=MB001  
		LEFT OUTER JOIN MOCTA AS MOCTA ON MOCTB.TB001=MOCTA.TA001 AND MOCTB.TB002=MOCTA.TA002 
		LEFT OUTER JOIN CMSMD AS CMSMD ON MOCTA.TA021=CMSMD.MD001  
	WHERE 
		(
				(MOCTA.TA011 = '2') 
				OR (MOCTA.TA011 = '3') 
				OR (
						MOCTA.TA011 = 
							CASE TA011
								WHEN 'N' 
									THEN '2' 
									ELSE '1' 
							END 
					)
			)  
	ORDER BY
		CMSMD.MD002 ASC,
		MOCTA.TA001 ASC,
		MOCTA.TA002 ASC
