/***领退料明细***/
--CREATE AT 2025/11/01 BY ZIYANG ZHANG
SELECT 
TC003 AS 领料日期,
TE001 AS 领料单别,
TE002 AS 领料单号,
TE003 AS 领料序号,
TC007 备注,
TC005 工作中心,
MD002 工作中心名称,
TC021 AS 部门,
ME002 部门名称,
TE004 AS 材料品号,
TE005 AS 领料数量,
TE006 材料单位,
TE008 AS 仓库编号,
MC002 仓库名称,
TE009 材料工艺,
TE017 材料品名,
TE018 材料规格

FROM MOCTE
INNER JOIN MOCTC ON TC001 = TE001 AND TC002 = TE002
INNER JOIN CMSMC ON MC001 = TE008
INNER JOIN CMSMD ON MD001 = TC005 
INNER JOIN CMSME ON ME001 = MD015
WHERE 
LEFT(TC001,2) = '54'
AND TC003 BETWEEN '20241001' AND '20251109'
AND TC009 = 'Y'
--AND TE018 LIKE '%需烧录%'
AND ME001 = '130200'
AND LEFT(MD002,1) = 'D'
ORDER BY TC003,TE001,TE002,TE003