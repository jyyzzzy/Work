--查询挪料单是否存在对应领/退料单
SELECT 
	TR001,
	TR002,
	CASE 
		WHEN C1.TC001 IS NOT NULL AND C2.TC001 IS NULL 
		THEN TR006
		ELSE TR004
	END AS TC001,
	CASE 
		WHEN C1.TC002 IS NOT NULL AND C2.TC002 IS NULL
		THEN TR007
		ELSE TR005
	END AS TC002
	FROM MOCTR 
	LEFT OUTER JOIN MOCTC AS C1 ON C1.TC001 = TR004 AND C1.TC002 = TR005
	LEFT OUTER JOIN MOCTC AS C2 ON C2.TC001 = TR006 AND C2.TC002 = TR007
	WHERE ((
				C1.TC001 IS NOT NULL 
				AND C1.TC002 IS NOT NULL
			) AND (
				C2.TC001 IS NULL 
				AND C2.TC002 IS NULL
				)
		) OR ((
				C1.TC001 IS NULL 
				AND C1.TC002 IS NULL
			) AND (
				C2.TC001 IS NOT NULL 
				AND C2.TC002 IS NOT NULL
			)
		)
	ORDER BY TR001,TR002 DESC;


--查询领/退料单是否存在对应挪料单
SELECT TC001, TC002
FROM MOCTC
WHERE TC001 IN ('54N1','56N1') AND TC009 = 'Y'

EXCEPT

SELECT TC001, TC002
FROM (
    SELECT TR004 AS TC001, TR005 AS TC002 FROM MOCTR WHERE TR004 IN ('54N1','56N1')
    UNION ALL
    SELECT TR006 AS TC001, TR007 AS TC002 FROM MOCTR WHERE TR006 IN ('54N1','56N1')
) AS P;

--排查挪料单异常状态
SELECT TR001,TR002,TR003,TR004,TR005,A.TC009,TR006,TR007,B.TC009 FROM MOCTR 
LEFT OUTER JOIN MOCTC AS A ON A.TC001 = TR004 AND A.TC002 = TR005
LEFT OUTER JOIN MOCTC AS B ON  B.TC001 = TR006 AND B.TC002 = TR007
WHERE 
A.TC009 <> B.TC009
ORDER BY TR003 DESC;

--排查挪料单异常状态
SELECT MOCTR.CREATOR,TR001,TR002,TR003,TR004,TR005,A.TC009,TR006,TR007,B.TC009 FROM MOCTR 
LEFT OUTER JOIN MOCTC AS A ON A.TC001 = TR004 AND A.TC002 = TR005
LEFT OUTER JOIN MOCTC AS B ON  B.TC001 = TR006 AND B.TC002 = TR007
WHERE 
A.TC009 <> 'Y'
OR B.TC009 <> 'Y'
ORDER BY TR003 DESC;