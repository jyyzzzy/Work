/*******根据工单信息更新领料单工艺******/
DROP TABLE #MOCTB -- 初始化临时表

SELECT * 
INTO #MOCTB 
FROM MOCTB 
WHERE TB001 = '5102' 
  AND TB002 = '25090900162'
  AND TB004 = 0;-- 将需求为0的工单单身插入临时表



UPDATE E
SET E.TE009 = TB.TB006
FROM MOCTE AS E
INNER JOIN #MOCTB AS TMP
  ON E.TE011 = TMP.TB001
 AND E.TE012 = TMP.TB002
 AND E.TE004 = TMP.TB003
INNER JOIN MOCTB AS TB
  ON TB.TB001 = TMP.TB001
 AND TB.TB002 = TMP.TB002
 AND TB.TB003 = TMP.TB003
WHERE TB.TB004 > 0
  AND E.TE009 = TMP.TB006;  -- 根据工单需求更新领料单工艺。
