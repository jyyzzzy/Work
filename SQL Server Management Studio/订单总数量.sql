    MB002 AS 品名,
    MB003 AS 规格,
    ISNULL(MA002,'') AS 客户简称,
    ISNULL(SUBSTRING(ME002,1,4),'') AS 事业部,
    SUM(CASE WHEN TC003 BETWEEN '20250101' AND '20241231' THEN TD008 ELSE 0 END) AS [2024年订单数量],
    SUM(CASE WHEN TC003 BETWEEN '20250101' AND '20241231' THEN TD009 ELSE 0 END) AS [2024年已交数量],
    SUM(CASE WHEN TC003 BETWEEN '20250101' AND '20251231' THEN TD008 ELSE 0 END) AS [2025年订单数量],
