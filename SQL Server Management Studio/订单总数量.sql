FROM INVMB
INNER JOIN LSSJ..ITEMTMP ON ITEMNO = MB001
LEFT JOIN COPTD ON TD004 = MB001
INNER JOIN COPTC ON TC001 = TD001 AND TC002 = TD002
LEFT JOIN COPMA ON MA001 = TC004
INNER JOIN MOCTA ON TA026 = TD001 AND TA027 = TD002 AND TA028 = TD003
INNER JOIN CMSMD ON MD001 = TA021
INNER JOIN CMSME ON ME001 = MD015
WHERE 
    (TC003 BETWEEN '20250101' AND '20261231' OR TC003 IS NULL)
    AND TD021 = 'Y'
GROUP BY MB001, MB002, MB003, MA002, SUBSTRING(ME002,1,4)
ORDER BY MB001;

