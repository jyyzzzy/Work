;WITH ITEM AS
(
    SELECT DISTINCT
        LTRIM(RTRIM(ITEMNO)) AS ITEMNO
    FROM LSSJ..ITEMTMP
    WHERE ISNULL(LTRIM(RTRIM(ITEMNO)), '') <> ''
),
U AS
(
    SELECT
        T.ITEMNO AS COMP,                                   -- 原始材料
        M.MD001 AS P,                                       -- 上阶主件
        CAST(M.MD006 AS DECIMAL(38,12)) AS CNT,             -- 用量
        CAST(1 AS INT) AS LVL,
        CAST('|' + RTRIM(T.ITEMNO) + '|' + RTRIM(M.MD001) + '|' AS VARCHAR(MAX)) AS PATH
    FROM ITEM T
    INNER JOIN BOMMD M
        ON M.MD003 = T.ITEMNO
    WHERE ISNULL(LTRIM(RTRIM(M.MD001)), '') <> ''

    UNION ALL

    SELECT
        U.COMP,
        M.MD001 AS P,
        CAST(U.CNT * CAST(M.MD006 AS DECIMAL(38,12)) AS DECIMAL(38,12)) AS CNT,
        U.LVL + 1 AS LVL,
        CAST(U.PATH + RTRIM(M.MD001) + '|' AS VARCHAR(MAX)) AS PATH
    FROM U
    INNER JOIN BOMMD M
        ON M.MD003 = U.P
    WHERE ISNULL(LTRIM(RTRIM(M.MD001)), '') <> ''
      AND U.LVL < 50
      AND CHARINDEX('|' + RTRIM(M.MD001) + '|', U.PATH) = 0
),
FATHER AS
(
    SELECT
        U.P AS 主件,
        U.COMP AS 元件,
        SUM(U.CNT) AS 用量
    FROM U
    WHERE U.P IS NOT NULL
      AND NOT EXISTS
      (
          SELECT 1
          FROM BOMMD Z
          WHERE Z.MD003 = U.P
      )
      AND LEFT(U.P, 1) IN ('1', 'A')
    GROUP BY
        U.P,
        U.COMP
)
SELECT
    主件 AS PROD,
    元件 AS MATL,
    用量 AS CNT
INTO #RELATION
FROM FATHER
OPTION (MAXRECURSION 100);

