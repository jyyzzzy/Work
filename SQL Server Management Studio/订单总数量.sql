USE SDRD;
SELECT 
    MB001 AS 品号,
    MB002 AS 品名,
    MB003 AS 规格,
    ISNULL(MA002,'') AS 客户简称,
    ISNULL(SUBSTRING(ME002,1,4),'') AS 事业部,
    SUM(CASE WHEN TC003 BETWEEN '20240101' AND '20241231' THEN TD008 ELSE 0 END) AS [2024年订单数量],
    SUM(CASE WHEN TC003 BETWEEN '20240101' AND '20241231' THEN TD009 ELSE 0 END) AS [2024年已交数量],
    SUM(CASE WHEN TC003 BETWEEN '20250101' AND '20251231' THEN TD008 ELSE 0 END) AS [2025年订单数量],
    SUM(CASE WHEN TC003 BETWEEN '20250101' AND '20251231' THEN TD009 ELSE 0 END) AS [2025年已交数量]
FROM INVMB
INNER JOIN LSSJ..ITEMTMP ON ITEMNO = MB001
LEFT JOIN COPTD ON TD004 = MB001
INNER JOIN COPTC ON TC001 = TD001 AND TC002 = TD002
LEFT JOIN COPMA ON MA001 = TC004
INNER JOIN MOCTA ON TA026 = TD001 AND TA027 = TD002 AND TA028 = TD003
INNER JOIN CMSMD ON MD001 = TA021
INNER JOIN CMSME ON ME001 = MD015
WHERE 
    (TC003 BETWEEN '20240101' AND '20251231' OR TC003 IS NULL)
    AND TD021 = 'Y'
GROUP BY MB001, MB002, MB003, MA002, SUBSTRING(ME002,1,4)
ORDER BY MB001;

