SELECT 
	WHS02.COMPANY AS 公司别,
	WHS02.WHS001 AS 单号,
	WHS02.WHS002 AS 品号,
	WHS02.WHS003 AS 品名,
	WHS02.WHS004 AS 规格,
	WHS02.WHS009 AS 日期,
	WHS02.WHS005 AS 状态,
	WHS02.WHS006 AS 数量,
	WHS02.WHS007 AS 数量2,
	WHS02.WHS008 AS 单位,
	WHS02.WHS010 AS 库位
	--,WHS02.DOC_TYPE AS 订单单别
	--,WHS02.DOC_NO AS 订单单号
	--,WHS02.LINE_NO AS 订单序号
	--,WHS02.CUSTOMER_CODE AS 客户编号
	--,WHS02.CUSTOMER_SHORT_NAME AS 客户简称
FROM (
	SELECT WHS02.*,
		'SDRD' AS COMPANY 
		--,MOCTA.TA026 AS DOC_TYPE
		--,MOCTA.TA027 AS DOC_NO
		--,MOCTA.TA028 AS LINE_NO
		--,COPTC.TC004 AS CUSTOMER_CODE
		--,COPMA.MA002 AS CUSTOMER_SHORT_NAME
	FROM SDRD..WHS02 AS WHS02
		INNER JOIN SDRD..INVMB AS INVMB ON INVMB.MB001 = WHS02.WHS002
		--LEFT OUTER JOIN SDRD..MOCTA AS MOCTA ON MOCTA.TA001 + '-' + MOCTA.TA002 = LEFT(WHS02.WHS001,16)--关联工单
		--LEFT OUTER JOIN SDRD..COPTC AS COPTC ON COPTC.TC001 = MOCTA.TA026 AND COPTC.TC002 = MOCTA.TA027--关联订单
		--LEFT OUTER JOIN SDRD..COPMA AS COPMA ON COPMA.MA001 =COPTC.TC004 --关联客户
	WHERE INVMB.MB109 = 'Y'--关联核准代码
	UNION ALL
	SELECT WHS02.*,
		'ZJRD' AS COMPANY 
		--,MOCTA.TA026 AS DOC_TYPE
		--,MOCTA.TA027 AS DOC_NO
		--,MOCTA.TA028 AS LINE_NO
		--,COPTC.TC004 AS CUSTOMER_CODE
		--,COPMA.MA002 AS CUSTOMER_SHORT_NAME
	FROM ZJRD..WHS02 AS WHS02
		INNER JOIN ZJRD..INVMB AS INVMB ON INVMB.MB001 = WHS02.WHS002
		--LEFT OUTER JOIN ZJRD..MOCTA AS MOCTA ON MOCTA.TA001 + '-' + MOCTA.TA002 = LEFT(WHS02.WHS001,16)
		--LEFT OUTER JOIN ZJRD..COPTC AS COPTC ON COPTC.TC001 = MOCTA.TA026 AND COPTC.TC002 = MOCTA.TA027
		--LEFT OUTER JOIN ZJRD..COPMA AS COPMA ON COPMA.MA001 =COPTC.TC004 
	WHERE INVMB.MB109 = 'Y'
	UNION ALL
	SELECT WHS02.*,
		'AHRD' AS COMPANY 
		--,MOCTA.TA026 AS DOC_TYPE
		--,MOCTA.TA027 AS DOC_NO
		--,MOCTA.TA028 AS LINE_NO
		--,COPTC.TC004 AS CUSTOMER_CODE
		--,COPMA.MA002 AS CUSTOMER_SHORT_NAME
	FROM AHRD..WHS02 AS WHS02
		INNER JOIN AHRD..INVMB AS INVMB ON INVMB.MB001 = WHS02.WHS002
		--LEFT OUTER JOIN AHRD..MOCTA AS MOCTA ON MOCTA.TA001 + '-' + MOCTA.TA002 = LEFT(WHS02.WHS001,16)
		--LEFT OUTER JOIN AHRD..COPTC AS COPTC ON COPTC.TC001 = MOCTA.TA026 AND COPTC.TC002 = MOCTA.TA027
		--LEFT OUTER JOIN AHRD..COPMA AS COPMA ON COPMA.MA001 =COPTC.TC004 
	WHERE INVMB.MB109 = 'Y'
	UNION ALL
	SELECT WHS02.*,
		'YNRD' AS COMPANY 
		--,MOCTA.TA026 AS DOC_TYPE
		--,MOCTA.TA027 AS DOC_NO
		--,MOCTA.TA028 AS LINE_NO
		--,COPTC.TC004 AS CUSTOMER_CODE
		--,COPMA.MA002 AS CUSTOMER_SHORT_NAME
	FROM YNRD..WHS02 AS WHS02
		INNER JOIN YNRD..INVMB AS INVMB ON INVMB.MB001 = WHS02.WHS002
		--LEFT OUTER JOIN YNRD..MOCTA AS MOCTA ON MOCTA.TA001 + '-' + MOCTA.TA002 = LEFT(WHS02.WHS001,16)
		--LEFT OUTER JOIN YNRD..COPTC AS COPTC ON COPTC.TC001 = MOCTA.TA026 AND COPTC.TC002 = MOCTA.TA027
		--LEFT OUTER JOIN YNRD..COPMA AS COPMA ON COPMA.MA001 =COPTC.TC004 
	WHERE INVMB.MB109 = 'Y'
) AS WHS02 
	--INNER JOIN LSSJ..ITEMTMP ON ITEMNO = WHS02.WHS002
WHERE NULL IS NULL
	--AND WHS02.WHS009 >= '20250701'
	--OR WHS02.WHS009 = '00000000'
	--AND WHS02.WHS002 = '303000502600'
	AND LEFT(WHS02.WHS005,2) = '工单'
	--AND WHS02.WHS006 > WHS02.WHS007
ORDER BY  
	CASE LEFT(WHS02.WHS001,2) 
		WHEN '00' 
		THEN 0 
		ELSE 1 
	END ,
	WHS02.WHS007 ASC,
	WHS02.WHS001 ASC
