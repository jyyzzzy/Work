SELECT '瑞德智能' AS 所属账套,
	ITEMNO AS 品号,
	MB002 AS 品名,
	MB003 AS 规格,
	TD001 AS 订单单别,
	TD002 AS 订单单号,
	TD003 AS 订单序号,
	TC004 AS 客户编号,
	MA002 AS 客户简称,
	TA001 AS 工单单别,
	TA002 AS 工单单号,
	LEFT(LA004,6) AS 入库年月,
	SUM(ISNULL(LA011,0)) AS 入库数量,
	TD008 AS 订单数量,
	CAST((TD011*TC009) AS NUMERIC(17,8)) AS 本币单价,
	CAST(SUM(ISNULL(LA011,0))*CAST((TD011*TC009) AS NUMERIC(17,8)) AS NUMERIC(15,2)) 本币入库金额
FROM LSSJ..ITEMTMP AS ITEM
INNER JOIN SDRD..INVMB ON MB001 = ITEM.ITEMNO 
INNER JOIN SDRD..COPTD ON TD004 = ITEM.ITEMNO --TD001 = TA026 AND TD002 = TA027 AND TD003 = TA028
INNER JOIN SDRD..COPTC ON TC001 = TD001 AND TC002 = TD002
LEFT OUTER JOIN SDRD..COPMA ON MA001 = TC004
LEFT OUTER  JOIN SDRD..MOCTA ON TD001 = TA026 AND TD002 = TA027 AND TD003 = TA028 AND TA006 = ITEM.ITEMNO--TA001 = TG014 AND TA002 = TG015
--LEFT OUTER JOIN SDRD..MOCTG ON TA001 = TG014 AND TA002 = TG015 AND TG004 = ITEM.ITEMNO--TG004 = ITEM.ITEMNO
--LEFT OUTER JOIN SDRD..MOCTF ON TF001 = TD001 AND TF002 = TG002
LEFT OUTER  JOIN SDRD..INVLA ON LA024 = TA001 + '-'+ TA002 AND LA001 = ITEM.ITEMNO --LA006 = TG001 AND LA007 = TG002 AND LA008 = TG003
WHERE TC027 = 'Y'
AND ISNULL(TA013,'Y') = 'Y'
AND LA004 BETWEEN '20130101' AND '20251130'
GROUP BY ITEMNO,
	MB002,
	MB003,
	LEFT(LA004,6),
	TA001,
	TA002,
	TD001,
	TD002,
	TD003,
	TD008,
	TD011,
	TC004,
	MA002,
	TC009

UNION ALL

