SELECT 
	MOCTA.TA001 宸ュ崟鍗曞埆,
	MOCTA.TA002 宸ュ崟鍗曞彿,
	MOCTA.TA003 宸ュ崟鏃ユ湡,
	MOCTA.TA006 浜у搧鍝佸彿,
	MOCTA.UDF02 宸蹭笅鍗?
	ITEM.ITEMNO 鏉愭枡鍝佸彿,
	MOCTB.TB004 闇€棰嗙敤閲?
	MOCTB.TB006 鏉愭枡宸ヨ壓,
	MOCTB.TB007 鏉愭枡鍗曚綅,
	MOCTB.TB012 鏉愭枡鍝佸悕,
	MOCTB.TB013 鏉愭枡瑙勬牸,
	MOCTA.TA026 璁㈠崟鍗曞埆,
	MOCTA.TA027 璁㈠崟鍗曞彿,
	MOCTA.TA028 璁㈠崟搴忓彿,
	SUM(ISNULL(PURTB.TB009,0)) 璇疯喘鏁伴噺,
	SUM(ISNULL(PURTD.TD008,0)) 閲囪喘鏁伴噺,
	SUM(ISNULL(PURTD.TD015,0)) 宸蹭氦鏁伴噺,
	SUM(ISNULL(PURTH.TH015,0)) 楠屾敹鏁伴噺
FROM LSSJ..ITEMTMP AS ITEM 
INNER JOIN MOCTB --宸ュ崟鍗曡韩
	ON ITEM.ITEMNO = MOCTB.TB003
INNER JOIN MOCTA --宸ュ崟鍗曞ご
	ON	MOCTA .TA001 = MOCTB.TB001 
	AND MOCTA.TA002 = MOCTB.TB002
INNER JOIN PURTB --璇疯喘鍗曡韩
	ON PURTB.TB029 = MOCTB.TB001 
	AND PURTB.TB030 = MOCTB.TB002 
	AND PURTB.TB004 = ITEM.ITEMNO
INNER JOIN PURTA --璇疯喘鍗曞ご
	ON PURTA.TA001 = PURTB.TB001 
	AND PURTA.TA002 = PURTB.TB002
LEFT OUTER JOIN PURTD --閲囪喘鍗曡韩
	ON PURTD.TD026 = PURTB.TB001 
	AND PURTD.TD027 = PURTB.TB002 
	AND PURTD.TD028 = PURTB.TB003
LEFT OUTER JOIN PURTC --閲囪喘鍗曞ご
	ON PURTC.TC001 = PURTD.TD001
	AND PURTC.TC002 = PURTD.TD002
LEFT OUTER JOIN PURTH --杩涜揣鍗曡韩
	ON PURTH.TH011 = PURTD.TD001
	AND PURTH.TH012 = PURTD.TD002
	AND PURTH.TH013 = PURTD.TD003
LEFT OUTER JOIN PURTG --杩涜揣鍗曞ご
	ON PURTG.TG001 = PURTH.TH001
	AND PURTG.TG002 = PURTH.TH002
--LEFT OUTER JOIN COPTI --璁㈠崟鍗曞ご

GROUP BY ITEM.ITEMNO,
	MOCTA.TA003,
	MOCTA.TA002,
	MOCTA.TA001,
	MOCTA.TA006,
	MOCTB.TB004,
	MOCTB.TB006,
	MOCTB.TB007,
	MOCTB.TB012,
	MOCTB.TB013,
	MOCTA.UDF02,
	MOCTA.TA026,
	MOCTA.TA027,
	MOCTA.TA028
HAVING SUM(ISNULL(PURTB.TB009,0))>SUM(ISNULL(PURTH.TH015,0))--璇疯喘澶т簬楠屾敹锛堝湪閫旀暟閲忛渶鏀逛负閲囪喘澶т簬楠屾敹锛?
ORDER BY MOCTA.TA003,MOCTA.TA002,MOCTA.TA001

