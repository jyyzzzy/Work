--工单在途数量
USE SDRD

SELECT 
	MOCTA.TA001 工单单别,
	MOCTA.TA002 工单单号,
	MOCTA.TA003 工单日期,
	MOCTA.TA006 产品品号,
	MOCTA.UDF02 已下单,
	ITEM.ITEMNO 材料品号,
	MOCTB.TB004 需领用量,
	MOCTB.TB006 材料工艺,
	MOCTB.TB007 材料单位,
	MOCTB.TB012 材料品名,
	MOCTB.TB013 材料规格,
	MOCTA.TA026 订单单别,
	MOCTA.TA027 订单单号,
	MOCTA.TA028 订单序号,
	SUM(ISNULL(PURTB.TB009,0)) 请购数量,
	SUM(ISNULL(PURTD.TD008,0)) 采购数量,
	SUM(ISNULL(PURTD.TD015,0)) 已交数量,
	SUM(ISNULL(PURTH.TH015,0)) 验收数量
FROM LSSJ..ITEMTMP AS ITEM 
INNER JOIN MOCTB --工单单身
	ON ITEM.ITEMNO = MOCTB.TB003
INNER JOIN MOCTA --工单单头
	ON	MOCTA .TA001 = MOCTB.TB001 
	AND MOCTA.TA002 = MOCTB.TB002
INNER JOIN PURTB --请购单身
	ON PURTB.TB029 = MOCTB.TB001 
	AND PURTB.TB030 = MOCTB.TB002 
	AND PURTB.TB004 = ITEM.ITEMNO
INNER JOIN PURTA --请购单头
	ON PURTA.TA001 = PURTB.TB001 
	AND PURTA.TA002 = PURTB.TB002
LEFT OUTER JOIN PURTD --采购单身
	ON PURTD.TD026 = PURTB.TB001 
	AND PURTD.TD027 = PURTB.TB002 
	AND PURTD.TD028 = PURTB.TB003
LEFT OUTER JOIN PURTC --采购单头
	ON PURTC.TC001 = PURTD.TD001
	AND PURTC.TC002 = PURTD.TD002
LEFT OUTER JOIN PURTH --进货单身
	ON PURTH.TH011 = PURTD.TD001
	AND PURTH.TH012 = PURTD.TD002
	AND PURTH.TH013 = PURTD.TD003
LEFT OUTER JOIN PURTG --进货单头
	ON PURTG.TG001 = PURTH.TH001
	AND PURTG.TG002 = PURTH.TH002
--LEFT OUTER JOIN COPTI --订单单头

GROUP BY ITEM.ITEMNO,
	MOCTA.TA003,
	MOCTA.TA002,
	MOCTA.TA001,
	MOCTA.TA006,
	MOCTB.TB004,
	MOCTB.TB006,
	MOCTB.TB007,
	MOCTB.TB012,
	MOCTB.TB013,
	MOCTA.UDF02,
	MOCTA.TA026,
	MOCTA.TA027,
	MOCTA.TA028
HAVING SUM(ISNULL(PURTB.TB009,0))>SUM(ISNULL(PURTH.TH015,0))--请购大于验收（在途数量需改为采购大于验收）
ORDER BY MOCTA.TA003,MOCTA.TA002,MOCTA.TA001

