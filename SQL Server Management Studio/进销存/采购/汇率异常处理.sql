	CAST((TH016 * TH018 * TG030)/(1 + TG030 ) AS NUMERIC(15,2)) ,
	CAST(TH018*TH016*TG008/(1+TG030) AS NUMERIC(15,2)) ,
	CAST((TH016 * TH018 * TG030 * TG008)/(1 + TG030 )AS NUMERIC(15,2))
FROM PURTH INNER JOIN PURTG ON TG001 = TH001 AND TG002 = TH002 
WHERE 
TG003 BETWEEN '20250801'AND '20251031'
AND TH030='Y'
AND  TG016 NOT IN( '采购月末退货月初进仓','代管料转月月初入库单')
