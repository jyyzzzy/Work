SELECT 
'SDRD' AS COMPANY,
TC003 AS 审核日期,
TD001 AS 采购单别,
TD002 AS 采购单号,
TD003 AS 采购序号,
TC009 AS 订单编号,
TD012 AS 订单预计到货日期,
PURTD.UDF05 AS 供应商回复交期,
MA002 AS 供应商名称,
TD004 AS 物料编号,
TD005 AS 物料名称,
TD006 AS 规格型号,
TD008 AS 采购数量,
TD010 AS 含税单价,
ISNULL(QTY.QTH007,0) AS 送货数量,
TD008 - ISNULL(QTY.QTH007,0) AS 可制单剩余数量,
ISNULL(QTH015, 0) AS 合格入库数量,
TD014 AS 备注,
CASE TD016
	WHEN 'N'
	THEN '未结束'
	WHEN 'Y'
	THEN '自动结束'
	WHEN 'y'
	THEN '指定结束'
	ELSE TD016
END
AS 确认状态,
TC004 AS 供应商编号,
TD009 AS 单位,
TD010/(1+TD033) AS 不含税单价,
TD011 AS 金额,
TD033 AS 税率,
TD035 AS 税额,
TD034 AS 不含税金额,
TD007 AS 默认仓库名称
FROM 
	SDRD..PURTD
	INNER JOIN SDRD..PURTC ON TC001 = TD001 AND TC002 = TD002 
	INNER JOIN SDRD..PURMA ON MA001 = TC004
	LEFT OUTER JOIN (
		SELECT TH011 AS QTH011,TH012 AS QTH012,TH013 AS QTH013,SUM(TH007) AS QTH007,SUM(TH015) AS QTH015
		FROM SDRD..PURTH 
		GROUP BY TH011,TH012,TH013
	) AS QTY ON QTY.QTH011 = TD001 AND QTY.QTH012 = TD002 AND QTY.QTH013 = TD003
WHERE MA002 LIKE '%天波港联%'
AND TD016 = 'N'

