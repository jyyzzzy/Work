/*******转月代管料查询******/
--CREATE AT 202512/11
SELECT 
TG001 单别,
TG002 单号,
TG003 日期,
TG005 供应商,
TG016 备注
FROM PURTG
WHERE TG003 BETWEEN '20260401' AND '20260431'
AND TG016 IN (N'代管料转月月初入库单',N'采购月末退货月初进仓')

UNION ALL 

SELECT 
TI001 单别,
TI002 单号,
TI003 日期,
TI004 供应商,
TI012 备注
FROM PURTI
WHERE TI003 BETWEEN '20260401' AND '20260431'
AND TI012 IN (N'代管料转月月末退货单',N'月末批量开退货单')
ORDER BY 单别,单号 


