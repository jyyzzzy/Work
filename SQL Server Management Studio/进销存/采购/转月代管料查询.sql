SELECT 
TG001 单别,
TG002 单号,
TG003 日期,
TG005 供应商,
TG016 备注,
TH003 序号,
TH004 品号,
TH005 品名,
TH006 规格,
TH007 数量,
TH009 仓库
FROM PURTG
INNER JOIN PURTH ON TG001 = TH001 AND TG002 = TH002
WHERE TG003 BETWEEN '20260401' AND '20260431'
AND TG016 IN (N'代管料转月月初入库单',N'采购月末退货月初进仓')

UNION ALL

SELECT 
TI001 单别,
TI002 单号,
TI003 日期,
TI004 供应商,
TI012 备注,
TJ003 序号,
TJ004 品号,
TJ005 品名,
TJ006 规格,
TJ009 数量,
TJ011 仓库
FROM PURTI
INNER JOIN PURTJ ON TI001 = TJ001 AND TI002 = TJ002
WHERE TI003 BETWEEN '20260401' AND '20260431'
AND TI012 IN (N'代管料转月月末退货单',N'月末批量开退货单')
