SELECT 
MB001 AS 品号,
MB002 AS 品名,
MB003 AS 规格,
MB004 AS 单位,
LA004 AS 日期,
CASE 
	LA005
	WHEN 1
	THEN '退料'
	WHEN -1 
	THEN '领料'
END 


 AS 出入别,
LA006 AS 单别,
LA007 AS 单号,
LA008 AS 序号,
LA009 AS 仓库,
-1*LA005*LA011 AS 领退料数量
FROM 
INVLA 
INNER JOIN INVMB ON MB001 = LA001
WHERE 
SUBSTRING(LA006,1,1) = '5'
AND LA004 BETWEEN '20240801' AND '20241231'
AND CHARINDEX(MB002, '端子')>0
-- GROUP BY LA001,MB001,MB002,MB003,MB004
ORDER BY LA004