DECLARE @dt varchar(8);
SET @dt = CONVERT(varchar(6), DATEADD(MONTH,-25, GETDATE()), 112) + '01';

-- 统一取数并修正三处跨库误连、纳入负向异动、用可比较日期
;WITH U AS (
    -- 生产回冲/入库
    SELECT TE001 AS DocType, TE002 AS DocNo, TC003 AS DocDate8, TE004 AS Item, TE005 AS Qty,
           CONVERT(date, TC003, 112) AS TxnDate
    FROM SDRD..MOCTC C
    JOIN SDRD..MOCTE E ON C.TC001 = E.TE001 AND C.TC002 = E.TE002
    JOIN SDRD..INVMB  M ON E.TE004 = M.MB001 AND M.MB109 = 'Y'
    WHERE C.TC003 >= @dt AND ABS(E.TE005) <> 0

    UNION ALL
    SELECT TE001, TE002, TC003, TE004, TE005, CONVERT(date, TC003, 112)
    FROM ZJRD..MOCTC C
    JOIN ZJRD..MOCTE E ON C.TC001 = E.TE001 AND C.TC002 = E.TE002
    JOIN ZJRD..INVMB  M ON E.TE004 = M.MB001 AND M.MB109 = 'Y'
    WHERE C.TC003 >= @dt AND ABS(E.TE005) <> 0

    UNION ALL
    -- 修正：AHRD 正确连 AHRD..MOCTE 与 AHRD..INVMB
    SELECT TE001, TE002, TC003, TE004, TE005, CONVERT(date, TC003, 112)
    FROM AHRD..MOCTC C
    JOIN AHRD..MOCTE E ON C.TC001 = E.TE001 AND C.TC002 = E.TE002
    JOIN AHRD..INVMB  M ON E.TE004 = M.MB001 AND M.MB109 = 'Y'
    WHERE C.TC003 >= @dt AND ABS(E.TE005) <> 0

    -- 销售出货
    UNION ALL
    SELECT TG001, TG002, TG003, TH004, TH008, CONVERT(date, TG003, 112)
    FROM SDRD..COPTG G
    JOIN SDRD..COPTH H ON G.TG001 = H.TH001 AND G.TG002 = H.TH002
    JOIN SDRD..INVMB  M ON H.TH004 = M.MB001 AND M.MB109 = 'Y'
    WHERE G.TG003 >= @dt AND ABS(H.TH008) <> 0

    UNION ALL
    SELECT TG001, TG002, TG003, TH004, TH008, CONVERT(date, TG003, 112)
    FROM ZJRD..COPTG G
    JOIN ZJRD..COPTH H ON G.TG001 = H.TH001 AND G.TG002 = H.TH002
    JOIN ZJRD..INVMB  M ON H.TH004 = M.MB001 AND M.MB109 = 'Y'
    WHERE G.TG003 >= @dt AND ABS(H.TH008) <> 0

    UNION ALL
    -- 修正：AHRD 正确连 AHRD..COPTH 与 AHRD..INVMB
    SELECT TG001, TG002, TG003, TH004, TH008, CONVERT(date, TG003, 112)
    FROM AHRD..COPTG G
    JOIN AHRD..COPTH H ON G.TG001 = H.TH001 AND G.TG002 = H.TH002
    JOIN AHRD..INVMB  M ON H.TH004 = M.MB001 AND M.MB109 = 'Y'
    WHERE G.TG003 >= @dt AND ABS(H.TH008) <> 0

    -- 库存异动（含领退料、调拨等，正负都算异动）
    UNION ALL
    SELECT TB001, TB002, TA003, TB004, TB007, CONVERT(date, TA003, 112)
    FROM SDRD..INVTA A
    JOIN SDRD..INVTB B ON A.TA001 = B.TB001 AND A.TA002 = B.TB002
    JOIN SDRD..INVMB  M ON B.TB004 = M.MB001 AND M.MB109 = 'Y'
    WHERE A.TA003 >= @dt AND ABS(B.TB007) <> 0

    UNION ALL
    SELECT TB001, TB002, TA003, TB004, TB007, CONVERT(date, TA003, 112)
    FROM ZJRD..INVTA A
    JOIN ZJRD..INVTB B ON A.TA001 = B.TB001 AND A.TA002 = B.TB002
    JOIN ZJRD..INVMB  M ON B.TB004 = M.MB001 AND M.MB109 = 'Y'
    WHERE A.TA003 >= @dt AND ABS(B.TB007) <> 0

    UNION ALL
    -- 修正：AHRD 正确连 AHRD..INVTB 与 AHRD..INVMB
    SELECT TB001, TB002, TA003, TB004, TB007, CONVERT(date, TA003, 112)
    FROM AHRD..INVTA A
    JOIN AHRD..INVTB B ON A.TA001 = B.TB001 AND A.TA002 = B.TB002
    JOIN AHRD..INVMB  M ON B.TB004 = M.MB001 AND M.MB109 = 'Y'
    WHERE A.TA003 >= @dt AND ABS(B.TB007) <> 0
),
M AS (
    SELECT DocType AS TE001, DocNo AS TE002, DocDate8 AS TC003, Item AS TE004, Qty AS TE005,
           ROW_NUMBER() OVER (PARTITION BY Item ORDER BY TxnDate DESC, DocType DESC, DocNo DESC) AS rn
    FROM U
)
SELECT TE001, TE002, TE004, TC003, TE005
INTO #MOC
FROM M
WHERE rn = 1;

-- 库存汇总不变
SELECT SUM(ISNULL(MC007,0)) AS MC007, MC001
INTO #INVMC
FROM (
    SELECT INVMC.MC007, INVMC.MC001
    FROM SDRD..INVMC INVMC
    JOIN SDRD..CMSMC CMSMC ON INVMC.MC002 = CMSMC.MC001
    WHERE INVMC.MC007 > 0 AND RIGHT(CMSMC.UDF01,3) <> '不良品'
    UNION ALL
    SELECT INVMC.MC007, INVMC.MC001
    FROM ZJRD..INVMC INVMC
    JOIN ZJRD..CMSMC CMSMC ON INVMC.MC002 = CMSMC.MC001
    WHERE INVMC.MC007 > 0 AND RIGHT(CMSMC.UDF01,3) <> '不良品'
    UNION ALL
    SELECT INVMC.MC007, INVMC.MC001
    FROM AHRD..INVMC INVMC
    JOIN AHRD..CMSMC CMSMC ON INVMC.MC002 = CMSMC.MC001
    WHERE INVMC.MC007 > 0 AND RIGHT(CMSMC.UDF01,3) <> '不良品'
) T
GROUP BY MC001;

-- 创建人缓存不变
SELECT DISTINCT MV001, MV002
INTO #CMSMV
FROM (
    SELECT MV001, MV002 FROM SDRD..CMSMV
    UNION ALL
    SELECT MV001, MV002 FROM ZJRD..CMSMV
    UNION ALL
    SELECT MV001, MV002 FROM AHRD..CMSMV
) X;

-- 主查询（保留 TOP 100000 以避免超时）
SELECT TOP 100000
    RTRIM(MB001) AS 品号,
    RTRIM(MB002) AS 品名,
    RTRIM(MB003) AS 规格,
    RTRIM(MB004) AS 单位,
    ISNULL(MC007,0) AS 库存,
    ISNULL( (SELECT COUNT(*) FROM SDRD.dbo.Fn_GetBOMUpIDs(MB001) BOM WHERE LEFT(BOM.MD01,1) IN ('A','1')), 0 ) AS 成品数量,
    ISNULL(UDF05,'') AS 采购选型,
    ISNULL(MOC.TC003,'') AS 最后交易日,
    ISNULL(MOC.TE005,0) AS 最后交易数量,
    LEFT(CREATE_DATE,8) AS 物料创建时间,
    RTRIM(CREATOR) + RTRIM(ISNULL(MV002,'')) AS 物料创建人,
    MB.MB109 AS 核准状况,
    ISNULL(MOC.TE001,'') AS 单别,
    ISNULL(MOC.TE002,'') AS 单号,
    'N' AS 有代管库存
FROM SDRD..INVMB MB
LEFT JOIN #MOC    MOC ON MOC.TE004 = MB.MB001
LEFT JOIN #INVMC  MC  ON MC.MC001 = MB.MB001 AND MB.MB109 = 'Y'
LEFT JOIN #CMSMV  MV  ON MV.MV001 = MB.CREATOR
WHERE MB.MB109 = 'Y'
  AND LEFT(MB001,2) <> 'LS'
  AND LEFT(MB001,1) <> 'P'
ORDER BY MB001;

DROP TABLE #MOC;
DROP TABLE #INVMC;
DROP TABLE #CMSMV;
