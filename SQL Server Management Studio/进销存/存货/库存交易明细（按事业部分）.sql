SELECT DISTINCT ITEMNO AS 品号,
MB002 AS 品名,
MB003 AS 规格,
LEFT(INVI.ME002,4) AS 事业部门,
INVI.LA011 AS 领料数量,
INVR.LA011 AS 退料数量
FROM 
LSSJ..ITEMTMP AS ITEM
INNER JOIN (
	SELECT LA001,SUM(LA011) AS LA011,ME001,ME002
	FROM SDRD..INVLA 
	LEFT OUTER JOIN SDRD..MOCTC ON TC001 = LA006 AND TC002 = LA007
	LEFT OUTER JOIN SDRD..CMSMD ON MD001 = TC005 
	LEFT OUTER JOIN SDRD..CMSME ON MD015 = ME001
	WHERE LEFT(LA006,2) = '54' AND LA004 BETWEEN '20251001' AND '20251031'
	GROUP BY LA001,ME001,ME002
	UNION ALL
	SELECT LA001,SUM(LA011) AS LA011,ME001,ME002
	FROM ZJRD..INVLA
		LEFT OUTER JOIN ZJRD..MOCTC ON TC001 = LA006 AND TC002 = LA007
	LEFT OUTER JOIN ZJRD..CMSMD ON MD001 = TC005 
	LEFT OUTER JOIN ZJRD..CMSME ON MD015 = ME001
	WHERE LEFT(LA006,2) = '54' AND LA004 BETWEEN '20251001' AND '20251031'
	GROUP BY LA001,ME001,ME002
	UNION ALL
	SELECT LA001,SUM(LA011) AS LA011,ME001,ME002
	FROM AHRD..INVLA
		LEFT OUTER JOIN AHRD..MOCTC ON TC001 = LA006 AND TC002 = LA007
	LEFT OUTER JOIN AHRD..CMSMD ON MD001 = TC005 
	LEFT OUTER JOIN AHRD..CMSME ON MD015 = ME001
	WHERE LEFT(LA006,2) = '54' AND LA004 BETWEEN '20251001' AND '20251031'
	GROUP BY LA001,ME001,ME002
	UNION ALL
	SELECT LA001,SUM(LA011) AS LA011,ME001,ME002
	FROM YNRD..INVLA
		LEFT OUTER JOIN YNRD..MOCTC ON TC001 = LA006 AND TC002 = LA007
	LEFT OUTER JOIN YNRD..CMSMD ON MD001 = TC005 
	LEFT OUTER JOIN YNRD..CMSME ON MD015 = ME001
	WHERE LEFT(LA006,2) = '54' AND LA004 BETWEEN '20251001' AND '20251031'
	GROUP BY LA001,ME001,ME002
) AS INVI ON INVI.LA001 = ITEM.ITEMNO

INNER JOIN (
	SELECT LA001,SUM(LA011) AS LA011,ME001,ME002
	FROM SDRD..INVLA 
	LEFT OUTER JOIN SDRD..MOCTC ON TC001 = LA006 AND TC002 = LA007
	LEFT OUTER JOIN SDRD..CMSMD ON MD001 = TC005 
	LEFT OUTER JOIN SDRD..CMSME ON MD015 = ME001
	WHERE LEFT(LA006,2) = '56' AND LA004 BETWEEN '20251001' AND '20251031'
	GROUP BY LA001,ME001,ME002
	UNION ALL
	SELECT LA001,SUM(LA011) AS LA011,ME001,ME002
	FROM ZJRD..INVLA
		LEFT OUTER JOIN ZJRD..MOCTC ON TC001 = LA006 AND TC002 = LA007
	LEFT OUTER JOIN ZJRD..CMSMD ON MD001 = TC005 
	LEFT OUTER JOIN ZJRD..CMSME ON MD015 = ME001
	WHERE LEFT(LA006,2) = '56' AND LA004 BETWEEN '20251001' AND '20251031'
	GROUP BY LA001,ME001,ME002
	UNION ALL
	SELECT LA001,SUM(LA011) AS LA011,ME001,ME002
	FROM AHRD..INVLA
		LEFT OUTER JOIN AHRD..MOCTC ON TC001 = LA006 AND TC002 = LA007
	LEFT OUTER JOIN AHRD..CMSMD ON MD001 = TC005 
	LEFT OUTER JOIN AHRD..CMSME ON MD015 = ME001
	WHERE LEFT(LA006,2) = '56' AND LA004 BETWEEN '20251001' AND '20251031'
	GROUP BY LA001,ME001,ME002
	UNION ALL
	SELECT LA001,SUM(LA011) AS LA011,ME001,ME002
	FROM YNRD..INVLA
		LEFT OUTER JOIN YNRD..MOCTC ON TC001 = LA006 AND TC002 = LA007
	LEFT OUTER JOIN YNRD..CMSMD ON MD001 = TC005 
	LEFT OUTER JOIN YNRD..CMSME ON MD015 = ME001
	WHERE LEFT(LA006,2) = '56' AND LA004 BETWEEN '20251001' AND '20251031'
	GROUP BY LA001,ME001,ME002
) AS INVR ON INVR.LA001 = ITEM.ITEMNO AND LEFT(INVR.ME002,4) = LEFT(INVI.ME002,4)
INNER JOIN SDRD..INVMB ON MB001 = ITEM.ITEMNO

--GROUP BY ITEMNO,MB002,MB003,LEFT(INVI.ME002,4)
ORDER BY ITEMNO
