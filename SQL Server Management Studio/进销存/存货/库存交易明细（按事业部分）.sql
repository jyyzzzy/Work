		LEFT OUTER JOIN YNRD..MOCTC ON TC001 = LA006 AND TC002 = LA007
	LEFT OUTER JOIN YNRD..CMSMD ON MD001 = TC005 
	LEFT OUTER JOIN YNRD..CMSME ON MD015 = ME001
