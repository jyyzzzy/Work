;WITH ITEM AS (
    SELECT DISTINCT ITEMNO
    FROM LSSJ..ITEMTMP
),
INV AS (
    SELECT LA001, LA006, LA011
    FROM SDRD..INVLA
    WHERE LA004 BETWEEN '20260101' AND '20260531'
      AND LEFT(LA006, 2) IN ('54', '56')

    UNION ALL

    SELECT LA001, LA006, LA011
    FROM ZJRD..INVLA
    WHERE LA004 BETWEEN '20260101' AND '20260531'
      AND LEFT(LA006, 2) IN ('54', '56')

    UNION ALL

    SELECT LA001, LA006, LA011
    FROM AHRD..INVLA
    WHERE LA004 BETWEEN '20260101' AND '20260531'
      AND LEFT(LA006, 2) IN ('54', '56')

    UNION ALL

    SELECT LA001, LA006, LA011
    FROM YNRD..INVLA
    WHERE LA004 BETWEEN '20260101' AND '20260531'
      AND LEFT(LA006, 2) IN ('54', '56')
),
SUM_INV AS (
    SELECT
        LA001 AS ITEMNO,
        SUM(CASE WHEN LEFT(LA006, 2) = '54' THEN LA011 ELSE 0 END) AS 总领料数量,
        SUM(CASE WHEN LEFT(LA006, 2) = '56' THEN LA011 ELSE 0 END) AS 总退料数量
    FROM INV
    GROUP BY LA001
)
SELECT
    ITEM.ITEMNO AS 品号,
    MB.MB002 AS 品名,
    MB.MB003 AS 规格,
    --ISNULL(SUM_INV.总领料数量, 0) AS 总领料数量,
    --ISNULL(SUM_INV.总退料数量, 0) AS 总退料数量,
    ISNULL(SUM_INV.总领料数量, 0) - ISNULL(SUM_INV.总退料数量, 0) AS 领料数量
FROM ITEM
LEFT JOIN SUM_INV
    ON SUM_INV.ITEMNO = ITEM.ITEMNO
INNER JOIN SDRD..INVMB MB
    ON MB.MB001 = ITEM.ITEMNO
ORDER BY ITEM.ITEMNO;