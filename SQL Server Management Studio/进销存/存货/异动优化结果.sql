SET NOCOUNT ON;

DECLARE @dt char(8) = CONVERT(char(6), DATEADD(MONTH,-25, GETDATE()), 112) + '01';

-- 1) 先确定成品物料集合，后续一切仅围绕这些料号，显著降维
SELECT MB001
INTO #MBList
FROM SDRD..INVMB
WHERE MB109='Y'
  AND LEFT(MB001,2) <> 'LS'
  AND MB001 NOT LIKE 'P%';

CREATE UNIQUE CLUSTERED INDEX IX_MBList ON #MBList(MB001);

-- 2) 汇总所有异动到一张轻量临时表（不再跨库 JOIN INVMB，仅用 #MBList 过滤）
CREATE TABLE #U(
  DocType  varchar(10)  NOT NULL,
  DocNo    varchar(20)  NOT NULL,
  DocDate8 char(8)      NOT NULL, -- yyyymmdd，可直接用于排序与比较
  Item     varchar(40)  NOT NULL,
  Qty      decimal(18,6) NOT NULL
);

-- MO：生产相关
INSERT #U(DocType,DocNo,DocDate8,Item,Qty)
SELECT TE001,TE002,TC003,TE004,TE005
FROM SDRD..MOCTC C
JOIN SDRD..MOCTE E ON C.TC001=E.TE001 AND C.TC002=E.TE002
JOIN #MBList L     ON E.TE004=L.MB001
WHERE C.TC003>=@dt AND TE005<>0
UNION ALL
SELECT TE001,TE002,TC003,TE004,TE005
FROM ZJRD..MOCTC C
JOIN ZJRD..MOCTE E ON C.TC001=E.TE001 AND C.TC002=E.TE002
JOIN #MBList L     ON E.TE004=L.MB001
WHERE C.TC003>=@dt AND TE005<>0
UNION ALL
SELECT TE001,TE002,TC003,TE004,TE005
FROM AHRD..MOCTC C
JOIN AHRD..MOCTE E ON C.TC001=E.TE001 AND C.TC002=E.TE002
JOIN #MBList L     ON E.TE004=L.MB001
WHERE C.TC003>=@dt AND TE005<>0;

-- CO：销售出货
INSERT #U(DocType,DocNo,DocDate8,Item,Qty)
SELECT TG001,TG002,TG003,TH004,TH008
FROM SDRD..COPTG G
JOIN SDRD..COPTH H ON G.TG001=H.TH001 AND G.TG002=H.TH002
JOIN #MBList L     ON H.TH004=L.MB001
WHERE G.TG003>=@dt AND TH008<>0
UNION ALL
SELECT TG001,TG002,TG003,TH004,TH008
FROM ZJRD..COPTG G
JOIN ZJRD..COPTH H ON G.TG001=H.TH001 AND G.TG002=H.TH002
JOIN #MBList L     ON H.TH004=L.MB001
WHERE G.TG003>=@dt AND TH008<>0
UNION ALL
SELECT TG001,TG002,TG003,TH004,TH008
FROM AHRD..COPTG G
JOIN AHRD..COPTH H ON G.TG001=H.TH001 AND G.TG002=H.TH002
JOIN #MBList L     ON H.TH004=L.MB001
WHERE G.TG003>=@dt AND TH008<>0;

-- IV：库存异动（领退料/调拨等）
INSERT #U(DocType,DocNo,DocDate8,Item,Qty)
SELECT TB001,TB002,TA003,TB004,TB007
FROM SDRD..INVTA A
JOIN SDRD..INVTB B ON A.TA001=B.TB001 AND A.TA002=B.TB002
JOIN #MBList L     ON B.TB004=L.MB001
WHERE A.TA003>=@dt AND TB007<>0
UNION ALL
SELECT TB001,TB002,TA003,TB004,TB007
FROM ZJRD..INVTA A
JOIN ZJRD..INVTB B ON A.TA001=B.TB001 AND A.TA002=B.TB002
JOIN #MBList L     ON B.TB004=L.MB001
WHERE A.TA003>=@dt AND TB007<>0
UNION ALL
SELECT TB001,TB002,TA003,TB004,TB007
FROM AHRD..INVTA A
JOIN AHRD..INVTB B ON A.TA001=B.TB001 AND A.TA002=B.TB002
JOIN #MBList L     ON B.TB004=L.MB001
WHERE A.TA003>=@dt AND TB007<>0;

-- 为“按料号取最新一笔”建立覆盖索引，避免全表排序或窗口函数回表
CREATE CLUSTERED INDEX IX_U ON #U(Item, DocDate8 DESC, DocType DESC, DocNo DESC);

-- 3) 逐料号取最后一笔（按 DocDate8、DocType、DocNo 降序）
SELECT L.MB001      AS TE004,
       U.DocDate8   AS TC003,
       U.Qty        AS TE005,
       U.DocType    AS TE001,
       U.DocNo      AS TE002
INTO #MOC
FROM #MBList L
OUTER APPLY (
  SELECT TOP(1) DocType,DocNo,DocDate8,Qty
  FROM #U U
  WHERE U.Item = L.MB001
  ORDER BY U.DocDate8 DESC, U.DocType DESC, U.DocNo DESC
) U;

CREATE UNIQUE CLUSTERED INDEX IX_MOC ON #MOC(TE004);

-- 4) 库存汇总（同样用 #MBList 限定，减少分组规模）
SELECT MC001, SUM(MC007) AS MC007
INTO #INVMC
FROM (
  SELECT I.MC001, I.MC007
  FROM SDRD..INVMC I
  JOIN SDRD..CMSMC S ON I.MC002=S.MC001
  JOIN #MBList  L ON I.MC001=L.MB001
  WHERE I.MC007>0 AND S.UDF01 NOT LIKE N'%不良品'
  UNION ALL
  SELECT I.MC001, I.MC007
  FROM ZJRD..INVMC I
  JOIN ZJRD..CMSMC S ON I.MC002=S.MC001
  JOIN #MBList  L ON I.MC001=L.MB001
  WHERE I.MC007>0 AND S.UDF01 NOT LIKE N'%不良品'
  UNION ALL
  SELECT I.MC001, I.MC007
  FROM AHRD..INVMC I
  JOIN AHRD..CMSMC S ON I.MC002=S.MC001
  JOIN #MBList  L ON I.MC001=L.MB001
  WHERE I.MC007>0 AND S.UDF01 NOT LIKE N'%不良品'
) T
GROUP BY MC001;

CREATE UNIQUE CLUSTERED INDEX IX_INVMC ON #INVMC(MC001);

-- 5) 创建人员缓存
SELECT DISTINCT MV001,MV002
INTO #CMSMV
FROM (
  SELECT MV001,MV002 FROM SDRD..CMSMV
  UNION ALL
  SELECT MV001,MV002 FROM ZJRD..CMSMV
  UNION ALL
  SELECT MV001,MV002 FROM AHRD..CMSMV
) X;

CREATE INDEX IX_CMSMV ON #CMSMV(MV001);

-- 6) 主查询（维持 TOP，避免过多 IO；Fn_GetBOMUpIDs 如重则考虑预计算）
SELECT TOP 100000
  RTRIM(MB.MB001)                            AS 品号,
  RTRIM(MB.MB002)                            AS 品名,
  RTRIM(MB.MB003)                            AS 规格,
  RTRIM(MB.MB004)                            AS 单位,
  ISNULL(MC.MC007,0)                         AS 库存,
  ISNULL((SELECT COUNT(*) FROM SDRD.dbo.Fn_GetBOMUpIDs(MB.MB001) B WHERE LEFT(B.MD01,1) IN ('A','1')),0) AS 成品数量,
  ISNULL(MB.UDF05,'')                        AS 采购选型,
  ISNULL(MOC.TC003,'')                       AS 最后交易日,
  ISNULL(MOC.TE005,0)                        AS 最后交易数量,
  LEFT(MB.CREATE_DATE,8)                     AS 物料创建时间,
  RTRIM(MB.CREATOR)+RTRIM(ISNULL(MV.MV002,'')) AS 物料创建人,
  MB.MB109                                   AS 核准状况,
  ISNULL(MOC.TE001,'')                       AS 单别,
  ISNULL(MOC.TE002,'')                       AS 单号,
  'N'                                        AS 有代管库存
FROM SDRD..INVMB MB
JOIN #MBList L  ON L.MB001 = MB.MB001
LEFT JOIN #MOC  MOC ON MOC.TE004 = MB.MB001
LEFT JOIN #INVMC MC  ON MC.MC001 = MB.MB001
LEFT JOIN #CMSMV MV  ON MV.MV001 = MB.CREATOR
ORDER BY MB.MB001
OPTION (RECOMPILE);  -- 避免参数嗅探引起的坏计划

DROP TABLE #MOC;
DROP TABLE #INVMC;
DROP TABLE #CMSMV;
DROP TABLE #U;
DROP TABLE #MBList;
