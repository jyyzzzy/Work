USE ZJRD;
SELECT 
	LA001 AS 品号,
	MB002 AS 品名,
	MB003 AS 规格,
	LA004 AS 日期,
	LA005 AS 出入别,
	LA006 AS 单别,
	LA007 AS 单号,
	LA008 AS 序号,
	LA009 AS 仓库,
	LA011 AS 单据交易数量
FROM
	INVLA 
	INNER JOIN INVMB ON MB001 = LA001
WHERE 
	LA004 BETWEEN '20240701' AND '20251231'
	AND CHARINDEX('烧录',MB003)>0
	AND LEFT(LA006,1) = '5'
	ORDER BY LA004