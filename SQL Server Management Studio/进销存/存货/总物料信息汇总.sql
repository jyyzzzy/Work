SELECT MB001,
       CREATE_DATE,
       CREATOR
FROM (
    SELECT 
        MB001,
        CREATE_DATE,
        CREATOR,
        ROW_NUMBER() OVER(
            PARTITION BY MB001
            ORDER BY CASE WHEN CREATE_DATE IS NULL THEN 1 ELSE 0 END,
                     CREATE_DATE ASC
        ) AS RN
    FROM (
        SELECT MB001, CREATE_DATE, CREATOR FROM SDRD..INVMB WHERE MB109 = 'Y'
        UNION ALL
        SELECT MB001, CREATE_DATE, CREATOR FROM ZJRD..INVMB WHERE MB109 = 'Y'
        UNION ALL
        SELECT MB001, CREATE_DATE, CREATOR FROM AHRD..INVMB WHERE MB109 = 'Y'
        UNION ALL
        SELECT MB001, CREATE_DATE, CREATOR FROM YNRD..INVMB WHERE MB109 = 'Y'
        UNION ALL
        SELECT MB001, CREATE_DATE, CREATOR FROM RWDZ..INVMB WHERE MB109 = 'Y'
    ) AS INVMB
) AS T
WHERE RN = 1 AND LEFT(T.MB001,2)<>'LS' AND LEFT(T.MB001,1)<>'P'
ORDER BY MB001;