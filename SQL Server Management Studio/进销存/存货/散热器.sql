SELECT LA001 品号,MB002 品名,MB003 规格,LA004 日期,LA006 单别,LA007 单号,LA008 序号,LA009 仓库编号,MC002 仓库名称,-1*LA005*LA011 交易数量,INVLA.UDF06 部门信息
FROM INVLA
INNER JOIN INVMB ON MB001 = LA001 
LEFT OUTER JOIN CMSMC ON MC001 = LA009
WHERE 
LA004 BETWEEN '20241025' AND '20251025'
AND MB002 = '散热器'
AND (
	EXISTS(
		SELECT 1 FROM CMSMD INNER JOIN CMSME ON MD015 = ME001 WHERE CHARINDEX('三部',ME002) > 0 AND CHARINDEX(LTRIM(RTRIM(MD001)),INVLA.UDF06) > 0
	) OR CHARINDEX('三部',INVLA.UDF06) > 0 
)
ORDER BY LA004,LA006,LA007,LA008

