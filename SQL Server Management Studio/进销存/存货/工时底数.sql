SELECT 
	SD.MB001 AS 品号,
	SD.MB002 AS 品名,
	SD.MB003 AS 规格,
	SD.MB004 AS 库存单位,
	SD.MB096 AS 工时底数
FROM SDRD..INVMB AS SD
WHERE 
	SD.MB109 = 'Y'
ORDER BY SD.MB001


