SELECT TOP 10000000
			INVMA.MA002 AS MA002,--类别编号
			INVMA.MA003 AS MA003,--类别名称
			INVMA.MA004 AS MA004,--会计科目
			MB001,--品号
			MB002,--品名
			MB003,--规格
			MB004,--单位
			MB072,--小单位
			MB090,--包装单位
			MB057,--单位标准材料成本
			MB058,--单位标准人工成本
			MB059,--单位标准制造费用
			MB060,--单位标准加工费用
			MD003,--换算率分子
			MD004,--换算率分母
			A.MA003 AS MA003C,--品号类别名称
			MF004,--交易单别
			MF005,--交易单号
			CASE--分类方式
				WHEN INVMA.MA001 = '1' THEN INVMB.MB005 --会计
				WHEN INVMA.MA001 = '2' THEN INVMB.MB006 --仓管
				WHEN INVMA.MA001 = '3' THEN INVMB.MB007 --商品
				WHEN INVMA.MA001 = '4' THEN INVMB.MB008 --生管
			END AS CATEGORY, --类别
			FLOOR(ABS(ISNULL(LC004, 0))) * SIGN(ISNULL(LC004, 0)) +--月初数量
			SUM(ISNULL(INVLA.LA005 * FLOOR(ABS(INVLA.LA011)) * SIGN(INVLA.LA011), 0)) AS INVNUMA,--本月数量 总整数
			--月初数量*符号+本月数量*符号
			ISNULL(LC004, 0) - FLOOR(ABS(ISNULL(LC004, 0))) * SIGN(ISNULL(LC004, 0)) +
			SUM(ISNULL(INVLA.LA005 * ( INVLA.LA011 - FLOOR(ABS(INVLA.LA011)) * SIGN(INVLA.LA011) ), 0)) AS INVNUMB,--总整数
			--(月初数量-月初整数)+(本月数量-本月整数)
			( ISNULL(LC030, 0) + SUM(ISNULL(INVLA.LA021, 0) * ISNULL(INVLA.LA005, 0)) ) AS QUANTYPACK,--总包装
			--月初包装数量+本月包装数量
			( ISNULL(LC005, 0) + SUM(ISNULL(INVLA.LA013, 0) * ISNULL(INVLA.LA005, 0)) ) AS INVMONEY,
			--
			I.MC002 AS MC002,--仓库编号
			C.MC002 AS MC002C,--仓库编号

			SUM(ISNULL(INVLA.LA005 * FLOOR(ABS(INVLA.LA011)) * SIGN(INVLA.LA011), 0)) AS INVNUMAH,
			( SUM(ISNULL(INVLA.LA013, 0) * ISNULL(INVLA.LA005, 0)) ) AS INVMONEYH,
			FLOOR(ABS(ISNULL(LC004, 0))) * SIGN(ISNULL(LC004, 0)) AS INVNUMAQ,
			( ISNULL(LC005, 0) ) AS INVMONEYQ
			FROM
				INVMC I WITH (NOLOCK)
					LEFT JOIN INVMB AS INVMB WITH (NOLOCK)
						ON MB001 = I.MC001
					LEFT JOIN INVLC AS INVLC WITH (NOLOCK)
						ON LC001 = I.MC001 AND LC002 = '+@month+' AND LC003 = I.MC002 --取前三个月数据
					LEFT JOIN INVLA AS INVLA WITH (NOLOCK)
						ON LA001 = I.MC001 AND LA009 = I.MC002 AND
						   ( LA004 BETWEEN '20251101 ' AND '20251130' )
					LEFT JOIN CMSMC C WITH (NOLOCK)
						ON C.MC001 = I.MC002
					LEFT JOIN INVMA AS INVMA
						ON MA001 = '1' AND MA002=MB005
					LEFT JOIN ACTMA A ON A.MA001 =INVMA.MA004
 					LEFT JOIN CMSMF AS CMSMF WITH ( NOLOCK ) ON MF001='RMB'
 					LEFT JOIN INVMD AS INVMD WITH ( NOLOCK ) ON MD001=MB001 AND MD002=MB072
	WHERE
		1=1
		AND (
		1=1)
		AND C.MC004='1'
	GROUP BY
		INVMA.MA002,
		INVMA.MA003,
		INVMA.MA004,
		MB001,
		MB002,
		MB003,
		MB004,
		MB072,
		MB090,
		MB057,
		MB058,
		MB059,
		MB060,
		A.MA003,
		MF004,
		MF005,
		MD003,
		MD004,
		CASE
			WHEN INVMA.MA001='1' THEN INVMB.MB005
               WHEN INVMA.MA001='2' THEN INVMB.MB006
               WHEN INVMA.MA001='3' THEN INVMB.MB007
               WHEN INVMA.MA001='4' THEN INVMB.MB008
		END,
		LC004,
		LC005,
LC030,
I.MC002,
C.MC002
HAVING 
    1=1
    AND
    (
        (FLOOR(ABS(ISNULL(LC004,0)))*SIGN(ISNULL(LC004,0))+SUM(ISNULL(INVLA.LA005*FLOOR(ABS(INVLA.LA011))*SIGN(INVLA.LA011),0))<>0
            OR 
		        ISNULL(LC004,0) - FLOOR(ABS(ISNULL(LC004,0)))*SIGN(ISNULL(LC004,0))+SUM(ISNULL(INVLA.LA005*(INVLA.LA011-FLOOR(ABS(INVLA.LA011))*SIGN(INVLA.LA011)),0))<>0) 
            OR   
                (ISNULL(LC030,0) + SUM(ISNULL(INVLA.LA021,0)*ISNULL(INVLA.LA005,0)))<>0
            OR   
                (ISNULL(LC005,0) + SUM(ISNULL(INVLA.LA013,0)*ISNULL(INVLA.LA005,0)))<>0
         )   
ORDER BY  MA002,MB001,MC002