SELECT DISTINCT 
ITEMNO 材料品号, 
TB012 材料品名,
TB013 材料规格,
TD004 产品品号,
TD005 产品品名,
TD006 产品规格,
ISNULL(TOLTAL.orderQuantity,0) 订单总数量,
ISNULL(TOLTAL.deliveredQuantity,0) 已交总数量
FROM LSSJ..ITEMTMP AS I 
LEFT OUTER JOIN MOCTB ON TB003 = I.ITEMNO
LEFT OUTER JOIN MOCTA ON TA001 = TB001 AND TA002 = TB002
LEFT OUTER JOIN COPTD ON TD001 = TA026 AND TD002 = TA027 AND TD003 = TA028
LEFT OUTER JOIN (
	SELECT 
	TD004 productNo,
	SUM(TD008) AS orderQuantity,
	SUM(TD009) AS deliveredQuantity
	FROM COPTD
	INNER JOIN COPTC ON TC001 = TD001 AND TC002 = TD002 
	WHERE TC003 BETWEEN '20250101' AND '20251231' 
	AND TD021 = 'Y' AND TC027 = 'Y'
	GROUP BY TD004
) TOLTAL ON COPTD.TD004 = productNo
--WHERE LEFT(TA006,1) IN ('1','A')
GROUP BY ITEMNO, 
TB012,
TB013,
TD004,
TD005,
TD006,
TOLTAL.orderQuantity,
TOLTAL.deliveredQuantity
ORDER BY ITEMNO, TD004


