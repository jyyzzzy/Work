SELECT TD004,SUM(TD008)
FROM COPTD
INNER JOIN COPTC ON TC001 = TD001 AND TC002 = TD002
WHERE 
TC003 BETWEEN '20240101'AND  '20241231'
AND TD004 IN('137703640000',
    '166702350000',
    '171701450000',
    '1H3700430000',
    '1H3700500000')
AND TD021 = 'Y'
GROUP BY TD004



SELECT  M.TA021,
        MD.MD002,
        SUM(D.TD008) AS TD008_SUM
FROM COPTD D
JOIN COPTC C
  ON C.TC001 = D.TD001
 AND C.TC002 = D.TD002
JOIN (
    SELECT DISTINCT TA026, TA027, TA028, TA021
    FROM MOCTA
) M
  ON M.TA026 = D.TD001
 AND M.TA027 = D.TD002
 AND M.TA028 = D.TD003
LEFT JOIN CMSMD MD
  ON MD.MD001 = M.TA021
WHERE C.TC003 BETWEEN '20250101' AND '20251231'
  AND D.TD004 = '1H3700500000'
  AND D.TD021 = 'Y'
GROUP BY M.TA021, MD.MD002;

