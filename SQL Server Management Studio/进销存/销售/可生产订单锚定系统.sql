SELECT
	TC001 + '-' + TC002 AS [单别+单号],
	MOCTA.TA001 + '-' + MOCTA.TA002 AS 工单号,
	WORKCMSME.ME002 AS 事业部,
	COPTD.UDF04 AS 客户需求交期,
	CONVERT(CHAR(8), ASD.classes_start_time, 112) AS 事业部排产日期,
	IIF(TD008 > TD009, N'否', N'是') AS [订单状态（是否已完成生产）],
	INVMA.MA003 AS 产品大类,
	CMSMQ.MQ002 AS 订单类别,
	WORKCMSME.ME002 AS 事业部,
	TD001 AS 订单单别,
	COPTC.TC039 AS 单据日期,
	COPTC.TC003 AS 核准日期,
	TD002 AS 订单单号,
	COPTD.UDF05 AS 交货日期,
	COPMA.MA002 AS 客户简称,
	COPTD.TD004 AS 品号,
	COPTD.TD005 AS 品名,
	COPTD.TD006 AS 产品型号,
	COPTD.TD008 AS 订单数量,
	COPTD.TD011 AS 单价,
	COPTD.TD012 AS 金额,
	SALESCMSME.ME002 AS 部门,
	CMSMV.MV002 AS 业务员,
	COPTD.UDF01 AS PC交期,
	COPTD.UDF02 AS MC交期,
	COPTD.UDF03 AS 采购交期,
	COPTD.TD013 AS 预交货日,
	COPTD.UDF04 AS 客户原始交期,
	'' AS 可生产订单月份,
	'' AS 第一调整后月份,
	'' AS 第二调整后月份,
	'' AS 第三次调整后月份,
	OP.变更备注 AS 调整原因,
	'' AS 有无单据,
	'' AS 调整类型,
	'' AS 变更通知日,
	HR.lastname AS 通知人,
	'' AS 本月最终交期,
	'' AS 调整情况,
	'' AS 取消金额,
	OP.zj AS 总监,
	'' AS 事业部是否调整,
	'' AS 营销是否调整,
	'' AS 补录部门,
	COPTC.TC012 AS 客户单号,
	'' AS 备料原因分类,
	'' AS 备料原因,
	'' AS [PMC意见-变更单],
	'' AS 辅助列,
	'' AS 订单初始数量,
	'' AS 订单初始金额,
	'' AS 当月日期,
	DATEDIFF(
			DAY,
			CASE
				WHEN LEN(LTRIM(RTRIM(COPTD.TD013))) = 8 AND COPTD.TD013 NOT LIKE '%[^0-9]%'
					THEN CONVERT(DATE, LTRIM(RTRIM(COPTD.TD013)), 112) END,
			CASE
				WHEN LEN(LTRIM(RTRIM(COPTD.UDF05))) = 8 AND COPTD.UDF05 NOT LIKE '%[^0-9]%'
					THEN CONVERT(DATE, LTRIM(RTRIM(COPTD.UDF05)), 112) 
				WHEN LEN(LTRIM(RTRIM(COPTD.UDF05))) = 10 AND COPTD.UDF05 LIKE '[12][0-9][0-9][0-9]-[01][0-9]-[0-3][0-9]'
					THEN CONVERT(DATE, LTRIM(RTRIM(COPTD.UDF05)), 23)
				END
	) AS [超期天数],
	CASE
		WHEN LEN(LTRIM(RTRIM(COPTD.TD013))) = 8
			AND LEN(LTRIM(RTRIM(COPTD.UDF05))) = 8
			AND CONVERT(DATE, LTRIM(RTRIM(COPTD.UDF05)), 112) <= CONVERT(DATE, LTRIM(RTRIM(COPTD.TD013)), 112)
			THEN 'FALSE'
		WHEN LEN(LTRIM(RTRIM(COPTD.TD013))) = 8
			AND LEN(LTRIM(RTRIM(COPTD.UDF05))) = 10
			AND CONVERT(DATE, LTRIM(RTRIM(COPTD.UDF05)), 23) <= CONVERT(DATE, LTRIM(RTRIM(COPTD.TD013)), 112)
			THEN 'FALSE'
		ELSE 'TRUE'
		END
		AS [是否超期],
	'' AS 超期订单跟进,
	COPMA.MA002 AS 关联方,
	COPTD.TD011 AS 系统单价
	FROM
		SDRD..COPTD
			LEFT OUTER JOIN
			(
				SELECT *,
					ROW_NUMBER() OVER (PARTITION BY REQ_NUMBER ORDER BY classes_start_time DESC) AS rn
					FROM
						RDSJK.dbo.APS_ShedulDetails
			)
				AS ASD
					ON ASD.REQ_NUMBER = TD001+ '-' + TD002 AND
					   ASD.rn = 1
			LEFT OUTER JOIN SDRD..COPTC
				ON
			TC001 = TD001 AND TC002 = TD002--客户订单信息
			LEFT OUTER JOIN COPMA ON MA001 = TC004
			LEFT OUTER JOIN master.[dbo].Order_Pool AS OP --订单池
				ON
			TD001 = dddb COLLATE Chinese_PRC_BIN AND TD002 = dddh COLLATE Chinese_PRC_BIN
			AND TD003 = CONVERT(char(4), RIGHT('0000' + CONVERT(varchar(19), OP.rn), 4))
				AND OP.erpdyztm = 'SDRD'
			LEFT OUTER JOIN master.[dbo].HrmResource AS HR
				ON HR.id = OP.bgr--变更人信息
				AND TD003 = CAST(RIGHT('0000' + CONVERT(VARCHAR(20), OP.rn), 4) AS CHAR(4))
			LEFT OUTER JOIN SDRD..MOCTA
				ON MOCTA.TA026 = COPTC.TC001 AND MOCTA.TA027 = COPTC.TC002--工单信息
			LEFT OUTER JOIN SDRD..CMSME AS SALESCMSME
				ON SALESCMSME.ME001 = COPTC.TC005--营销部门信息
			LEFT OUTER JOIN SDRD..INVMB
				ON INVMB.MB001 = COPTD.TD004 COLLATE Chinese_PRC_BIN--品号信息
			LEFT OUTER JOIN SDRD..INVMA
				ON INVMA.MA002 = INVMB.MB007--品号类别
			LEFT OUTER JOIN SDRD..CMSMQ
				ON CMSMQ.MQ001 = COPTC.TC001 COLLATE Chinese_PRC_BIN--系统单据性质
			LEFT OUTER JOIN SDRD..CMSMD
				ON CMSMD.MD001 = MOCTA.TA021--工单工作中心信息
			LEFT OUTER JOIN SDRD..CMSME AS WORKCMSME
				ON WORKCMSME.ME001 = CMSMD.MD015 --工单部门信息
			LEFT OUTER JOIN SDRD..CMSMV
				ON CMSMV.MV001 = COPTC.TC006
WHERE COPTD.TD008 > COPTD.TD009 AND COPTC.TC027 = 'Y'
ORDER BY TC001 + '-' + TC002
