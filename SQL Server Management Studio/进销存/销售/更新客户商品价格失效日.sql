/******修改单价为长期有效*****/--2025/9/29 BY ZIYANG ZHANG

SELECT TOP (0) MB001, MB002, MB017, MB018
INTO #COPMB_KEYS
FROM COPMB;


--="INSERT INTO #COPMB_KEYS (MB001, MB002, MB017, MB018) VALUES ('"&&"','"&&"','"&&"','"&&"');"





SELECT * FROM #COPMB_KEYS

UPDATE A SET A.MB018 = '' ,A.MB012 = '单价长期有效'
FROM COPMB AS A
INNER JOIN #COPMB_KEYS AS CK 
ON
A.MB001 = CK.MB001
AND A.MB002 = CK.MB002
AND A.MB017 = CK.MB017
AND A.MB018 = CK.MB018

DROP TABLE #COPMB_KEYS