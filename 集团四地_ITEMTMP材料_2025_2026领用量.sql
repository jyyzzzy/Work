-- 0. 材料范围：只取 LSSJ..ITEMTMP.ITEMNO，排除空值并去重。
-- 使用当前账套的默认排序规则，避免跨库 JOIN 时发生排序规则冲突。
SELECT DISTINCT
    LTRIM(RTRIM(T.ITEMNO)) COLLATE DATABASE_DEFAULT AS 品号
INTO #MATERIAL
FROM LSSJ.dbo.ITEMTMP T WITH(NOLOCK)
WHERE T.ITEMNO IS NOT NULL
  AND LTRIM(RTRIM(T.ITEMNO)) <> '';

CREATE UNIQUE CLUSTERED INDEX IX_MATERIAL ON #MATERIAL (品号);

