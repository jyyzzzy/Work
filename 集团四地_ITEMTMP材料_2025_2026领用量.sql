-- 2. 集团合并；历史“事业二部/事业三部”统一归为“事业二三部”。
SELECT
    I.品号,
    I.产品品号,
    CASE WHEN I.事业部 IN (N'事业二部', N'事业三部')
         THEN N'事业二三部' ELSE I.事业部 END AS 事业部,
    SUM(I.领用数量25) AS 领用数量25,
    SUM(I.领用数量26) AS 领用数量26
INTO #ISSUE_SUM
FROM #ISSUE I
GROUP BY
    I.品号,
    I.产品品号,
    CASE WHEN I.事业部 IN (N'事业二部', N'事业三部')
         THEN N'事业二三部' ELSE I.事业部 END;

CREATE CLUSTERED INDEX IX_ISSUE_SUM ON #ISSUE_SUM (品号, 产品品号, 事业部);

-- 3. 仅查询报表涉及的品号名称、规格。优先 SDRD，其次 ZJRD/AHRD/YNRD。
SELECT K.品号
INTO #NEEDED_ITEM
FROM
(
    SELECT 品号 FROM #ISSUE_SUM
    UNION
    SELECT 产品品号 FROM #ISSUE_SUM
) K;

CREATE UNIQUE CLUSTERED INDEX IX_NEEDED_ITEM ON #NEEDED_ITEM (品号);

CREATE TABLE #ITEM_INFO
(
    品号 NVARCHAR(40) COLLATE DATABASE_DEFAULT NOT NULL PRIMARY KEY,
    品名 NVARCHAR(255) NULL,
    规格 NVARCHAR(1000) NULL
);

INSERT INTO #ITEM_INFO (品号, 品名, 规格)
