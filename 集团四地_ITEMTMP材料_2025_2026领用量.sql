-- 1. 分账套先汇总，避免将所有领退料明细直接合并后再聚合。
-- SDRD：领料(54) - 退料(56)
INSERT INTO #ISSUE (品号, 产品品号, 事业部, 领用数量25, 领用数量26)
SELECT
    RTRIM(E.TE004),
    RTRIM(A.TA006),
    CASE
        WHEN LTRIM(RTRIM(ISNULL(D.MD011, N''))) = N'' THEN N'广东瑞德'
        ELSE LTRIM(RTRIM(LEFT(D.MD011, CHARINDEX('-', D.MD011 + '-') - 1)))
    END,
    SUM(CASE WHEN C.TC003 < '20260101'
             THEN CASE WHEN E.TE001 LIKE '54%' THEN CONVERT(DECIMAL(28, 6), ISNULL(E.TE005, 0))
                       ELSE -CONVERT(DECIMAL(28, 6), ISNULL(E.TE005, 0)) END
             ELSE 0 END),
    SUM(CASE WHEN C.TC003 >= '20260101'
             THEN CASE WHEN E.TE001 LIKE '54%' THEN CONVERT(DECIMAL(28, 6), ISNULL(E.TE005, 0))
                       ELSE -CONVERT(DECIMAL(28, 6), ISNULL(E.TE005, 0)) END
             ELSE 0 END)
FROM SDRD.dbo.MOCTE E WITH(NOLOCK)
INNER JOIN #MATERIAL T ON T.品号 = E.TE004 COLLATE DATABASE_DEFAULT
INNER JOIN SDRD.dbo.MOCTC C WITH(NOLOCK)
    ON C.TC001 = E.TE001 AND C.TC002 = E.TE002
INNER JOIN SDRD.dbo.MOCTA A WITH(NOLOCK)
    ON A.TA001 = E.TE011 AND A.TA002 = E.TE012
LEFT JOIN SDRD.dbo.CMSMD D WITH(NOLOCK)
    ON D.MD001 = A.TA021
WHERE C.TC003 BETWEEN '20250101' AND '20261231'
  AND E.TE019 = 'Y'
  AND (E.TE001 LIKE '54%' OR E.TE001 LIKE '56%')
  AND ISNULL(E.TE004, '') <> ''
  AND ISNULL(A.TA006, '') <> ''
GROUP BY
    E.TE004,
    A.TA006,
    D.MD011;

