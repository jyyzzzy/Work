-- 4. 最终输出：列名、顺序与需求一致。
SELECT
    S.品号,
    ISNULL(M.品名, N'') AS 品名,
    ISNULL(M.规格, N'') AS 规格,
    S.产品品号,
    ISNULL(P.品名, N'') AS 产品品名,
    ISNULL(P.规格, N'') AS 产品规格,
    S.领用数量25 AS [25年领用数量],
    S.领用数量26 AS [26年领用量],
    S.事业部
FROM #ISSUE_SUM S
LEFT JOIN #ITEM_INFO M ON M.品号 = S.品号
LEFT JOIN #ITEM_INFO P ON P.品号 = S.产品品号
WHERE S.领用数量25 <> 0 OR S.领用数量26 <> 0
ORDER BY S.品号, S.产品品号, S.事业部;
